#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
玄武_镜.py — 镜：假世界

他摸到的是**一个货真价实的数据库**，里面装的是编的东西。假世界越真，
他留得越久。

⛔ 铁律：镜里一个真字节都不许有
==============================

计划 §六·一 那张表：

    **结构**（表名 / 列名 / 类型 / 约束）  照真库读 —— 不然他一眼看出是假的
    **数据**（每一行的每一个值）          **全部现编**
    真库的行                              ⛔ 一行都不许进

这条不是靠自觉，是**结构上就断掉的**：这个文件里唯一读到真库的地方是
`真语法.tables` —— 那是**表定义**，开库时从 `catalog` 装好的一个字典
（`syntax.py:586`、`备份.py:379` 都写着"不是一条语句"）。**它里面没有
一行值、没有一列数据**。真库的 `fetch` / `page` / `scan`，镜这一层
**一次都不调**。

抽一行真数据放进镜 = **你亲手把真数据递到他手上，还骗自己说在防他。**

镜就是第二个库
==============

霸下已经是多库的（库 = 一个根目录），所以镜不需要新写一行存储：

    <库>/玄武/镜/     ← 一个真的霸下库，真引擎、真格式、真语法层

用的是 `龙龟之心.建` / `内核.进出`，和界面开一个库是**同一条路**。
落盘、语法、主键直取，全是真的 —— 他拿 `显示 表列表`、拿 `显示 结构`
看到的都是真东西，只有值是我们编的。

⛔ 一条不得不认的结构约束：`Syntax` 的身份游标只容许一个调用者
================================================================

`syntax.py:1361` 那段自己写着：`_身份` 是个**单槽游标**，"这条做法成立的
前提只有一条：**一次只有一个调用者**"。而 3306 那条路是**一条连接一条
线程**（`mysql_门`），两个攻击者同时摸镜就是两个线程同时进同一个
`Syntax` —— 身份会互相踩。

所以镜这儿**有一把锁，而且是"等不到就拒"的锁**：

    借不到 → 回 `None` → 调用方拒掉这一手（fail-closed）

⛔ **不能等下去。** 等下去就是把"攻击者多开几条连接"变成"我们的线程
全堵在这儿"—— 那是拿他的矛攻我们的盾。宁可拒（他反正也在镜里，拒了
也是拒），也不能把自己的线程池赔进去。

镜是丢得掉的
============

计划 §六·三：他写脏了、写爆了 —— **整个目录删掉重造**。这正是
`baxia-derived-state-must-be-droppable` 的样板：镜里没有一个字节是真相，
所以随时丢得起。`复位()` 干的就是这件事。

明文、不加密，这是故意的
========================

镜那个库**不上锁**（`密文=None`）。理由：镜里一个真字节都没有，给它配
一把钥匙、一个锁标记文件，换来的只是**多几个会坏的地方**（钥匙丢了镜就
重建不了），而换来的保密是零 —— 里面的东西本来就是编来给他看的。
"""

from __future__ import annotations

import json
import os
import shutil
import threading

import 玄武_饵 as _饵

__all__ = ['镜', '造镜', '镜错', '镜标记', '镜目录']

#: 镜那个库放在库目录里的哪儿。**这个字符串只许在这儿写一遍。**
镜目录 = os.path.join('玄武', '镜')
#: 镜的标记文件（管理员、口令、这一面镜的轮次）。见 `_读标记` 那段。
镜标记 = os.path.join('玄武', '镜.json')

_版本 = 1
_管理员 = '镜'


class 镜错(Exception):
    """镜这一台自己坏了。**判的台，所以调用方一律按拒办**（fail-closed）。"""


def _引(名):
    """把表名/列名裹起来。**反引号在名字里就拒绝** —— 见 `_能引`。"""
    return '`%s`' % 名


def _能引(名):
    """这个名字能不能原样写进语句。反引号没法转义，所以一律不收。"""
    return '`' not in str(名) and str(名).strip() != ''


#: 类型号 → 建表语句里那个词（`schema.INT/FLOAT/TEXT/BLOB/TIME`）
_类型词 = {1: '整数', 2: '实数', 3: '文本', 4: '二进制', 5: '时间'}


# ══ 一、一面镜 ═════════════════════════════════════════════════════════

class 镜(object):
    """
    一个可调用（登记成 `城` 的 `镜` 那一台），同时是**镜那个库的把手**。

    参数：

        `真库路` 真库的根目录。镜建在它下面的 `玄武/镜/`。
        `真语法` 真库的语法层（鸭子类型：只要一个 `.tables` 字典）。
                 ⛔ **这是镜唯一能碰到真库的东西**，而它是结构、不是行。
        `值`     `配置.py` 那份值（`玄武用镜` / `玄武镜行数` / `玄武盐`）。
        `说`     记一句话的回调。
        `存储配置` / `上限`  建镜那个库要用的，和真库同一份
                 （`配置.存储区配置(值)` / `配置.语句上限(值)`）。
                 由装配层递进来 —— 这个文件不 import `配置`。

    作为台，它做的事只有两件：

        判词不是 `镜`    → 一个字都不动
        判词是 `镜`      → 保证镜在那儿（没有就现建），并记下这一手属于
                          哪一面镜（`手.备注`）

    **它不判词、不动答案。** 判决是 `门` 的事，"给他什么"是 `饵` 的事。
    """

    def __init__(self, 真库路, 真语法, 值=None, 说=None,
                 存储配置=None, 上限=None, 建库=None):
        值 = 值 or {}
        self._库路 = str(真库路 or '')
        self._真语法 = 真语法
        self._开 = bool(值.get('玄武用镜'))
        self._回环 = bool(值.get('玄武镜回环', True))
        try:
            # ⛔ **这一格不能用 `or`**（同 `玄武_粘滞.粘滞.__init__` 那一段）：
            # `0` 是配得出来的 —— 下限就是 0，意思是"镜照开、一行都不回"。
            # 而 `0 or 200` 是 `200`：人调成 0，盘上写着 0、界面也显示 0，
            # **这一层照旧回 200 行**。只有 `None`（没配过）才落默认值。
            数 = 值.get('玄武镜行数')
            self._行数 = max(0, int(200 if 数 is None else 数))
        except (TypeError, ValueError):
            self._行数 = 200
        #: 编假时间用的基准（毫秒）。**镜自己不用它**，只是转手递给
        #: `玄武_饵.编行` —— 编行是造行的那一个，它才是用它的。配置键
        #: `玄武饵纪元`，`None` = 照 `玄武_饵._纪元` 那个模块常量。
        try:
            self._纪元 = int(值.get('玄武饵纪元'))
        except (TypeError, ValueError):
            self._纪元 = None
        self._说 = 说 or (lambda 文: None)
        self._存储配置 = 存储配置
        self._上限 = 上限 or {}
        #: 建库那个函数。**注入进来的**，默认才去 import `龙龟之心` ——
        #: 让探针能拿一个假的把它换掉，也让这个文件在没装引擎时不炸。
        self._建库 = 建库

        self._锁 = threading.Lock()
        self._内核 = None
        self._闸 = None
        self._轮次 = ''
        self._坏过 = 0
        self._建过几面 = 0
        self._借出过几次 = 0

    # ── 路径 ────────────────────────────────────────────────────────

    @property
    def 库目录(self):
        return os.path.join(self._库路, 镜目录)

    @property
    def 标记路径(self):
        return os.path.join(self._库路, 镜标记)

    @property
    def 轮次(self):
        """这一面镜的轮次（`复位` 之后会变）。**调用方拿它做缓存键。**"""
        return self._轮次

    @property
    def 语法(self):
        """
        镜那个库的**语法层**。9099 那三扇门收的就是一份语法层（不是闸口
        —— 3306 那条路才走闸口），所以只有那一条路要用这一格。

        ⛔ **拿它的人必须自己拿 `占住()`。** 这一格只把物件递出去，一点
        保护都不带：`Syntax` 是单槽游标（"一次只有一个调用者"），两个
        调用方同时用它就串身份了。**没有 `占住()` 就一定出事。**

        ⛔ **`复位` 之后要重拿。** 复位是整面镜丢掉重造，旧的那份语法层
        指着已经关掉的库 —— 拿 `轮次` 当缓存键，别把这一份存起来。
        """
        if not self._开:
            raise 镜错('这个库没开镜（`玄武用镜` 关着）')
        self.准备好()
        return self._内核.语法层

    # ── 那一手 ──────────────────────────────────────────────────────

    def __call__(self, 手):
        """
        判词不是 `镜` 就收手。是 `镜` 就**确保镜能用**。

        ⛔ 建不起来就 `raise` —— 镜归在 `判的台` 里（`玄武_城.判的台`），
        所以这一抛会被城接住、判成 `断`。**这正是要的**：镜坏了而这一手
        又该进镜，那么"拒"是对的，"偷偷放真库"是绝不能做的那个选择。
        """
        if not self._开:
            return None
        if getattr(手, '判词', None) != '镜':
            return None
        if not self._库路:
            raise 镜错('不知道真库在哪，建不出镜')
        self.准备好()
        手.备注 = (手.备注 + '；' if 手.备注 else '') + '镜：%s' % self._轮次
        return self._轮次

    # ── 准备好 / 复位 ───────────────────────────────────────────────

    def 准备好(self):
        """镜没建好就现建。**幂等**（第二次什么都不做）。"""
        if self._闸 is not None:
            return self._闸
        with self._锁:
            if self._闸 is not None:
                return self._闸
            self._建()
            return self._闸

    def _建(self):
        """
        造一面镜：**结构照真库读，数据全部现编。**

        ⛔ 全程在 `self._锁` 里（调用方拿着），因为 `Syntax` 只容许一个
        调用者。

        三步：建库 → 照真库的结构建表 → 灌编出来的行。
        """
        建库 = self._取建库()
        标记 = self._读标记()
        if 标记 is not None:
            try:
                self._开起来(建库, 标记)
                return
            except BaseException as 错:
                # 开不开、登不进 —— **镜是丢得掉的**，删掉重造，不跟它较劲。
                self._说('[玄武] 这个镜打不开（%s），丢掉重造' % (错,))
                self._丢掉()
        self._造新的(建库)

    def _取建库(self):
        if self._建库 is not None:
            return self._建库
        import 龙龟之心            # 只在这一处 import，见模块头
        return 龙龟之心

    def _读标记(self):
        try:
            with open(self.标记路径, 'r', encoding='utf-8') as fh:
                体 = json.load(fh)
        except (OSError, ValueError):
            return None
        if not isinstance(体, dict) or 体.get('v') != _版本:
            return None
        if not os.path.isdir(self.库目录):
            return None
        return 体

    def _写标记(self, 口令, 轮次):
        os.makedirs(os.path.dirname(self.标记路径), exist_ok=True)
        体 = {'v': _版本, '管理员': _管理员, '口令': 口令, '轮次': 轮次,
              '话': '这一份是玄武的镜：里面一个真字节都没有，随便丢。'}
        with open(self.标记路径, 'w', encoding='utf-8') as fh:
            json.dump(体, fh, ensure_ascii=False)

    def _开起来(self, 建库, 标记):
        """开一个已经存在的镜。**口令不对就抛**，由 `_建` 接住丢掉重造。"""
        内核 = 建库.开(self.库目录, config=self._存储配置, **self._上限)
        闸 = 内核.进出
        谁 = 闸.登录(标记.get('管理员') or _管理员, 标记.get('口令') or '')
        if 谁 is None:
            raise 镜错('镜的管理员登不进去')
        self._装上(内核, 闸, str(标记.get('轮次') or ''))

    def _造新的(self, 建库):
        """从头造一个。**目录已经存在就先丢掉**（`arena.create` 要求空目录）。"""
        self._丢掉()
        os.makedirs(self.库目录, exist_ok=True)
        口令 = os.urandom(24).hex()
        内核 = 建库.建(self.库目录, config=self._存储配置, **self._上限)
        内核.设初始管理员(_管理员, 口令)
        闸 = 内核.进出
        if 闸.登录(_管理员, 口令) is None:
            raise 镜错('刚造出来的镜，管理员居然登不进去')
        轮次 = '%s-%s' % (os.path.basename(self._库路) or '库',
                           os.urandom(4).hex())
        # ⛔ **轮次得在灌数据之前撂上去。** 灌的时候 `_照结构灌` 拿
        # `轮次盐()` 拌进每一条假数据 —— 轮次还是空的，那每一面镜编出来
        # 的东西就一模一样，"这数据出自哪一次镜"那条水印（计划 §七·五）
        # 也就白写了。
        self._轮次 = 轮次
        表数, 行数 = self._照结构灌(闸)
        self._写标记(口令, 轮次)
        self._装上(内核, 闸, 轮次)
        self._建过几面 += 1
        self._说('[玄武] 造了一面新镜：%d 张表、%d 行编出来的数据（%s）'
                 % (表数, 行数, 轮次))

    def _装上(self, 内核, 闸, 轮次):
        self._内核 = 内核
        self._闸 = 闸
        self._轮次 = 轮次 or '镜'

    def _丢掉(self):
        """
        把镜那个库整个删掉。**这就是 §六·三 的"复位"。**

        ⛔ 只删 `玄武/镜/` 和 `玄武/镜.json` 这两样 —— 路径是拼出来的、
        **写死在本文件顶上那两个常量里**（`镜目录` / `镜标记`）。别处
        再拼一遍路径，就有删错目录的那一天。
        """
        # ⛔ **不许在这儿调 `停()`。** `停()` 自己也要 `self._锁`，而
        # `_丢掉` 的调用方（`_建` / `复位`）**正拿着那把锁** —— 普通锁不
        # 可重入，那就是当场死锁，症状是"一进镜就整个卡住"、没有异常
        # 没有日志。`玄武_门.门台.报数` 踩过同一个坑。
        内, self._内核 = self._内核, None
        self._闸 = None
        # 关 `内核` 就够：闸口是拿 `Gate.attach` 挂在同一个 `Storage` 上的，
        # 内核一停，那个库就关了。**两个都关一次是重复关库**——第二次会
        # 撞在"已经关了"上，白挨一个异常。
        if 内 is not None:
            try:
                内.停()
            except BaseException:
                pass
        shutil.rmtree(self.库目录, ignore_errors=True)
        try:
            os.remove(self.标记路径)
        except OSError:
            pass

    def 停(self):
        """
        关掉镜那个库。**关库、停城那条路上要叫一声。**

        ⛔ **不是可选的。** 镜是一个**真的霸下库**，它开着就持着那个目录
        的句柄；Windows 上被独占的目录删不掉，于是"库已经关干净了"会是
        一句假话 —— `arena.py` 里那个 `_关掉没开成的` 就是同一个坑踩出来
        的（见开发计划 §十 那条）。下次开同一个库时，这个句柄就是那个
        "删不掉的空壳"。

        **不删镜**（`停` 和 `复位` 是两件事）：下次开库接着用这一面。
        """
        with self._锁:
            内, self._内核 = self._内核, None
            self._闸 = None
            if 内 is not None:
                try:
                    内.停()
                except BaseException as 错:
                    self._说('[玄武] 镜没关干净 —— %s：%s'
                             % (type(错).__name__, 错))

    def 复位(self):
        """
        他写脏了、写爆了 —— **整面镜丢掉重造**。返回新的轮次。

        ⛔ 不删真库任何东西。被删的只有 `玄武/镜/` 那一个目录，而里面
        没有一个是真数据（这条由 `_照结构灌` 保证）。
        """
        with self._锁:
            self._丢掉()
            self._建()
            return self._轮次

    # ── 照结构灌 ────────────────────────────────────────────────────

    def _照结构灌(self, 闸):
        """
        ⛔ **镜里每一张表的每一个值都是这儿编的，没有一行来自真库。**

        读的只有 `真语法.tables` —— 表定义。那是开库时从 `catalog` 装好
        的字典，里面是列名、类型、可空、主键，**没有值**。

        回 `(建了几张表, 灌了几行)`。
        """
        表们 = getattr(self._真语法, 'tables', None) or {}
        想几行 = self._行数
        建了 = 0
        灌了 = 0
        for 名 in sorted(表们, key=lambda x: getattr(表们[x], 'table_id', 0)):
            表 = 表们[名]
            # 索引表不是给人看的表（`schema.Table.index_of`），真库里
            # `显示 表列表` 也把它们藏起来。镜里照做 —— 不然他一眼看出
            # "这库怎么比别人的多几张"。
            if getattr(表, 'index_of', None):
                continue
            列们 = self._列们(表)
            if not 列们 or not _能引(名):
                self._说('[玄武] 镜跳过了表 %r（名字或列名引不了）' % (名,))
                continue
            建 = self._建表语句(名, 列们, 表)
            if 建 is None:
                continue
            回 = 闸.send(建)
            if 回 is not None and getattr(回, 'error', None):
                self._说('[玄武] 镜建表 %r 没成：%s' % (名, 回.error))
                continue
            建了 += 1
            行们 = [_饵.编行(列们, i, 盐=self.轮次盐(名),
                             纪元=self._纪元)
                    for i in range(想几行)]
            灌 = 闸.fill(名, 行们, columns=[c[0] for c in 列们],
                         on_error='collect')
            if isinstance(灌, dict):
                灌了 += int(灌.get('ok') or 0)
                for 错 in (灌.get('errors') or [])[:3]:
                    self._说('[玄武] 镜灌 %r 有行没进去：%s' % (名, 错))
        return 建了, 灌了

    def 轮次盐(self, 表名=''):
        """编数据用的盐。**跟着轮次走** —— 换一面镜就换一批值。"""
        return '%s|%s' % (self._轮次, 表名)

    def _列们(self, 表):
        """`[(列名, 类型号, 可空, 是不是主键)]`。照真库的表定义抄。"""
        主键 = list(getattr(表, 'pk', None) or [])
        出 = []
        for 列 in getattr(表, 'columns', None) or []:
            名 = getattr(列, 'name', None)
            if 名 is None or not _能引(名):
                return []
            出.append((str(名), getattr(列, 'type', 3),
                       bool(getattr(列, 'nullable', True)), 名 in 主键))
        return 出

    def _建表语句(self, 名, 列们, 表):
        """
        拼一条建表语句。**主键、维度、可空都照抄** —— 结构不一样他一眼
        就看出来了。

        ⛔ 主键用**表级**那一种写法（`主键 (a, b)`），因为列级那种只能
        写单列主键，而真库里的主键可能是复合的（`sql.py:1040`）。
        """
        块 = []
        for 列名, 类号, 可空, _是主键 in 列们:
            词 = _类型词.get(类号)
            if 词 is None:
                self._说('[玄武] 镜认不出 %r 那一列的类型号 %r，整张表跳过'
                         % (列名, 类号))
                return None
            块.append('%s %s%s' % (_引(列名), 词, '' if 可空 else ' 非空'))
        主键 = [c[0] for c in 列们 if c[3]]
        if not 主键:
            # 本库必须有主键（`sql.py:1062`）。真库那张表有主键，走到这儿
            # 说明我们没读懂它的定义 —— **宁可不建，也不建一张假的**。
            self._说('[玄武] 镜读不出 %r 的主键，整张表跳过' % (名,))
            return None
        块.append('主键 (%s)' % ', '.join(_引(c) for c in 主键))
        维 = getattr(表, 'dim_column', None)
        if 维:
            块.append('维度 (%s)' % _引(维))
        return '建表 %s (%s)' % (_引(名), ', '.join(块))

    # ── 借出 ────────────────────────────────────────────────────────

    def 占住(self, 等=2.0):
        """
        取镜的独占权。**回一个上下文管理器**，`with` 出来的那个格子是闸口
        （借不到就是 `None`）。

            with 镜机.占住() as 闸:
                if 闸 is None: 拒掉这一手
                ...

        ⛔ **等不到就回 `None`，绝不等下去。** 理由见模块头："那是拿他的
        矛攻我们的盾"。
        """
        return _占(self, 等)

    def 闸(self):
        """镜的闸口（没建好就是 `None`）。**调用方自己负责 `占住`。**"""
        return self._闸

    # ── 状态 ────────────────────────────────────────────────────────

    def 报数(self):
        with self._锁:
            return {'开着': self._开, '建好了': self._闸 is not None,
                    '轮次': self._轮次, '库目录': self.库目录,
                    '坏过': self._坏过, '建过几面': self._建过几面,
                    '借出过几次': self._借出过几次,
                    '有人正借着': self._锁.locked()}


class _占(object):
    """`镜.占住()` 回的那个东西。**只管一把锁，别的什么都不做。**"""

    def __init__(self, 镜机, 等):
        self._镜 = 镜机
        self._等 = max(0.0, float(等 or 0.0))
        self._拿 = False

    def __enter__(self):
        self._拿 = self._镜._锁.acquire(timeout=self._等)
        if not self._拿:
            self._镜._坏过 += 1
            self._镜._说('[玄武] 镜正被别的会话占着，等不到 —— 这一手拒了')
            return None
        self._镜._借出过几次 += 1
        try:
            if self._镜._闸 is None:
                self._镜._建()
        except BaseException as 错:
            self._镜._说('[玄武] 镜没建起来 —— %s：%s'
                         % (type(错).__name__, 错))
            return None
        return self._镜._闸

    def __exit__(self, *a):
        if self._拿:
            self._拿 = False
            self._镜._锁.release()
        return False


