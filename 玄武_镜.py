def 造镜(真库路, 真语法, 值=None, 说=None, 存储配置=None, 上限=None,
         建库=None):
    """
    造一面镜，给 `城.登记('镜', …)` 用。

    读的配置键是 `玄武用镜` / `玄武镜回环` / `玄武镜行数`。

    ⚠ `玄武用镜` **默认关**：开了它就得先落盘建出那个库（几十万字节、
    上千行的假数据），而那是"人按一下才该发生"的事。开关关着的时候，
    `镜.__call__` 立刻回 `None` —— 判词是 `镜` 的手没人接，城那边
    `包闸口` 会把它拒掉（**不会偷偷改成真库**）。
    """
    return 镜(真库路, 真语法, 值=值, 说=说,
              存储配置=存储配置, 上限=上限, 建库=建库)
