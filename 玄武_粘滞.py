#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
玄武_粘滞.py — 粘：吊住隧道

**它只算一个数：`一手.延迟秒`。** 真正去 `sleep` 的不是这一台，是
`玄武_门.包闸口`（判完之后、干活之前）。这个分工是故意的：

    粘     回答"这一手该等多久"        ← 一个纯计算，不 sleep
    门那一边   真去等                    ← 只有它知道"等"发生在哪儿

理由和第 3306 那条路上的其它地方一样：**台是插在城上的，城是按次序叫台
的那一个**。让台自己 `sleep`，城就被按住了 —— 而城的次序是给**所有**台
用的，不是给这一条连接的。算和等分开，账才写得出、次序才走得动。

吊谁，不吊谁
============

判词是 `粘` 看得到的（它在 `门` 后面跑），所以规矩写得很直：

    真库      延迟 = 0        ⛔ **永远不吊合法用户。**
    断        延迟照着往上加   他已经要被拒了 —— 那就让他**等**着被拒
    镜        延迟照着往上加   让他觉得"这库就是慢"，多待一会儿

**吊一条被拒的连接，比秒拒它狠得多。** 秒拒是明确的信号："你被发现了，
换下一个"。吊着不吭声，他那边是超时、是重试、是把并发槽位占住 ——
而他的槽位是有数的（计划 §三·二：粘的"说不"的后果就是"耗他的并发槽位"）。

⛔ 但它也会占**我们**的槽位
==========================

`mysql_门` 是一条连接一条线程。**每睡一秒，就有一条线程睡在那儿。**
所以"让对手等"和"让自己被拖死"之间只隔着一条线，这条线必须画在代码里、
不能靠自觉：

1. **单次有上限** —— `玄武粘滞秒`。
2. **同时吊住的有上限** —— `玄武粘滞上限`。到顶之后**新来的延迟一律 0**，
   宁可放他一马，也不能把自己的线程扑满。**这一条是这一台里最要紧的。**
3. **梯子是封顶的** —— 一个会话越闹越久，但到 `玄武粘滞秒` 就停，不再涨。

丢得掉吗
========

丢得掉。`粘` 手里只有一张"会话号 → 闹了几次 / 吊到几秒了"的表，它
**完全能从账本推出来**（账上每一手都带着会话号和延迟），所以不落盘、
重启重新数，而且**封顶**（同 `玄武_画.画._翻账` 那条：键是攻击者刷出来的）。
"""

from __future__ import annotations

import threading

__all__ = ['粘滞', '造粘台']

#: 一个会话连着闹几手之后才开始吊。**头几手不吊** —— 头几手里的"闹"
#: 多半是正常客户端在重试（网络抖一下而已）。配置键 `玄武粘滞宽限`。
_宽限 = 2

#: 梯子：闹到第 n 手，等 `最小(上限, 基数 * 倍增**(n-宽限-1))` 秒。
#: 配置键 `玄武粘滞基数` / `玄武粘滞倍增`。
_基数 = 0.5
_倍增 = 2.0


def _正(值, 默认):
    """取一个"至少是 0 的整数"。给不出来就用默认。"""
    try:
        return max(0, int(值 if 值 is not None else 默认))
    except (TypeError, ValueError):
        return 默认


def _数(值, 默认, 下限=0.0):
    """取一个不小于 `下限` 的小数。给不出来就用默认。"""
    try:
        return max(下限, float(值 if 值 is not None else 默认))
    except (TypeError, ValueError):
        return 默认


class 粘滞(object):
    """
    算延迟的台。**一个可调用，收 `一手`，填 `一手.延迟秒`。**

    参数：

        `值`    `配置.py` 那份值。读的是 `玄武粘滞` / `玄武粘滞秒` /
                `玄武粘滞上限` 三个键。
        `说`    记一句话的回调。
        `上限笔` 那张按会话号的表最多记几笔。同 `玄武_画`。

    ⛔ **它从不写判词。** 判词是 `门` 的事；粘只往 `延迟秒` 那一格里写。
    关掉这一条（`玄武粘滞` = 假），`延迟秒` 就是 `0.0` —— 那也是**明说了
    不等**，和"没判"是两件事。
    """

    def __init__(self, 值=None, 说=None, 上限笔=4096):
        值 = 值 or {}
        self._开 = bool(值.get('玄武粘滞'))
        try:
            # ⛔ **这一格不能用 `or`。** `0.0` 是配得出来的（下限就是 0.0，
            # 意思是"粘滞照判，一秒都不等"），而 `0.0 or 5.0` 是 `5.0`：
            # 人把这一格调成 0 想关掉等待，盘上写着 0、界面回头也显示 0，
            # **只有这一层偷偷等 5 秒** —— 没有报错、没有日志，就是"改了
            # 设置不生效"。配置里配出来的 0.0 和"没配过这一格"必须分开，
            # 后者才是 `None`。
            数 = 值.get('玄武粘滞秒')
            self._最大 = max(0.0, float(5.0 if 数 is None else 数))
        except (TypeError, ValueError):
            self._最大 = 5.0
        try:
            self._上限 = max(0, int(值.get('玄武粘滞上限') or 64))
        except (TypeError, ValueError):
            self._上限 = 64
        try:
            self._上限笔 = max(64, int(上限笔 or 4096))
        except (TypeError, ValueError):
            self._上限笔 = 4096
        # ── 梯子的形状 ────────────────────────────────────────────────
        # ⛔ **属性名不带下划线，是故意的**（同 `玄武_画.画`）：模块顶上
        # 那几个常量叫 `_宽限` / `_基数` / `_倍增`，而方法体里写 `_宽限`
        # 指的是**模块那个**。属性名要是也起成 `_宽限`，`算()` 里漏改一句
        # **不报错、静默用回模块常量** —— 界面上改了、吊住的秒数没变。
        self.宽限 = _正(值.get('玄武粘滞宽限'), _宽限)
        self.基数 = _数(值.get('玄武粘滞基数'), _基数)
        self.倍增 = _数(值.get('玄武粘滞倍增'), _倍增, 下限=1.0)
        self._说 = 说 or (lambda 文: None)

        self._锁 = threading.Lock()
        #: 会话号 -> 闹到第几手了
        self._闹 = {}
        #: **此刻真有几条睡在那儿。** 这是"别把自己拖死"那个闸看的东西。
        self._吊着 = 0

    # ── 那一手 ──────────────────────────────────────────────────────

    def __call__(self, 手):
        手.延迟秒 = self.算(手)
        return 手.延迟秒

    def 算(self, 手):
        """这一手该等几秒。**纯函数（就那张表是状态），不去睡。**"""
        if not self._开 or self._最大 <= 0:
            return 0.0

        # ⛔ **真库一律不等。** 合法用户不许被这一台碰到 —— 这一条写在
        # 最前面，后面的任何条件都盖不过它。
        判 = getattr(手, '判词', None)
        if 判 not in ('断', '镜'):
            return 0.0

        号 = getattr(手, '会话号', 0)
        with self._锁:
            # ── 闸一：同时吊住的有上限 ──────────────────────────────
            #
            # 到顶了就 **0**，一个都不再吊。这一条是保护自己那边的：
            # 线程是有限的，"吊住对手"用的是同一种资源。
            if self._吊着 >= self._上限:
                return 0.0
            闹 = self._闹.get(号, 0) + 1
            if 号 not in self._闹 and len(self._闹) >= self._上限笔:
                self._闹.pop(next(iter(self._闹)), None)
            self._闹[号] = 闹

        if 闹 <= self.宽限:
            return 0.0
        # ── 闸二：梯子封顶 ──────────────────────────────────────────
        #
        # ⛔ **指数要先夹住，这不是洁癖。** `2.0 ** 20000` 在 Python 里是
        # `OverflowError`，而粘是**判的台**（fail-closed）：真抛出去，
        # 那一手就被判死了 —— 他连闹几千手就能把这个异常当开关用。
        # 夹到 64 级足够：到那儿无论基数多小都早就超过"单次最多吊多久"，
        # 下面那句 `min` 本来就会把它截掉。**夹的是指数，不是结果。**
        级 = min(64, max(0, 闹 - self.宽限 - 1))
        等 = self.基数 * (self.倍增 ** 级)
        return min(self._最大, 等)

    # ── 吊着的那一条 ────────────────────────────────────────────────

    def 进去(self):
        """
        "有一条要睡了"。**由真去睡的那一边调**（`玄武_门.包闸口`），
        并且必须配一个 `出来()`。到顶了回 `False` —— 那一边就不睡。
        """
        with self._锁:
            if self._吊着 >= self._上限:
                return False
            self._吊着 += 1
            return True

    def 出来(self):
        with self._锁:
            if self._吊着 > 0:
                self._吊着 -= 1

    # ── 状态 ────────────────────────────────────────────────────────

    def 忘掉(self, 会话号):
        """`关会话` 那条路上叫一声：这个号的了结清了。**不掉也不碍事。**"""
        with self._锁:
            self._闹.pop(会话号, None)

    def 报数(self):
        with self._锁:
            return {'开着': self._开, '单次最长秒': self._最大,
                    '同时上限': self._上限, '此刻吊着': self._吊着,
                    '宽限手数': self.宽限, '梯子基数秒': self.基数,
                    '梯子倍增': self.倍增, '会话表上限': self._上限笔,
                    '记着的会话数': len(self._闹)}


def 造粘台(值=None, 说=None):
    """
    造一台粘，给 `城.登记('粘', …)` 用。

    读的配置键全在 `配置.py`「城防·粘」那一组：`玄武粘滞` /
    `玄武粘滞秒` / `玄武粘滞上限` / `玄武粘滞宽限` / `玄武粘滞基数` /
    `玄武粘滞倍增` / `玄武粘滞笔上限`。**默认关** —— 它会让对手等，
    也会占自己的线程，是要人主动开的。
    """
    值 = 值 or {}
    return 粘滞(值, 说=说, 上限笔=值.get('玄武粘滞笔上限'))
