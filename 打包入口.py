# -*- coding: utf-8 -*-
"""
打包用的启动入口。**只在打包出来的 exe 里跑，开发时不用它。**
================================================================

开发时直接 `python 霸下之躯.py` 就行 —— 这个文件是给 PyInstaller
当入口用的，它比 `霸下之躯.py` 多做两件事，**两件都是为了打包之后
那两处按 `__file__` 算出来的路径**。

⛔ **为什么不能不写这个文件、直接拿 `霸下之躯.py` 当入口。**

打包之后（PyInstaller **onedir**）目录长这样：

    发布/霸下数据库/
      霸下数据库.exe
      依赖库/            ← 依赖全在这儿（`sys._MEIPASS` 指向它）
        霸下之躯.pyc     ← 模块的 `__file__` 落在这儿

而 `配置.py:698` 那一句是

    配置文件 = os.path.join(os.path.dirname(os.path.abspath(__file__)), '霸下.conf')

⇒ 打包之后它算出来的是 **`依赖库/霸下.conf`**。三个后果，一个比一个坏：

1. 用户在「设置」页改完、保存，文件**落到依赖库里面去了** —— 他按着
   界面上写的那条路去找，找不到（界面报的路是从同一个变量来的，
   所以界面上看不出错）；
2. 升级 / 重装的时候，人**换掉整个依赖库**是最自然的动作 ⇒
   设置跟着一起没了，而且**一声不响**；
3. 想手改那个文件的人根本想不到要去依赖库里翻。

**所以这个文件干的第一件事：把配置那条路挪到 exe 旁边。**

⚠️ 挪法是**改 `配置` 模块那个模块级变量**，不是改 `配置.py` 一个字节。
`配置.读 / 写 / 删` 三处都是 `路径 = 路径 or 配置文件`（模块级名字，
调用时才取），所以在这儿盖一次就全生效 —— `备份.py` 那些
"自己去读配置"的调用点走的是同一个函数，一起跟着变。

⛔ **第二件事：`os.chdir` 到 exe 旁边。** 因为配置里那条 `库路径`
默认是 **`霸下.db`（相对路径）**，相对谁由"怎么启动"决定：

    双击 exe          → 工作目录 = exe 那个文件夹
    快捷方式          → 看快捷方式里"起始位置"填了没
    从资源管理器拖进来 → 看那个文件夹
    命令行            → 你当时站的那个目录

不 chdir 的话，**同一个软件会在两个地方各建一个 `霸下.db`**，
两个都打得开、都看着正常 —— 症状是"我的数据不见了"。chdir 之后
相对路径一律锚在 exe 旁边，跟"随行文件夹"那套一致。

⚠️ 图标那一格（`霸下之躯.py:1174`）**不用在这儿管**：它按
`dirname(__file__)` 找 `red_start-baxia.png`，而打包时那张图
被 `--add-data` 放进了 `依赖库/`（= `_MEIPASS`），
`dirname(__file__)` 正好也是 `依赖库/` —— 两边自然对上。
"""

import os
import sys


def _锚定():
    """
    把"配置在哪儿""相对路径相对谁"两件事锚到 exe 旁边。

    **没打包的时候（`getattr(sys, 'frozen', False)` 是假）什么都不做** ——
    开发时跑这个文件也必须跟跑 `霸下之躯.py` 一模一样，否则就会出
    "开发时好好的、打出来不一样"这种最难查的岔子。
    """
    if not getattr(sys, 'frozen', False):
        return
    程序目录 = os.path.dirname(os.path.abspath(sys.executable))
    try:
        os.chdir(程序目录)
    except OSError:
        # 盘符不在了、没权限 —— **不抛**。抛在这里就是"双击没反应"，
        # 而人看不到任何字。退回"工作目录照旧"，配置那条路下面照锚。
        pass
    import 配置
    配置.配置文件 = os.path.join(程序目录, '霸下.conf')
    配置.旧MySQL配置文件 = os.path.join(程序目录, '霸下-mysql.conf')


_锚定()

import 霸下之躯                                        # noqa: E402


if __name__ == '__main__':
    # `霸下之躯.main()` 自己 `return 0`，`__main__` 那边也是
    # `sys.exit(main())` —— 这儿照抄那个形状，退出码才一样。
    sys.exit(霸下之躯.main())
