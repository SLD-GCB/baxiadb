#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
玄武_台账.py — 城防的账本

城防里发生的每一件事都往这儿记，**记进去就改不动，也删不掉**。

为什么不能像一代那样只放在内存里
================================

一代的账（`xwf/audit/logger.py`）是一条内存里的哈希链：防"事后改账"
防得很认真，可它自己**活不过一次重启** —— 创世盐是启动时随机掷的，
重启一次链子从头再来，前一本账连个尸首都没有。

**攻击者让你重启一次，账就没了。** 而"他重启过你"这件事，
恰恰是最该被记下来的那一条。

二代这条链**落在盘上**，盐写在账本自己的第一行：

    创世行   只有这一行，写一次，后面不再有；盐住在里面
    事件行   `前` = 上一行的哈希，`本` = 哈希(前 + 这一行的内容)
    想改     改任何一行，从它往后**每一行**都对不上

重开时把第一行的盐原样读回来接着往下接，**不重掷**。

append-only 不是靠约定
======================

这个类里**没有任何一处 seek 回写、truncate、或者重写某一行**。
文件只以 `'ab'` 开。不是"我们小心一点"，是**这一层根本没有那个口子**。
要毁账只有一条路：把文件删了 —— 而那就是"整本掉"，一眼看得见。

它丢得掉吗
==========

丢得掉，所以这里可以放开手记。

**账是衍生结构**（见 `baxia-derived-state-must-be-droppable` 那条）：
把 `<库目录>/玄武/` 整个删掉，库一个字节都不少、照原样打得开 ——
账里没有一样东西是库的真相，它只是**发生过什么**的记录。
正因为丢得起，这里才敢越记越细，不用怕记出依赖来。

谁在写
======

**好几条线程一起写**：MySQL 口那条 socket 线程、界面那条工人线程、
扫尾的定时线程。所以 `记` 里有一把锁，而且**写一行就是一次 write
+ flush** —— 攒着不落的账，在"他正在攻"这个场景里等于没有。

账本自己会不会被撑爆
====================

会，而且攻击者能拿它撑。**"攻击者用日志把自己的盘写满"是一个自伤**
—— 他不需要攻破任何东西，只要每秒连一万次就行。

所以 `记` 有一个 `可合并` 开关：

    可合并=False（默认）   一件事一行，一字不改 —— 值钱的事走这条
    可合并=True           同类同源、一秒之内的，**并成一条带 `次数`**

连接进来、探测被拒这类高频率低信息量的事走合并那条；
登录失败、SQL、判词这类走逐条。合并项攒在内存里，满一秒落一次，
`收尾()` 和任何一次查询都会先把它冲下去。
"""

import hashlib
import json
import os
import threading
import time

__all__ = ['台账', '台账错', '账台', '相对路径', '库账路径']

#: 一个库的账本放在库里的哪个位置。
#:
#: ⛔ **这个字符串只许在这儿写一遍。** 以前它同时出现在本文件的文档里和
#: `玄武_界面._账路径` 那个方法里（那个方法自己留了一条注释说"两处写着
#: 同一个字符串"）——现在收成一处，两边都认它。
相对路径 = os.path.join('玄武', '账.jsonl')


def 库账路径(库根):
    """`<库根>/玄武/账.jsonl`。`库根` 空着就回 `None`（没有库就没有账）。"""
    if not 库根:
        return None
    return os.path.join(str(库根), 相对路径)


_编码 = 'utf-8'
_创世类 = '创世'
#: 同类同源的事几秒并成一条。配置键 `玄武账合并秒`。
_合并窗口秒 = 1.0
# 一行最多这么长。超过的字段会被截断并标出来 —— **不是怕写不下，
# 是怕攻击者往一个字段里灌 100MB，让"记一笔"变成一次自伤。**
# 配置键 `玄武账字段上限`。
_字段上限 = 64 * 1024
#: 一个列表/字典最多记几项。配置键 `玄武账容器项数`。
_容器项数 = 256


def _正(值, 默认, 下限=1):
    """取一个不小于 `下限` 的整数。给不出来就用默认。"""
    try:
        return max(下限, int(值 if 值 is not None else 默认))
    except (TypeError, ValueError):
        return 默认


def _数(值, 默认, 下限=0.0):
    """取一个不小于 `下限` 的小数。给不出来就用默认。"""
    try:
        return max(下限, float(值 if 值 is not None else 默认))
    except (TypeError, ValueError):
        return 默认


class 台账错(Exception):
    """账本的事出了岔子（写不进去、路径不可用）。"""


# ── 编行：一行必须编出确定的字节 ──────────────────────────────────


def _时刻秒():
    return time.time()


def _时刻文(秒):
    return time.strftime('%Y-%m-%d %H:%M:%S', time.localtime(秒))


def _整齐(对象):
    """
    字典 -> 一串字节。

    **必须排序键、必须紧凑分隔符。** 哈希是对着这串字节算的，同样的
    内容换个键序就编出另一串字节、算出另一个哈希 —— 而"同一件事编出
    两个哈希"会让验账在一条完全正常的记录上报错。
    """
    return json.dumps(对象, ensure_ascii=False, sort_keys=True,
                      separators=(',', ':')).encode(_编码)


def _哈希(前, 体):
    """链上的一环：`sha256(上一行的哈希 \\n 这一行的内容)`。"""
    h = hashlib.sha256()
    h.update(前)
    h.update(b'\n')
    h.update(体)
    return h.hexdigest()


def _收一收(值, 字段上限=_字段上限, 容器项数=256):
    """
    字段值 -> 能编进一行的东西，顺便封顶。

    只认识 json 编得动的那几样；别的一律 `repr` —— **宁可记一句
    "这是什么"，也不要为了记一笔而抛异常**。记日志这件事要是能
    把主流程弄挂，那就等于攻击者拿到了一个"让防守方自己崩"的开关。

    两个上限从 `台账` 那边传进来（配置键 `玄武账字段上限` /
    `玄武账容器项数`），**递归下去的时候也要传** —— 漏传一层就是
    "只封了最外面那层"，而攻击者要的正是里面那层。
    """
    if 值 is None or isinstance(值, (bool, int, float, str)):
        if isinstance(值, str) and len(值) > 字段上限:
            return 值[:字段上限] + '…（截断，原长 %d）' % len(值)
        return 值
    if isinstance(值, (bytes, bytearray)):
        # ⚠ 这儿的 64 是**另一种字节**：字节串不整篇记，只记它多长、
        # 头 64 字节长什么样。它和 `字段上限` 不是一回事，别并成一条。
        return {'字节': len(值), '头': bytes(值[:64]).hex()}
    if isinstance(值, (list, tuple)):
        return [_收一收(x, 字段上限, 容器项数)
                for x in list(值)[:容器项数]]
    if isinstance(值, dict):
        return {str(k): _收一收(v, 字段上限, 容器项数)
                for k, v in list(值.items())[:容器项数]}
    try:
        文 = repr(值)
    except Exception:
        文 = '<取不出样子>'
    return 文[:字段上限]


# ══ 台账 ══════════════════════════════════════════════════════════


class 台账(object):
    """
    一个库一本。放在 `<库目录>/玄武/账.jsonl`（= `库账路径(库目录)`）。

    一行一条记录 —— **不用 `indent=` 那种多行格式**：一条记录占一行，
    验账才能一行一行读着走，而且文件里任何一处坏了都能指出"第几行"。

    参数：

        `路径`  账本文件。它的父目录会被建出来。
    """

    def __init__(self, 路径, 值=None):
        值 = 值 or {}
        self._路径 = os.path.abspath(str(路径))
        # ── 账本自己那几把尺子（配置键全在「城防·账」那一组）──────────
        # ⛔ **属性名不带下划线，是故意的**（同 `玄武_画` / `玄武_粘滞`）：
        # 模块顶上那几个常量叫 `_字段上限` / `_合并窗口秒`，方法体里写
        # `_字段上限` 指的是**模块那个**。属性名撞上就是"改了配置、
        # 实际没变"，还不报错。
        self.合并秒 = _数(值.get('玄武账合并秒'), _合并窗口秒, 下限=0.05)
        self.字段上限 = _正(值.get('玄武账字段上限'), _字段上限, 下限=1024)
        self.容器项数 = _正(值.get('玄武账容器项数'), 256, 下限=4)
        self.尾数 = _正(值.get('玄武账尾数'), 50)
        self.查数 = _正(值.get('玄武账查数'), 500)
        self._锁 = threading.RLock()
        self._号 = 0            # 最后一条的号（创世行是 0）
        self._前 = b''          # 最后一行的哈希（十六进制字节）
        self._盐 = ''
        self._攒 = {}           # (类, 源) -> 攒着的合并项
        目录 = os.path.dirname(self._路径)
        if 目录:
            os.makedirs(目录, exist_ok=True)
        self._接上()

    # ── 起手：读回上一次的尾 ────────────────────────────────────

    def _接上(self):
        """
        把盘上那本读一遍，找回**尾**，接着往下接。

        **盐不重掷。** 它在第一行里躺着，原样读回来 —— 重掷的话
        整条链就从今天重新开始，昨天那本账再也验不了。

        整本读进来是 O(文件大小)。一个库的账本不会太大，而且这件事
        开机只做一次；真大到慢了，那也是"该归档了"的信号，
        不该在这儿偷偷改成只读最后一行 —— 那样链子断在中间就看不见。
        """
        if not os.path.exists(self._路径):
            self._开一本()
            return
        try:
            with open(self._路径, 'rb') as f:
                块 = f.read()
        except OSError as exc:
            raise 台账错('账本读不出来（%s）：%s' % (self._路径, exc))
        行们 = [x for x in 块.split(b'\n') if x.strip()]
        if not 行们:
            self._开一本()
            return
        try:
            创 = json.loads(行们[0].decode(_编码))
            末 = json.loads(行们[-1].decode(_编码))
        except Exception as exc:
            raise 台账错('账本开头或结尾不是一行合法 JSON（%s）：%s'
                         % (self._路径, exc))
        self._盐 = str(创.get('盐', ''))
        self._号 = int(末.get('号', 0))
        self._前 = str(末.get('本', '')).encode(_编码)

    def _开一本(self):
        """第一次开：写创世行，顺手把盐定下来。"""
        体 = {'号': 0, '类': _创世类, '时刻': _时刻文(_时刻秒()),
              '盐': os.urandom(16).hex(), '前': ''}
        本 = _哈希(b'', _整齐(体))
        体['本'] = 本
        self._加一行(体)
        self._盐 = 体['盐']
        self._号 = 0
        self._前 = 本.encode(_编码)

    # ── 写 ──────────────────────────────────────────────────────────

    def _加一行(self, 体):
        """**唯一**一处碰文件的写。`体` 里不能带 `本`。"""
        行 = _整齐(体) + b'\n'
        try:
            with open(self._路径, 'ab') as f:
                f.write(行)
                f.flush()
        except OSError as exc:
            raise 台账错('账写不进去（%s）：%s' % (self._路径, exc))

    def _落(self, 类, 字段, 源=''):
        """编一条事件行、接上链、写下去。**调用方持锁。**"""
        self._号 += 1
        体 = dict(字段)
        体['号'] = self._号
        体['类'] = 类
        体['时刻'] = _时刻文(_时刻秒())
        if 源:
            体['源'] = 源
        体['前'] = self._前.decode(_编码)
        本 = _哈希(self._前, _整齐(体))
        体['本'] = 本
        try:
            self._加一行(体)
        except 台账错:
            self._号 -= 1
            raise
        self._前 = 本.encode(_编码)
        return 体

    def 记(self, 类, 可合并=False, 源='', **字段):
        """
        记一笔。返回写下去的那条（合并项返回 `None`）。

        **这个方法不抛业务异常。** 调用方是城防的判词、是 socket
        线程 —— 记不上账不该让一次判断失败，更不该让一条连接掉线。
        路径真出了事，抛 `台账错`，由 `城` 那一层决定怎么办
        （做法是报一次、然后退化成不记，不是把请求打回去）。

        `可合并=True` 的走合并窗口：同类同源的重复事件并成一条带
        `次数` 的记录。**值钱的判定必须逐条**，别图省事全设成可合并 ——
        那样"他第几次才试对"这件事就没了。
        """
        字段 = {str(k): _收一收(v, self.字段上限, self.容器项数)
                for k, v in 字段.items()}
        with self._锁:
            self._冲()
            if 可合并:
                键 = (类, str(源))
                现在 = _时刻秒()
                攒 = self._攒.get(键)
                if 攒 is None:
                    self._攒[键] = {'类': 类, '源': str(源), '次数': 1,
                                    '首': 现在, '末': 现在, '样': 字段}
                else:
                    攒['次数'] += 1
                    攒['末'] = 现在
                return None
            return self._落(类, 字段, 源=str(源))

    def _冲(self, 现在=None):
        """
        把攒够一秒的合并项落下去。**调用方持锁。**

        攒着的那几条**只在有人问的时候才看得见**（`冲` 挂在查询前面）。
        攻击停了、没人再 `记` 了，最后不到一秒的那几条要等下一次
        查询才落地 —— 所以关库那条路必须显式 `收尾()`。
        """
        现在 = _时刻秒() if 现在 is None else 现在
        for 键 in [k for k, v in self._攒.items()
                   if 现在 - v['末'] >= self.合并秒]:
            攒 = self._攒.pop(键)
            字段 = dict(攒['样'])
            字段['次数'] = 攒['次数']
            字段['首见'] = _时刻文(攒['首'])
            字段['末见'] = _时刻文(攒['末'])
            self._落(攒['类'], 字段, 源=攒['源'])

    def 收尾(self):
        """把攒着的全落下去。**关库、停城之前必须调一次。**"""
        with self._锁:
            现在 = _时刻秒()
            for 键 in list(self._攒):
                攒 = self._攒.pop(键)
                字段 = dict(攒['样'])
                字段['次数'] = 攒['次数']
                字段['首见'] = _时刻文(攒['首'])
                字段['末见'] = _时刻文(攒['末'])
                self._落(攒['类'], 字段, 源=攒['源'])
            return 现在

    # ── 读 ──────────────────────────────────────────────────────────

    def _读全(self):
        """盘上所有行 -> [dict]。坏一行就跳过那一行，不整本报废。"""
        if not os.path.exists(self._路径):
            return []
        try:
            with open(self._路径, 'rb') as f:
                块 = f.read()
        except OSError:
            return []
        出 = []
        for 行 in 块.split(b'\n'):
            if not 行.strip():
                continue
            try:
                出.append(json.loads(行.decode(_编码)))
            except Exception:
                continue
        return 出

    def 尾(self, n=None):
        """
        最近 `n` 条，**老到新**。给界面那个"正在发生什么"用。

        `n` 不给就用配置里那条 `玄武账尾数`（`self.尾数`）—— 界面照着
        默认叫一句 `账.尾()` 就行，**尺子只有账本这一处拿得到**。
        """
        n = self.尾数 if n is None else n
        with self._锁:
            self._冲()
        return self._读全()[-max(1, int(n)):]

    def 查(self, 类=None, 源=None, 自=None, 至=None, 限=None):
        """
        挑着看。

        `自` / `至` 是**秒级时间戳**（不是字符串）—— 界面按"最近五分钟"
        挑，算的是时间不是文本，字符串比较在跨天的时候会骗人。

        `限` 是**从新的那头往回数**。攻得凶的时候账目涨得比人看得快，
        从老的那头截，看到的永远是开场那几条。
        `限` 不给就用配置里那条 `玄武账查数`（`self.查数`），同上。
        """
        限 = self.查数 if 限 is None else 限
        with self._锁:
            self._冲()
        出 = []
        for 条 in self._读全():
            if 类 is not None and 条.get('类') != 类:
                continue
            if 源 is not None and 条.get('源') != 源:
                continue
            if 自 is not None or 至 is not None:
                try:
                    秒 = time.mktime(time.strptime(
                         str(条.get('时刻', '')), '%Y-%m-%d %H:%M:%S'))
                except Exception:
                    continue
                if 自 is not None and 秒 < 自:
                    continue
                if 至 is not None and 秒 > 至:
                    continue
            出.append(条)
        return 出[-max(1, int(限)):]

    # ── 验 ──────────────────────────────────────────────────────────

    def 验(self):
        """
        把整条链重算一遍。返回 `(对不对, 一句话, 第几行)`。

        **这一条不是"顺手做的自检"，是城防功能本身。** 攻击者进来之后
        干的第一件事常常是抹痕迹，而"账被抹过"这件事必须能看见 ——
        所以界面上要有一个按钮，按下去跑的就是它。

        报"第几行"而不是"链子坏了"：一行一行数出来的位置，能直接
        对着文件看，也能算出从他进来的哪一刻起不对。
        """
        with self._锁:
            self._冲()
        行们 = []
        if os.path.exists(self._路径):
            try:
                with open(self._路径, 'rb') as f:
                    块 = f.read()
                行们 = [x for x in 块.split(b'\n') if x.strip()]
            except OSError as exc:
                return False, '账本读不出来：%s' % exc, 0
        if not 行们:
            return True, '还没有账', 0

        前 = b''
        for i, 行 in enumerate(行们, 1):
            try:
                体 = json.loads(行.decode(_编码))
            except Exception:
                return False, '第 %d 行不是一行合法的 JSON' % i, i
            本 = 体.pop('本', None)
            if not isinstance(本, str):
                return False, '第 %d 行没有"本"这个字段' % i, i
            # ⛔ **先判链子，再判哈希。** 顺序反过来会骗人：
            # 删掉第 3 行之后，顶上来的第 4 行**内容一个字没改**，
            # 只是它的"前"指向一个已经不挨着的前面 —— 而拿新的前
            # 去重算哈希也一样对不上，于是报出来的是"内容被改过"。
            # 报错指错方向，比不报还坏：人会去查一条根本没被动过的行。
            if str(体.get('前', '')) != 前.decode(_编码):
                return False, '第 %d 行的"前"接不上上一行 —— 中间少了一行' % i, i
            想 = _哈希(前, _整齐(体))
            if 本 != 想:
                return False, '第 %d 行对不上 —— 这一行的内容被改过' % i, i
            前 = 本.encode(_编码)
        return True, '共 %d 行，链子完整' % len(行们), 0

    # ── 报数 ────────────────────────────────────────────────────────

    def 大小(self):
        try:
            return os.path.getsize(self._路径)
        except OSError:
            return 0

    def 统计(self):
        """
        给界面那一格用。

        **`件数` 是连创世行一起数的**（`号` 从 0 起），所以它是
        "这个文件里有多少行"，不是"发生过多少件攻击"。两个数不要混用。
        """
        with self._锁:
            self._冲()
            return {'路径': self._路径, '盐': self._盐,
                    '件数': self._号 + 1, '字节': self.大小(),
                    '攒着': len(self._攒)}

    # ── 样子 ────────────────────────────────────────────────────────

    def __repr__(self):
        return '<台账 %s 第 %d 件>' % (self._路径, self._号)


# ══ 账台：把「一手」记上账 ═════════════════════════════════════════════

class 账台(object):
    """
    账这一台。**一个可调用，收 `一手`，把它记上账。**给
    `城.登记('账', 玄武_台账.账台(本))` 用。

    ⛔ **这个类是"城"和"账本"之间唯一的一层。** 账本那边只管一行一行
    地写（它不认识 `一手`），城那边只管按次序叫台（它不认识 JSON）。
    两边的活儿不一样，所以中间要有人翻译一次 —— 那就是这儿。

    它**什么都不判**：`一手.判词` 是什么就记什么。判是 `门台` 的事，
    账台要是也判一次，就成了两处会不一致的规矩。
    """

    def __init__(self, 本):
        self._本 = 本

    @property
    def 本(self):
        return self._本

    def __call__(self, 手):
        if self._本 is None:
            return None
        条 = self._本.记(手.类, 可合并=手.可合并, 源=手.来源,
                        **手.账字段())
        # **号回填到手上**：合并项回 `None`（还没落盘），那就留 `None`，
        # 别编一个号出来 —— 编出来的号对不上盘上任何一行。
        if 条 is not None:
            手.账上 = 条.get('号')
        return 条

    def __repr__(self):
        return '<账台 %r>' % (self._本,)
