# ── 库目录：盘上有哪些库 ──────────────────────────────────────────────
#
# **一个库 = 一块永久存储区 = 一个根目录**（里面 `catalog` + `r/`）。所以
# "有好几个库"落在盘上就是"有好几个这样的目录"。
#
# 界面得知道有哪些库。两条路：去数目录，或者另记一本账。**这里选数目录**
# ——账本会跟盘对不上（有人拿资源管理器删了一个，账上还留着；有人拷进来
# 一个，账上不知道），而数目录永远等于盘上真有什么。
#
# **库都放在同一个目录底下**，那个目录就是配置里那条 `库路径` 的上一级。
# 不加新配置项：现在开着的库放在哪，别的库就放在它旁边。


def 是库(路):
    """
    这个目录是不是一块永久存储区。**认招牌，不认名字。**

    招牌是 `catalog`（`store_format.CATALOG_NAME`）。只按后缀认的话，一个
    叫 `x.db` 的普通文件夹也会被当成库，点进去才报"存储区不存在"——那时
    人已经以为它是库了。而 `arena.create` 判"已存在"用的**就是这一样**
    （`arena.py:335`），两边同一把尺子。
    """
    import store_format
    return os.path.isfile(os.path.join(路, store_format.CATALOG_NAME))


def 扫库(库目录):
    """扫一遍库目录，回 `[(库名, 路), …]`，按名字排。扫不动就回空的。"""
    出 = []
    try:
        名们 = sorted(os.listdir(库目录))
    except OSError:
        return 出                      # 目录不在、读不动——当成"一个库都没有"
    for 名 in 名们:
        路 = os.path.join(库目录, 名)
        if os.path.isdir(路) and 是库(路):
            出.append((os.path.splitext(名)[0], 路))
    return 出


def 库目录(值=None):
    """库都放在哪个目录：**配置里那条 `库路径` 的上一级**。"""
    值 = 值 if 值 is not None else _配置.读()[0]
    return os.path.dirname(os.path.abspath(值['库路径']))


def 新库路径(目录, 名):
    """给新库拼一个路径。用 `.db` 后缀，跟盘上那个 `霸下.db` 一个样子
    ——**只是为了看着像同类东西**，引擎不认后缀（它认 `catalog`）。"""
    return os.path.join(目录, 名 + '.db')


def 库名从路径(路):
    """`霸下.db` → `霸下`。和 `开库` 里那句 `库名` 拼法**是同一件事**，
    别再写第二遍（两处不一致的样子是"树上写霸下、状态栏写霸下.db"）。"""
    return os.path.splitext(os.path.basename(路))[0]


