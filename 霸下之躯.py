    def _on_toggle_mysql(self) -> None:
        """
        就地开停 MySQL 口。

        ⛔ **停的时候必须走 `门.停()`，不能直接把引用扔掉。** `停` 会
        **先把攒着没落的那批写落下去**再断连接——直接扔掉的话，已经跟客户端
        回过 `affected=1` 的那批写就没了，客户端以为成了、库里没有。理由写在
        `mysql_门.门.停` 那段。

        起的时候**先把配置重读一遍**：设置页刚存完，这儿要照新的来（口令
        映射、白名单、端口都是那两份文件里的）。
        """
        门 = getattr(self.引擎壳, 'MySQL口', None)
        if 门 is not None and 门.听着():
            try:
                门.停()
            except Exception as 错:
                QMessageBox.warning(
                    self, 'MySQL 口',
                    '停的时候出了点岔子：%s\n\n（口已经不再接受新连接了，'
                    '刚才攒着的那批写会尽量落下去。）' % 错)
            self.引擎壳.MySQL口 = None
            # 城跟着口一起收 —— **次序不能反**：口停的时候每条连接都会
            # `关会话`，那些「一手」要走城；城先收了它们就记不上。
            _停玄武(self.引擎壳)
            self._刷MySQL钮()
            return

        import mysql_配置 as _MySQL配置
        import mysql_门 as _mysql门

        # **每次开都重读一遍盘上那份**：设置页刚存完，这儿要照新的来
        # ——账号映射、来源白名单、端口全在那一份里。
        值, 问题 = _配置.读()
        if 问题:
            # 不合法的那几项**已经回落默认值了**（`配置.读` 干的），
            # 但绝不闷着。人按了按钮是要它开，所以报完接着开——不拦。
            QMessageBox.warning(
                self, '配置里有毛病',
                '下面这几项不合法，已经按默认值来：\n\n%s'
                % '\n'.join('%s：%s' % (k or '（整份文件）', v)
                            for k, v in 问题))
        # 城重新装一遍：这一条路是"照着刚读进来的那份值来"，而城防那四条
        # 配置就在那份值里。**上一座城在停口那一步已经收尾收掉了。**
        # ⚠ **镜原样递回去**（`镜=…`）：这一条路上够不着本机内核，
        # 再造一台是造不出来的，而开库那一台还活着。不递的话，重开一次口
        # 城里的镜就没了 —— 判到镜的手全被拒，看着像镜坏了。
        (工位_给门, 说_给门,
         self.引擎壳.玄武城, self.引擎壳.玄武镜) = _装玄武(
            self.工位, 值, getattr(self.引擎壳, '库文件路径', None), _说MySQL,
            镜=getattr(self.引擎壳, '玄武镜', None))
        try:
            新门 = _mysql门.起一个(
                工位_给门, 值, self.引擎壳.库名取,
                _MySQL配置.监听地址(值), _MySQL配置.端口(值), 说=说_给门)
        except Exception as 错:
            # 口没起来，刚装好的那座城就没用了 —— 收掉。**不收的话它会一直
            # 挂在 `引擎壳.玄武城` 上**，下一次开口又装一座，旧的连引用都
            # 找不着了。
            _停玄武(self.引擎壳)
            QMessageBox.warning(
                self, 'MySQL 口起不来',
                '%s\n\n（多半是 3306 上已经坐着一个真的 MySQL。到「设置」里'
                '把 `MySQL端口` 换一个数——但爬虫那边把它写死在'
                ' `config_gui.py:201` 了，换了得同时改那边。）' % 错)
            return
        self.引擎壳.MySQL口 = 新门
        self.引擎壳.MySQL地址 = _MySQL配置.监听地址(值)
        self._刷MySQL钮()

        if not _MySQL配置.账号映射(值):
            # 和 `开库` 那一处同一句话，理由也一样：**空映射表 = 谁也不
            # 许连**，而门口绿着、报的 1045 又和"口令不对"是同一句。
            QMessageBox.information(
                self, 'MySQL 口',
                '口在听 %s:%d 了，但**账号映射表是空的**——现在谁连进来'
                '回的都是「Access denied」（1045）。\n\n'
                '到「设置」→ MySQL 兼容口，在「MySQL 用户名 → 霸下账号」'
                '那张表里加一条：左边填爬虫 `config_gui` 里那个用户名，'
                '右边填库里真有的霸下账号名。'
                % (_MySQL配置.监听地址(值), _MySQL配置.端口(值)))

    def 管MySQL口(self, 要听: bool) -> bool:
        """
        让 MySQL 口**听着**或者**别听**，回它原来是什么样。**幂等。**

        备份那条路要它（备份前后各叫一次：备之前停、备完照原样还回去），
        所以这里做成"要什么给什么"，不是 `_on_toggle_mysql` 那种一按翻一
        下的开关——开关的话，本来就没开着的口会被"顺手开上"，而那是用户
        自己关的，不该由备份替他开。

        真停 / 真开还是走 `_on_toggle_mysql`：它每次重读一遍配置，报的错
        也是现成的那几句（端口被占、映射表空），不在第二个地方再写一遍。
        """
        门 = getattr(self.引擎壳, 'MySQL口', None)
        听着 = bool(门 is not None and 门.听着())
        if 听着 != bool(要听):
            self._on_toggle_mysql()
        return 听着

    def _on_global_refresh(self) -> None:
        """
        全局刷新 — 把所有有 `refresh()` 的面板叫一遍。

        **跟参照项目不一样的一处**：那边 `refresh()` 是同步的，它能一边刷
        一边报"已刷新 N/M 个面板"；霸下这边 `refresh()` 是把活**投给工人
        线程**、当场就返回，真正刷完是稍后的事。所以这里能报的只有"已请求
        N 个面板刷新"——报"已刷新"就是在骗人。

        那个 `QApplication.processEvents()` 也不用要了：投活本来就不阻塞。
        """
        btn = getattr(self, '_global_refresh_btn', None)
        if btn:
            btn.setEnabled(False)
            btn.setText("⏳ 正在刷新...")

        投出 = 0
        for i in range(self.tabs.count()):
            widget = self.tabs.widget(i)
            if hasattr(widget, 'refresh'):
                widget.refresh()
                投出 += 1

        if btn:
            btn.setEnabled(True)
            btn.setText("🔄 全局刷新 (F5)")
        self.status.showMessage(
            '🔄 已请求 %d 个面板刷新（异步，稍后可见）' % 投出, 3000)

    def _on_refresh_current(self) -> None:
        """刷新当前选中的面板。"""
        idx = self.tabs.currentIndex()
        widget = self.tabs.widget(idx)
        if hasattr(widget, 'refresh'):
            widget.refresh()
            tab_name = self.tabs.tabText(idx).split(' [', 1)[0]
            self.status.showMessage('已请求刷新: %s' % tab_name, 1500)

    def refresh(self) -> None:
        self._on_global_refresh()

