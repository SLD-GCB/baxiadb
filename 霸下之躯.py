def 建一个库(路, 值=None):
    """
    在盘上建一块空存储区，**建完就关**。

    **参数必须和 `开库` 拿的是同一份**（`配置.存储区配置` + `配置.语句上限`），
    不能图省事让引擎用默认值。原因是一条硬约束：`区域容量` 建库时写进
    超级块，开库时**必须一致**（`arena.py:363`）。用默认值建、用配置里那
    套开，只要配置里改过容量，这个库建出来**当场就开不回去**——报"区域
    容量不一致"，而它是一秒钟前刚建的。所以两条路共用一处参数。

    **不在这里登录**：建出来的库一个用户都没有，进去之后开库那一步会
    要求设管理员（`装身份` 那一支）。这里只负责"把地圈出来"。

    **建完必须 `停()`**——`龙龟之心.建` 返回的那个内核占着一个 Arena，
    不关掉就直接去开它，就是同一个目录上两个写者（`龙龟之心.py:83-95`
    那条铁律）。
    """
    值 = 值 if 值 is not None else _配置.读()[0]
    内核 = 龙龟之心.建(路, config=_配置.存储区配置(值),
                       **_配置.语句上限(值))
    内核.停()
    return 路


def 删一个库(路, 留哪个=None):
    """
    把一块存储区从盘上抹掉。**不可撤销。**

    **引擎里没有这条原语**——我把 `format` / `reset` / `drop_all` / `清空`
    这些名字全项目搜过，区一级只有"标死一个区"（`arena.py:443`）、表一级
    只有"写墓碑"（`syntax.py:1529`），**没有任何一条路能抹掉整个存储区**。
    所以只能在这一层亲手删目录。

    调用它之前**必须保证那个库已经关了**（`删库前先切走` 那一路）。原因是
    Windows 上文件开着就删不掉：`Arena` 长开着 `catalog` 和活跃区那两个
    句柄（`arena.py:345/359/1082`），删到一半会抛 `PermissionError`，留下
    一个半死不活的目录——`arena.py:186-188` 那段注释专门在说这个坑。

    删的是**整个根目录**。`catalog` 和 `r/` 是平级的（`arena.py:337/345`），
    只删 `catalog` 会留下一堆没人认领的区文件。

    **删完要把配置里那条 `库路径` 改开**，见下面 `_改配置默认库`。不改的话
    下次开界面会**悄悄原地长出一个同名的空库**出来——`开库` 是"路径在就
    开、不在就建"（见那儿 `os.path.exists` 那个分岔），它不知道这个库是刚
    被人删掉的。那不是"删干净了"，是"删完又回来了，里面还空了"。

    `留哪个` 是"改开之后指向谁"，由调用方给**这次真开着的那个库**（删之前
    一定先切走了，所以它必然存在、必然不是刚删的那个）。不给就退而求其次，
    挑库目录里剩下的第一个。
    """
    import shutil
    if not os.path.isdir(路):
        return False
    shutil.rmtree(路)
    _改配置默认库(路, 留哪个)
    return True


def 配置默认库():
    """
    配置里那条 `库路径` 指向哪个库——也就是**下次开界面进的是哪个**。

    给界面在**删库之前**问一句用的：删的正好是这一个时，得先告诉人"启动
    那个库也要改到别处去"（见 `_改配置默认库`），删完再说就晚了。
    """
    return _配置.读()[0]['库路径']


def _改配置默认库(删掉的, 留哪个=None):
    """
    刚删掉的那个库要是**就是配置里指着的那个**，把配置改到别的库上。

    只在这一种情况下动配置——配置里的 `库路径` 指的是别人时，一个字都不
    改（用户特意把启动库定在别处，删第三方库不该动它）。

    挑谁：`留哪个` → 库目录里剩下的第一个 → 都不剩就**不动**。最后那一种
    不是偷懒：一个库都不剩的时候，下次开界面在建一个新的是**对的**（目录
    里确实什么都没有了），那时候没有"别的库"可以指。
    """
    值, _ = _配置.读()
    if os.path.abspath(值['库路径']) != os.path.abspath(删掉的):
        return None
    目录 = os.path.dirname(os.path.abspath(删掉的))
    剩下 = [p for _名, p in 扫库(目录)]
    挑 = 留哪个 if 留哪个 in 剩下 else (剩下[0] if 剩下 else None)
    if 挑 is None:
        return None
    值['库路径'] = 挑
    _配置.写(值)
    return 挑


def _说MySQL(文):
    """
    MySQL 口那些日志（攒批落地、超时的那几条语句）。

    **走 stderr，不弹窗。** 这是每分钟几十条的量，弹窗会把人淹掉；而
    `耗时日志秒` 那一条本来就是为了"攒批到底省了多少"给人看的。

    拿 `pythonw` 起来的时候 `sys.stderr` 是 `None`，`print` 会抛——
    所以这里兜一下。**日志写不出去不该把库带倒。**
    """
    try:
        print('[mysql] %s' % 文, file=sys.stderr, flush=True)
    except Exception:
        pass


