"""
玄武_饵.py — 饵：在他那边引爆

**这是"有来无回"里"有来"的那一半。** 他拿走的东西里埋着三样，各打各的：

    投毒  打他的**结论**   🔇 静 —— 他到最后都不知道
    畸形  打他的**工具**   🔊 响 —— 会暴露"有陷阱"
    水印  证明**这东西出自你这儿**

⛔ 头一条硬闸：**饵只进镜出来的数据，与真库零接触**
=================================================

计划 §七·六 那张"绝不能碰的"表里，**真库排在第一位**。这一条不是靠
自觉，是靠代码：`饵.__call__` 第一句就是

    if 手.判词 != 镜: return

判词不是 `镜` 的手，饵**一个字都不动**。走真库的请求永远不会经过饵的
有效分支 —— 它连"这一手有哪些行"都拿不到（`手.答案` 是空的）。

⛔ 第二条：**饵是"记的台"，坏了不许拦人**
==========================================

计划 §三·三：记的台出错 → 请求照走 + 会话降级。所以这个文件里
**任何一处都不许 `raise`**，捕到什么都咽下去、只留一句话。

信标：**没做，而且这是故意的**
==============================

计划 §七·三 说信标打的是他的**位置**，§十一 第 3 条自己写着它是
"**唯一一处会暴露你自己的设计**"—— 它要一个公网可达的收集点，也就是
你这台机器得对外开个口子。**那是用户的决定，不是这一层的实现细节。**
所以这一版不写它。要写的话，加的是一个新方法，不是改这个文件的骨架。

水印说的是什么、不说的是什么
============================

**说的是**："这批数据的形状，和从那面镜里出来时留下的规则对得上。"
判据是**比例**，不是"找到一个就断言"：

    编的数据里，某格的末几位恰好等于"这一行其余部分算出来的指纹"的概率
    是 1/10000。那 1% 的命中率是不可能碰出来的。

**不说的**：它不是密码学证明。他没拿到账本、只拿到数据，这个说法成立；
**他要是连账本一起搬走了，盐也就跟着走了**（账本在库目录里、没加密），
那他能伪造。所以它证明的是"**数据是从我这儿流出去的**"，不是
"**这数据是他偷的**"—— 后半句由账本自己说（账上有来源、有时间）。

格式必须过他自己的校验
======================

计划 §七·四："他脚本校验手机号格式 → 假的要过；校验身份证校验位 →
假的要过。**过了，他就不会怀疑。**"所以这儿的每一个编造函数都照着
真格式来 —— 手机是 11 位、身份证是 18 位且**最后一位校验位算对**。
"""

