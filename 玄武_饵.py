# ══ 二、指纹与水印 ═════════════════════════════════════════════════════

def 指纹(行, 跳过=-1):
    """
    一行的指纹：**把 `跳过` 那一格挖掉之后，剩下的算出个数来。**

    ⛔ **为什么必须挖掉自己。** 水印要能**只看他手里的数据**验出来 ——
    验的人没有"原来那个值"，他只有这一行。所以规则只能长成
    "**这一格 = 其余各格算出来的**"这种**自洽**的形状：把带标记的那一格
    挖掉，剩下的还能重算出标记来。

    回 `0` 到 `9999` 之间的整数（水印只用低四位）。
    """
    块 = []
    for i, 格 in enumerate(行):
        if i == 跳过:
            continue
        try:
            类号, 值 = 格
        except (TypeError, ValueError):
            continue
        if isinstance(值, (bytes, bytearray)):
            值 = bytes(值).hex()
        块.append('%d:%s' % (类号, 值))
    if not 块:
        return 0
    料 = '|'.join(块).encode('utf-8', 'replace')
    return int(hashlib.sha256(料).hexdigest()[:8], 16) % 10000


def 验水印(行们, 期望率=0.0):
    """
    看这批数据像不像从镜里出来的。**只读，一个字节都不改。**

    回 `{'行数', '命中', '命中率', '偶然率', '像不像', '话'}`。

    判据是**比例**（见文件头"水印说的是什么"）：编的数据里，某一格的末
    四位恰好等于"这一行其余部分算出来的指纹"的概率是 `1/10000`。所以
    命中率远远压过 `1/10000` 才说明"这是照我们的规则编的"。

    `期望率` 是调用方自己知道的投毒率（比如 `1.0` 表示 1%）。给了它，
    命中率还得跟它在一个数量级上 —— 只多不少、也只多那么些。
    """
    行们 = list(行们 or [])
    总 = 0
    中 = 0
    for 行 in 行们:
        if not 行:
            continue
        总 += 1
        for i, 格 in enumerate(行):
            try:
                类号, 值 = 格
            except (TypeError, ValueError):
                continue
            if not _带标记(值, 指纹(行, i)):
                continue
            中 += 1
            break            # 一行算一次，别让一行的多格把比例抬起来
    率 = (中 / 总) if 总 else 0.0
    偶然 = 0.0001
    像 = 率 > 偶然 * 20          # 20 倍，免得几行数据就下结论
    if 期望率 > 0:
        像 = 像 and 率 <= (期望率 / 100.0) * 5 + 偶然
    话 = ('命中 %d / %d（%.2f%%），偶然撞上的期望是 %.4f%% —— %s'
          % (中, 总, 率 * 100, 偶然 * 100,
             '像' if 像 else '看不出是照我们的规则编的'))
    return {'行数': 总, '命中': 中, '命中率': 率,
            '偶然率': 偶然, '像不像': 像, '话': 话}


def _带标记(值, 标):
    """这一格的末四位是不是就是这个标记。**只认得出，不改。**"""
    if isinstance(值, bool) or 值 is None:
        return False
    if isinstance(值, float):
        # 实数只看分的末四位（`1.23` 里的 `23` 那种精度是人看得惯的）。
        return int(round(值 * 100)) % 10000 == 标
    if isinstance(值, int):
        return 值 % 10000 == 标
    if isinstance(值, str):
        数 = ''.join(c for c in 值 if c.isdigit())
        if len(数) < 4:
            return False
        return int(数[-4:]) == 标
    return False


# ══ 三、编造：格式全合法 ═══════════════════════════════════════════════

def _编手机(标):
    """
    11 位、`1[3-9]` 开头。**末四位留给水印。**

    ⛔ **数位要数清楚。** 这里写错过一次：`1` + 号段(1) + 中段(4) + 水印(4)
    是 **10** 位 —— 编出来的号码短一位，他自己的格式校验**第一个就把它
    挑出来**，那这一批毒就白下了（计划 §七·四："假的值必须过他自己的
    校验"）。中段取 5 位，`1 + 1 + 5 + 4 = 11`。
    """
    头 = '1%d' % (3 + 标 % 7)                    # 号段：13x ~ 19x
    中 = '%06d' % (标 * 7919 % 1000000)
    return 头 + 中[:5] + '%04d' % 标


#: 身份证前 17 位的加权因子和校验码表（`GB 11643-1999`，公开的标准算法）
_权 = (7, 9, 10, 5, 8, 4, 2, 1, 6, 3, 7, 9, 10, 5, 8, 4, 2)
_码 = '10X98765432'


def _编身份证(标):
    """
    18 位。**最后一位是算出来的校验位** —— 他脚本一验就过。

    前 17 位里末四位放水印（水印在**校验位之前**，校验位照常算对）。
    """
    身 = '11010119%06d%04d' % (标 * 104729 % 1000000, 标)
    身 = 身[:17].ljust(17, '0')[:17]
    和 = sum(int(身[i]) * _权[i] for i in range(17))
    return 身 + _码[和 % 11]


#: 姓（按常见程度排，头几个最像真的）和名字用字
_姓 = ('王李张刘陈杨黄赵吴周徐孙马朱胡林郭何高罗')
_名字 = ('伟芳娜秀英敏静丽强磊军洋勇艳杰娟涛明超秀霞平刚桂英')


def _编姓名(标):
    """姓 + 名。**取字由标记定**，同一个标记每次编出同一个名字。"""
    return (_姓[标 % len(_姓)]
            + _名字[(标 // len(_姓)) % len(_名字)])


_域名 = ('qq.com', '163.com', '139.com', 'outlook.com', 'foxmail.com')


def _编邮箱(标):
    return 'user%04d@%s' % (标, _域名[标 % len(_域名)])


_省 = ('北京市朝阳区', '上海市浦东新区', '广东省深圳市南山区',
       '浙江省杭州市西湖区', '江苏省南京市鼓楼区', '四川省成都市武侯区')
_路 = ('建设路', '人民大道', '解放路', '中山北路', '科技园路', '文化街')


def _编地址(标):
    return '%s%s%d号' % (_省[标 % len(_省)], _路[(标 // 7) % len(_路)],
                        1 + 标 % 900)


# ══ 四、饵 ═════════════════════════════════════════════════════════════

class 饵(object):
    """
    下饵的台。**一个可调用，收 `一手`，把 `一手.答案` 里的行改掉。**

    ⛔ 它在 `城.记手` 里被叫（**不是 `请判`**）—— 因为"他带走的东西"要等
    这一手真查完才存在。见 `玄武_城.城.记手` 那段。

    参数：

        `值`    `配置.py` 那份值。读 `玄武下饵` / `玄武投毒率` / `玄武盐`。
        `说`    记一句话的回调。
        `盐`    水印用的盐。**一般是账本那一个**（`玄武_台账` 的第一行里
                躺着的创世盐，重启不重掷）。没给就退回一个固定串 ——
                那还是能验，只是不同库之间认不出区别。

    投毒率是**按行**算的（`玄武投毒率`，单位百分比，默认 1.0），而且用
    指纹定"毒不毒"：**同一批数据反复过手，毒的永远是那几行**。不这么定
    的话，他多拉两次一比，就发现"上一次还是真的、这一次变了"。
    """

    def __init__(self, 值=None, 说=None, 盐=''):
        值 = 值 or {}
        self._开 = bool(值.get('玄武下饵', True))
        self._畸形 = bool(值.get('玄武畸形'))
        #: 隔几行埋一个畸形值。**埋浅了等于开场就报信** —— 计划 §七·三
        #: 要的是"让他先投入大量工作才碰到"，见 `_补畸形`。
        try:
            self._间隔 = max(1, int(值.get('玄武饵畸形间隔') or 997))
        except (TypeError, ValueError):
            self._间隔 = 997
        # ⛔ **`100.0` 是这里的天花板，不是 `1.0`。** 判句在 `_该毒`：
        # `标 < int(率 * 100)`，而 `标` 是 `指纹()` 算出来的 **0..9999** ——
        # 填 1.0 动的是百分之一，填 100.0 才是全动。（`配置.py` 那一行
        # 原先把上限写成 1.0 并说"1.0 = 全动"，是那边错了，已改。）
        try:
            self._率 = max(0.0, min(100.0, float(值.get('玄武投毒率') or 0.0)))
        except (TypeError, ValueError):
            self._率 = 1.0
        self._盐 = str(盐 or '') or '玄武·没有盐'
        self._说 = 说 or (lambda 文: None)
        self._毒过的行数 = 0
        self._畸形过的行数 = 0

    # ── 那一手 ──────────────────────────────────────────────────────

    def __call__(self, 手):
        """
        ⛔ **第一句就是那道硬闸。** 判词不是 `镜`，这一台立刻收手 ——
        真库出来的行**一格都不许碰**（计划 §七·六）。
        """
        if not self._开:
            return None
        if getattr(手, '判词', None) != '镜':
            return None
        行们 = getattr(手, '答案', None)
        if not 行们:
            return None
        try:
            return self._下(手, 行们)
        except BaseException as 错:
            # 记的台：**坏了不许拦人**，一句话，然后照走。
            self._说('[玄武] 饵下不去 —— %s：%s' % (type(错).__name__, 错))
            return None

    def _下(self, 手, 行们):
        列名 = _列名(手)
        毒了 = 0
        for 序, 行 in enumerate(行们):
            if not 行:
                continue
            for i, 格 in enumerate(行):
                名 = 列名[i].lower() if i < len(列名) else ''
                if _是键(名):
                    continue                    # ⛔ 键列一个字都不碰
                类 = _分类(名)
                if 类 is None:
                    continue
                料 = '%s|%s|%d|%s' % (self._盐, 名, 序, _行料(行))
                标 = int(hashlib.sha256(
                    料.encode('utf-8', 'replace')).hexdigest()[:8], 16) % 10000
                if not self._该毒(标):
                    continue
                # ⛔ **标记要拿"挖掉这一格之后"的行去算** —— 验的人手里
                # 只有这一行，他得能自己重算出来。先算，再改。
                标 = 指纹(行, i)
                新 = 编(类, 格[0], 格[1], 标)
                if 新 is None:
                    continue
                行[i] = (格[0], 新)
                毒了 += 1
                break                            # 一行最多毒一格
            else:
                # 这一行没毒成（没有值钱的列）。**畸形只在很深的地方补**
                # ——计划 §七·三："响的那种必须埋在深的地方（第几千行、
                # 很少被看的字段），让他先投入大量工作才碰到"。
                if self._畸形 and 序 and 序 % self._间隔 == 0:
                    if self._补畸形(行, 列名):
                        self._畸形过的行数 += 1
        self._毒过的行数 += 毒了
        if 毒了:
            self._说('[玄武] 往镜里这一手下了 %d 处饵' % 毒了)
        return 行们

    def _该毒(self, 标):
        """这一行毒不毒。**由标记定，所以反复拉还是那几行。**"""
        return 标 < int(self._率 * 100)

    def _补畸形(self, 行, 列名):
        """
        补一个**畸形**值：响的那一种，打他的工具。

        只在很深、很少被看的行上补（调用方按行号筛过），而且挑一个
        **不是键**的格子 —— 畸形值本身就是要让他解析出错，碰了键列
        等于当场把镜的结构也弄坏了。
        """
        for i, 格 in enumerate(行):
            名 = 列名[i].lower() if i < len(列名) else ''
            if _是键(名) or not isinstance(格[1], str):
                continue
            # 一个合法客户端读下去不会崩、但**按结构解析的脚本会**的东西：
            # 值里带一个内嵌的引号和换行。
            行[i] = (格[0], '%s";\n' % 格[1])
            return True
        return False

    # ── 状态 ────────────────────────────────────────────────────────

    def 报数(self):
        return {'开着': self._开, '投毒率': self._率, '畸形': self._畸形,
                '畸形间隔': self._间隔,
                '毒过的行数': self._毒过的行数,
                '畸形过的行数': self._畸形过的行数,
                '有盐': bool(self._盐)}


def _列名(手):
    """这一手的列名。**从 `手.请求` 里拿** —— 那是 `包闸口` 填进去的。"""
    请 = getattr(手, '请求', None)
    if isinstance(请, dict):
        列 = 请.get('列名')
        if isinstance(列, (list, tuple)):
            return [str(x) for x in 列]
    return []


def _行料(行):
    """一行拿来拌盐的料。**值和类型号都要**，不然两种类型同值会撞标记。"""
    块 = []
    for 格 in 行:
        try:
            类号, 值 = 格
        except (TypeError, ValueError):
            continue
        if isinstance(值, (bytes, bytearray)):
            值 = bytes(值).hex()
        块.append('%d:%s' % (类号, 值))
    return '~'.join(块)


def _是键(名):
    return any(词 in 名 for 词 in _不许碰)


def _分类(名):
    for 类, 词们 in _值钱的:
        if any(词 in 名 for 词 in 词们):
            return 类
    return None


def 编(类, 类号, 旧值, 标):
    """
    照分类编一个**格式全合法**的新值。编不出来就回 `None`（不碰）。

    ⚠ **`玄武_镜` 也用这一个函数造它那个假世界** —— 镜里的每一行都从这儿
    出来，所以这里编出来的东西必须"看着像真的"：格式全合法、彼此不打架。
    这不是两个模块互相调用（那是不许的），是**共用一份编造器**：`镜` 造
    整个世界，`饵` 事后往其中约 1% 的格子上刻水印，两边编出来的值必须是
    同一个谱系的，不然他跨表一看就看出来了。

    类型对不上的一律不碰：`INT` 那格的手机号是说不通的，硬换会把镜里的
    结构弄拧 —— 而镜的结构是照真库抄的。
    """
    值 = 旧值
    if 类 in ('手机', '身份证', '邮箱', '姓名', '地址'):
        if 类号 is not None and 类号 != 3:       # `schema.TEXT`
            return None
        if 值 is not None and not isinstance(值, str):
            return None
        if 类 == '手机':
            return _编手机(标)
        if 类 == '身份证':
            return _编身份证(标)
        if 类 == '邮箱':
            return _编邮箱(标)
        if 类 == '姓名':
            return _编姓名(标)
        return _编地址(标)
    if 类 in ('金额', '日期'):
        if isinstance(值, bool) or not isinstance(值, (int, float)):
            return None
        # ⛔ **时间列单独一条路，单位必须是毫秒。**
        # 这里踩过一次：时间列按名字归到"日期"，然后走下面"挪个小数"那条路
        # —— 编出来一个 `987`，引擎当场拒收（"看着像秒"），整张表的假数据
        # 一行都灌不进去。**列名一样，单位可以差一千倍。**
        if 类号 == 5:                            # `schema.TIME`
            挪 = (标 % 86400) * 1000             # 一天之内，毫秒
            return int(值) + 挪
        # 数：**在原来的数上挪一个由标记定的小量**，不跳到离谱的值上。
        if isinstance(值, float):
            挪 = (标 % 1000) / 100.0
            return round(值 + 挪, 2)
        挪 = 标 % 1000
        return int(值) + 挪
    return None


#: 编普通文本用的词（不属于上面任何一类值钱的列时用它）
_词 = ('样本', '记录', '条目', '批次', '条目组', '样例', '数据项', '编号组')


def 编行(列们, 序, 盐='', 纪元=None):
    """
    照一行的列定义编**一整行**假数据。**`玄武_镜` 灌数据走的就是这里。**

    `列们` 是一串 `(列名, 类型号, 可空, 是不是主键)`。回一行值（list），
    和 `Gate.fill` 要的形状一样（按位置对齐、纯值、不带类型号）。

    ⛔ **主键列必须唯一** —— 镜里的表也按主键直取，主键撞了就是两个坑：
    镜的数据自相矛盾（他能看出来），而且灌到一半会失败。所以主键一律用
    `序` 编，别的列随便。

    ⛔ **这个函数只认列的名字和类型，永远拿不到真库里的任何一行值。**
    调用方手上根本没有真数据（见 `玄武_镜` 那条铁律），这是结构上就
    断掉的，不是靠自觉。

    `纪元` 是编时间用的基准（毫秒），配置键 **`玄武饵纪元`**。
    **不给就用模块常量** —— 那是"以前那个数"，一个字不变。
    """
    行 = []
    for i, 列 in enumerate(列们):
        try:
            名, 类号, 可空, 是主键 = 列
        except (TypeError, ValueError):
            continue
        名 = str(名)
        低 = 名.lower()
        标 = int(hashlib.sha256(('%s|%s|%d' % (盐, 低, 序))
                                .encode('utf-8', 'replace')
                                ).hexdigest()[:8], 16) % 10000
        if 是主键:
            行.append(_主键值(类号, 序, 标))
            continue
        类 = _分类(低)
        if 类 is not None:
            编出 = 编(类, 类号, _苗子(类, 纪元), 标)
            if 编出 is not None:
                行.append(编出)
                continue
        行.append(_普通值(类号, 序, 标, 可空))
    return 行


#: 编时间用的基准（毫秒）。**不能给 `0`** —— 那是 1970 年，
#: 引擎有一条 `_MS_SANITY_FLOOR`（1973 年前后的值一律当"你给的是秒"退回）。
#: 配置键 `玄武饵纪元`，从 `编行(…, 纪元=…)` 传进来；不给就是这一个。
_纪元 = 1700000000000


def _苗子(类, 纪元=None):
    """
    给 `编` 一个"原来长什么样"的苗子 —— 它只拿它判类型。

    苗子只在 `玄武_镜` 那条路上用（真库的行它拿不到，也不许拿）：镜里
    没有"原来的值"，所以给一个**像样的起点**，让编出来的东西落在常识
    范围里。`饵` 那条路上苗子换了真的旧值，起点就是数据自己的值。
    """
    if 类 in ('手机', '身份证', '邮箱', '姓名', '地址'):
        return 'x'
    if 类 == '金额':
        return 0.0
    return _纪元 if 纪元 is None else 纪元


def _主键值(类号, 序, 标):
    """主键：**唯一**。整数就是行号；文本就是拼出来的号。"""
    if 类号 == 1:                                # INT
        return 序 + 1
    if 类号 == 2:                                # FLOAT
        return float(序 + 1)
    if 类号 == 5:                                # TIME
        return 1700000000000 + 序 * 1000
    if 类号 == 4:                                # BLOB
        return ('主键%08d' % 序).encode('utf-8')
    return 'K%08d' % 序


def _普通值(类号, 序, 标, 可空):
    """普通列：按类型编一个不出格的。真编不出来就 `None`（可空时）。"""
    if 类号 == 1:                                # INT
        return 标 % 100000
    if 类号 == 2:                                # FLOAT
        return round((标 % 100000) / 100.0, 2)
    if 类号 == 5:                                # TIME
        return 1700000000000 + (序 * 37 + 标) * 1000
    if 类号 == 4:                                # BLOB
        return ('字节%06d' % (标 % 1000000)).encode('utf-8')
    # TEXT（和一切没认出来的）
    return '%s%05d' % (_词[标 % len(_词)], 序)


def 造饵台(值=None, 说=None, 盐=''):
    """造一台饵，给 `城.登记('饵', …)` 用。盐一般传账本那一个。"""
    return 饵(值, 说=说, 盐=盐)
