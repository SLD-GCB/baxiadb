def 备份根从库(库路径, 配的=None):
    """
    备份放在哪儿。参数必须是**这个库的真路径**，见上面那段警告。

    `配的` 是配置里那条 `备份目录`：

        **空 / 不给**  →  `<库目录>/备份`（老位置，跟库同一块盘）
        **填了**       →  就用它，原样（相对路径按进程当前目录算）

    ⛔ **空着一定要回老位置，不能回 `None` 也不能抛。** 这一条是"能挪
    出去"的口子，不是"必须挪出去"的规定：填了才是改，不填就一个字节都
    不变。老位置那几份备份是**用户手上仅有的东西**，这一格读错一次就是
    界面上看不见它们。
    """
    if not 库路径:
        raise ValueError('没有库路径就算不出备份放哪儿')
    配的 = (配的 or '').strip() if isinstance(配的, str) else ''
    if 配的:
        return os.path.abspath(os.path.expanduser(配的))
    return os.path.join(os.path.dirname(os.path.abspath(库路径)), 备份目录名)


def 备份根按配置(库路径):
    """
    `备份根从库` 再加一步"自己去读配置里那条 `备份目录`"。

    ⛔ **三个调用点全得走这一条**（浏览页那个按钮 / 加密页 / 关窗口的
    提醒）。各读各的配置文件就是**三把尺子**，而分岔的样子最难查：
    "按钮备到 E 盘去了，恢复那一页还在 D 盘找" —— 一份备份明明在，
    界面上说没有。
    """
    try:
        # `配置` 在这儿 import，不放文件顶上：放上去就等于"谁 import 备份
        # 谁就得把 `配置`（进而 `arena` / `syntax`）一起拖进来"，而备份是
        # 个纯文件层的活，`store_format` 之外一个引擎模块都不该认得。
        import 配置 as _配置
        值, _ = _配置.读()
        配的 = str((值 or {}).get('备份目录') or '')
    except BaseException:
        # ⛔ **读不动就回老位置，不抛、不回 `None`。** 配置文件是垃圾、
        # 没权限、盘不在了 —— 这些都会走到这儿，而这一格上"回老位置"
        # 正是最有可能找得到那些备份的那一支。
        配的 = ''
    return 备份根从库(库路径, 配的)


def 能写进(目录, 叫法='这个目录'):
    """
    这个目录**建得出来、也确实是个目录**吗。建不出来就抛 `ValueError`，
    话说成中文，并且**指名道姓说是哪一格配置**。

    ⛔ **为什么要有这一步，而不是让 `makedirs` 自己抛。** 裸 `makedirs`
    在 Windows 上抛出来的是

        [WinError 3] 系统找不到指定的路径。: 'Q:\\'
        [WinError 123] 文件名、目录名或卷标语法不正确。: '...\\钥*匙'
        [WinError 183] 当文件已存在时，无法创建该文件。: '...\\我是个文件.txt'

    三句话里**没有一句说得出该去改哪儿** —— 而这三句对应的动作分别是
    "换一个存在的盘"、"把非法字符去掉"、"你指的其实是个文件"。用户看到
    的是一串英文加盘符，第一反应是"软件坏了"。

    这一步还买了**次序**：`做备份` 里建目录是在**停 MySQL 口和拷几百 MB
    之后**才撞上的，而半个钟头白等一场只是因为配置里那一格写错了。
    调用方在**动手之前**（`界面_浏览.手动备份` 第 ② 步之前）先叫一遍，
    当场就能把人拦住。

    ⚠️ **不写探针文件。** 想真验"写得进去"得落一个字节，而那是往用户的
    备份目录里塞垃圾（`makedirs` 过得去而写不进去的情形，多半是盘满或者
    只读 —— 那两种在真拷的时候会自己炸，而且炸得清楚）。
    """
    不叫 = str(目录 or '').strip()
    if not 不叫:
        return True                     # 空 = 老位置，老位置由调用方给全
    路 = os.path.abspath(os.path.expanduser(不叫))
    try:
        os.makedirs(路, exist_ok=True)
    except OSError as 错:
        raise ValueError(
            '%s（%s）建不起来：%s\n\n'
            '多半是：盘符不存在、路径里有 Windows 不认的字符'
            '（< > : " | ? * 这些），或者没有写权限。\n'
            '去「设置」页改那一格 —— 填一个已经存在的目录最省事。'
            % (叫法, 路, 错))
    if not os.path.isdir(路):
        raise ValueError(
            '%s（%s）不是一个目录 —— 这个位置上是个文件。\n\n'
            '去「设置」页改那一格。' % (叫法, 路))
    return True


def 装在库里吗(库根, 别的):
    """
    `别的` 是不是落在 `库根` **里面**（或者就是它本身）。

    拿来在动手之前拦住一种配置：`备份目录` / `备份钥匙目录` 指到库自己
    底下去。⛔ **这种配法两头都坏，而且坏法完全不同：**

      - **`备份钥匙目录` 指到库根里**（或者一个库名文件夹上）：钥匙文件
        落进库根。而 `指纹(库根)` 摘的是**库底下所有文件**，于是"备份自己
        改了库" ⇒ `已备份过吗` 永远回"没备过" ⇒ **关窗口那个提醒一直弹**，
        人点几次「去备份」都是白跑（实测过）。
      - **`备份目录` 指到库根里更糟**：`做备份` 把库往自己里面拷，
        拷出来的那一份底下又有一个"备份"……`备份/甲-001/备份/甲-001/…`
        一层套一层，**直到 `[WinError 206] 文件名或扩展名太长` 才炸**，
        而且中途已经写了几百 MB 的垃圾（实测过）。

    两种都是"设错了"而不是"库坏了"，所以拦在**动手之前**说清是哪一格，
    比让它在拷到一半时炸成一句 Windows 报错好得多。

    判的是**绝对路径的前缀**，两边都过 `normcase`：Windows 上盘符和路径
    大小写不敏感，不归一的话 `d:\\库` 和 `D:\\库` 会判成两处地方。
    """
    if not 别的:
        return False
    甲 = os.path.normcase(os.path.abspath(库根)).rstrip(os.sep)
    乙 = os.path.normcase(os.path.abspath(别的)).rstrip(os.sep)
    return 乙 == 甲 or 乙.startswith(甲 + os.sep)


def 盘(路):
    """
    这条路落在哪一块盘上。**UNC 的"盘符"是整个 `\\\\主机\\共享`。**

    本地路径回 `C:` 这种；认不出盘符的（POSIX 上的 `/mnt/x`）回空串 ——
    那种情况下两个空串会"相等"，于是同盘判成真。**这是故意的**：判不出
    来的时候宁可**多报一次警**，也不要漏报。
    """
    if not 路:
        return ''
    try:
        盘符 = os.path.splitdrive(os.path.abspath(路))[0]
    except (TypeError, ValueError, OSError):
        return ''
    return 盘符.rstrip('\\/').lower()


def 同盘吗(库根, 备份根):
    """
    备份和库是不是在同一块盘上。回 `(同盘, 一句话)`，**不抛**。

    ⚠️ **这一条只判得出"同不同盘"，判不出"同不同机"。** 网络共享挂成
    `Z:` 之后，从盘符上看和本地盘一模一样 —— 想真判同机得去看
    `\\\\主机\\共享` 那种路径形状，而挂载盘看不出来。计划 §八·七 第 4
    条写的是"同盘同机"，这里**只落了判得准的那一半**，另一半说在明处，
    别让人以为这一句已经把同机也管了。

    ⛔ **判出来是"同盘"，也只是报一声，绝不挡着不让备。** 挡下来的后果
    不是"他去挪个位置"，多半是**他干脆不备了** —— 拿一次提醒换掉唯一的
    一份备份，那是净亏。默认配置下本来就是同盘，真要拦，开箱第一次备份
    就被拦下了。
    """
    甲, 乙 = 盘(库根), 盘(备份根)
    if not 甲 or not 乙:
        return True, ('备份和库的盘认不出来（%s / %s）——'
                      '认不出来就按"同一块盘"提醒你一下。' % (库根, 备份根))
    if 甲 == 乙:
        return True, ('备份和库在**同一块盘**上（都是 %s）：盘一坏，'
                      '两样一起没。' % 甲.upper())
    return False, ''


# ── 备份钥匙：落在第三处的那把锁 ────────────────────────────────────
#
# **它和库那把锁是同一套东西**（`玄武_钥.锁`），只是标记不放在库目录里。
# 库、备份、钥匙三样分开，任丢一样都不足以打开 —— 这是末层「锁死备份」
# 的正身。一把钥匙一份备份 ⇒ 删掉哪一份的钥匙，就只有那一份永久打不开。
#
# ⛔ **第三处不配 = 不做这件事**（`钥匙根按配置` 回空串）。理由：改默认
# 行为 = 开箱第一次备份就和以前不一样，而这个模块存在的全部意义是
# "数据别丢" —— 没配就一直走老路，界面上明说那几个备份没锁死。


def 钥匙根按配置(库路径):
    """
    第三处放在哪儿 —— 配置里那条 `备份钥匙目录`。**空着回空串**。

    `库路径` 只在"要按库名分一层"的时候用得上，这一版**不分层**：一个人
    多半就一套备份，分了反而难找。参数留着是为了以后要分的时候不用改
    调用点。

    ⛔ 读不动配置就回空串（= 不做重加密），**不抛** —— 和
    `备份根按配置` 同一条：这一格上的降级方向是"退回老路"，
    不是"把备份拦下来"。
    """
    try:
        # 同 `备份根按配置`：`配置` 在这儿 import，不放文件顶上。
        import 配置 as _配置
        值, _ = _配置.读()
        配的 = str((值 or {}).get('备份钥匙目录') or '').strip()
    except BaseException:
        配的 = ''
    if not 配的:
        return ''
    return os.path.abspath(os.path.expanduser(配的))


def 钥匙文件名(份名):
    """`梼杌-20260913-213005` → `梼杌-20260913-213005.钥匙.json`。"""
    return '%s%s' % (份名, 钥匙名后缀)


def 钥匙路(钥匙根, 份名):
    """这一份备份的钥匙文件落在哪儿。"""
    if not 钥匙根:
        raise ValueError('没配备份钥匙目录，就没有"第几处的钥匙"这一说')
    return os.path.join(钥匙根, 钥匙文件名(份名))


def 造备份钥匙(钥匙根, 份名, 口令, 库名='', 库指纹=None):
    """
    给这一份备份造一把钥匙，**当场落到第三处**。回 **`(钥匙文件的路, 密文)`**。

    ⛔ **必须在拷任何密文之前叫它**（和 `锁` 那条"标记先落、密文后写"
    同向）。反过来的残局更坏：备份目录**看着是完整的**、`列备份` 会把它
    列出来，而它打不开 —— 那正是这个模块最不能出的东西。

    ⚠️ **顺手把 `密文` 一起还回去，不是图方便。** 拿它得跑一遍
    `pbkdf2`，而 `pbkdf2` 是**一百万次迭代**（`玄武_钥._迭代`）——
    实测一次约 0.3 秒。调用方要是拿到路之后自己再 `开备份钥匙` 推一遍，
    每备一份就白烧 0.3 秒，而且那 0.3 秒刚好落在"按了备份、界面不动"
    的那一段上。**一次口令只推一次。**

    ⚠️ `锁.造在` **每一把都新抽盐、新抽随机数**，所以就算两次用同一句
    口令，两把钥匙的钥匙流也不一样。同一个库的几份备份**互不通用**，
    删掉哪一份的钥匙就只有那一份死。

    `库指纹` 是**备份那一刻库的密文摘要**（`指纹戳(库根)`），只给
    `已备份过吗` 用，不参与加解密。读不出来（`None`）就不记 —— 那
    一份的"备过没有"退回比字节，不影响能不能恢复。

    ⚠️ **迭代 / 盐长 / 块字节三样照配置走，但它们都写进钥匙标记里**
    （`锁.造在`），`开备份钥匙` 认的是标记里那一份。所以**改了设置不会
    把已有的备份钥匙弄坏** —— 和库那把锁同一条道理，只是落在第三处。
    **块字节尤其要紧**：它一变，同一句口令算出来的密钥流整个不一样，
    那一份备份就永远是乱码了。
    """
    import 玄武_钥 as _钥
    import 配置 as _配置
    值 = _配置.读()[0]
    路 = 钥匙路(钥匙根, 份名)
    锁, 标记 = _钥.锁.造在(路, 口令, 库名,
                          迭代=值.get('玄武钥迭代'),
                          盐字节=值.get('玄武钥盐长'),
                          块字节=值.get('玄武钥块字节'))
    标记['份名'] = 份名
    if 库指纹 is not None:
        标记['库指纹'] = 库指纹
    _钥.锁.写标记在(路, 标记)
    return 路, 锁.密文()


def 读备份钥匙(钥匙根, 份名):
    """
    只看这一份的钥匙文件里写了什么，**不问口令、不解密**。回标记或 `None`。

    ⛔ **读坏了回 `None`，不抛。** 这个口子会被 `已备份过吗` 在一堆份上
    循环着叫，而那个调用点跑在**界面线程**上（关窗口的提醒）—— 一个
    读不动的钥匙文件把弹窗整条路炸掉，比"那一份不算数"坏得多。
    """
    import 玄武_钥 as _钥
    try:
        return _钥.锁.读标记(钥匙路(钥匙根, 份名))
    except BaseException:
        return None


def 开备份钥匙(钥匙根, 份名, 口令):
    """
    用备份口令开一把备份钥匙，**回 `密文` 对象**（`玄武_钥.密文`）。

    `口令不对` 抛 `锁错` —— 和库那把锁一样，是当场认出来的，不是等到
    读出乱码。**调用方要接住它**，因为这条路上"输错口令"是家常便饭。

    ⚠️ **钥匙文件不在的时候，报的是这一份的话，不是库那把锁的话。**
    `锁.开在` 的原话是「这儿没上锁（没有 …）」—— 那是给**库**说的。
    摆在备份这儿，用户看到的是"这儿没上锁"，而他明明拿着一份备份。
    """
    import 玄武_钥 as _钥
    路 = 钥匙路(钥匙根, 份名)
    if not os.path.exists(路):
        raise _钥.锁错('这一份（%s）的钥匙不在 %s。没有那把钥匙，'
                       '这份备份永远是乱码。' % (份名, 钥匙根))
    return _钥.锁.开在(路, 口令).密文()


def 毁备份钥匙(钥匙根, 份名):
    """
    **锁死这一份** —— 把它那把钥匙删掉。回真删了没有。

    ⛔ **不可逆，没有撤销。** 删掉之后那一份备份**永远是乱码** ——
    这不是"弄坏了"，这是设计本身：拿你的备份换他永远拿不到。
    所以它必须**人确认**（开发计划 §八·六 二级动作）。

    ⚠️ 它**只删钥匙文件，一个字节的备份都不动**。备份还完整地躺在那儿，
    只是没人打得开了 —— 留着的意义是"哪天钥匙回来了还能开"，而不是
    "删掉它就安全了"。
    """
    路 = 钥匙路(钥匙根, 份名)
    try:
        if os.path.exists(路):
            os.remove(路)
            return True
    except OSError:
        return False
    return False


def 列钥匙(钥匙根):
    """
    第三处现在有哪些钥匙：`{份名: 标记}`。**读不动的那些直接不列。**

    给界面用（"这几份有钥匙、那几份没有"）。空目录、没配、读不动，
    一律回空字典 —— 这个口子只回答"手上有什么"，不负责报错。
    """
    出 = {}
    if not 钥匙根:
        return 出
    try:
        名们 = sorted(os.listdir(钥匙根))
    except OSError:
        return 出
    for 名 in 名们:
        if not 名.endswith(钥匙名后缀):
            continue
        份 = 名[:-len(钥匙名后缀)]
        标记 = 读备份钥匙(钥匙根, 份)
        if 标记 is not None:
            出[份] = 标记
    return 出


# ── 换钥匙 ──────────────────────────────────────────────────────────


def 跟钥匙走(相):
    """
    相对路径 `相`（`/` 分隔）上的字节要不要跟着换钥匙。

    认法是**"在 `r/` 底下 + 后缀是 region/bloom"**，不是文件全名 ——
    区号是八位十六进制、桶号三位，枚举不出来。`catalog` 和 `玄武/`
    底下的东西一律不动。
    """
    头 = 相.split('/', 1)[0]
    if 头 != store_format.REGION_DIR or '.' not in 相:
        return False
    return 相.rsplit('.', 1)[-1].lower() in _换钥匙的后缀


def _换成另一把钥匙(源路, 目标路, 甲, 乙):
    """
    把 `源路`（甲钥匙的密文）按绝对偏移换成乙钥匙的密文，写进 `目标路`。

        乙密文 = 乙流 ⊕ 明文 = 乙流 ⊕ 甲流 ⊕ 甲密文

    两句 `解` / `加` 就是"先解回明文、再按乙加密"，**明文一秒钟都不落盘**
    （它只活在内存里那一个块里）。偏移用的是**文件内的绝对偏移**，两边
    一模一样 ⇒ 区文件的偏移寻址全部有效。
    """
    with open(源路, 'rb') as 入, open(目标路, 'wb') as 出:
        位 = 0
        while True:
            块 = 入.read(_换块)
            if not 块:
                break
            出.write(乙.加(位, 甲.解(位, 块)))
            位 += len(块)


def _拷着换钥匙(库根, 目标, 甲密文=None, 乙密文=None, 不要=()):
    """
    逐文件拷 `库根` 到 `目标`，**跟着钥匙走的那些换一遍钥匙**。

    `甲密文=None` = 源是明文库：不换，原样拷（跟 `copytree` 一样）。
    `不要` 是**不要拷过去的相对路径**（`/` 分隔）—— 备份那边用它把
    `<库>/玄武/锁.json` 挡在外面。⛔ 那一份**必须挡掉**：拷了它，备份就
    又自足了（拿库口令照样开），末层那四条第一条当场作废。

    ⚠️ **`目标` 是现造的，调用方已经建好了**（`os.makedirs`）。这里
    只管往里放。
    """
    不要 = set(不要)
    换了 = 0
    for 基, _, 文件们 in os.walk(库根):
        for 名 in sorted(文件们):
            源 = os.path.join(基, 名)
            相 = os.path.relpath(源, 库根).replace(os.sep, '/')
            if 相 in 不要:
                continue
            到 = os.path.join(目标, *相.split('/'))
            os.makedirs(os.path.dirname(到), exist_ok=True)
            if 甲密文 is not None and 乙密文 is not None and 跟钥匙走(相):
                _换成另一把钥匙(源, 到, 甲密文, 乙密文)
                换了 += 1
            else:
                shutil.copy2(源, 到)
    return 换了


def 份名(库名, 时刻=None):
    """
    `梼杌-20260913-213005`。

    **定宽、可字典序排**：时间戳一律 15 个字符，所以同一个库的几份之间
    按名字排就是按时间排，不用去读目录的 mtime（目录的 mtime 会随着往里
    增加文件而变，靠不住）。
    """
    时刻 = 时刻 if 时刻 is not None else time.time()
    return '%s-%s' % (库名, time.strftime('%Y%m%d-%H%M%S', time.localtime(时刻)))


def _时刻从名(名):
    """从份名尾巴上把时间戳解回来。解不出来回 None。"""
    尾 = 名[-15:]
    if len(尾) == 15 and 尾[8] == '-':
        try:
            return time.mktime(time.strptime(尾, '%Y%m%d-%H%M%S'))
        except ValueError:
            return None
    return None


def _是库(路):
    """认招牌不认名字 —— 和 `霸下之躯.是库` 是**同一把尺子**（`catalog`）。"""
    return os.path.isfile(os.path.join(路, store_format.CATALOG_NAME))


def 列备份(根):
    """
    列出备份根下现有的份：`[(名, 路, 时刻, 字节)]`，**新的在前**。

    只认"里面有 `catalog`"的目录 —— 别的东西（用户的杂物、拷了一半的）
    一概不算，当作不存在。读不动就回空的。
    """
    出 = []
    try:
        名们 = sorted(os.listdir(根))
    except OSError:
        return 出
    for 名 in 名们:
        路 = os.path.join(根, 名)
        if not (os.path.isdir(路) and _是库(路)):
            continue
        时刻 = _时刻从名(名)
        出.append((名, 路, 时刻, 目录字节(路)))
    # 解得出时刻的按时刻排；解不出的（手工改过名的）沉到最底下，
    # 不能让它们冒到"最新的一份"那个位置上。
    出.sort(key=lambda 条: (条[2] is None, -(条[2] or 0.0)))
    return 出


# ── 「库的内容」是什么：全项目就这一把尺子 ────────────────────────────
#
# ⛔ **凡是判"这个库变没变"、量"这份备份多大"的地方，都走 `是库内容吗`。**
# 谁也别自己再判一遍 —— 判成两把尺子的症状是**假"已备份过"**（该提醒的
# 时候不提醒），正是这个功能最不能出的错。

#: 挂件的住处。底下除了锁，**一样都不是库的真相**。
玄武目录 = '玄武'


def 是库内容吗(相):
    """
    相对路径 `相`（`/` 分隔）算不算**这个库的内容**。

        算     `catalog`、`r/**.region`、`玄武/锁.json`
        不算   `玄武/` 底下**除锁以外的一切** —— `账.jsonl`（记账流水）、
               `镜/`、`镜.json`，往后玄武再落什么新东西也一样

    **锁算、别的流水不算：** 锁是"这个库怎么开"的说明书，换了它就是这个
    库的身份变了；而账和镜按项目那条硬约束是**衍生结构，必须丢得掉**
    （`baxia-derived-state-must-be-droppable`）—— 账里没有一样东西是库的
    真相，它只是"发生过什么"的记录。

    ⛔ **把流水算进来的后果是实测过的。** 玄武每接一个连接就往 `账.jsonl`
    追加一行（爬虫重连一下就记一笔，**一行数据都不用写**），于是库的摘要
    跟着变，"备过没有"永远回"没备过" ⇒ **关窗口那个备份提醒每次都弹、
    点几次「去备份」都是白跑**。2026-09-14 用户报的就是这条，盘上逐文件
    比出来：`catalog` 和 256MB 数据区**一个字节不差**，只有账本长了 615
    字节。

    明文库（没有 `玄武/` 目录）不受影响：它底下每一样都算。
    """
    if not 相.startswith(玄武目录 + '/'):
        return True
    # 锁的名字由 `玄武_钥` 说了算 —— 在这儿再写一遍 `'锁.json'` 就是第二把
    # 尺子，哪天那边改了名，这儿的"算"会静悄悄地跟着错。
    import 玄武_钥 as _钥
    return 相 == 玄武目录 + '/' + _钥.标记名


def 目录字节(路):
    """
    一个目录底下**算库内容的那部分**一共多少字节，**只 stat，不读内容**。

    ⛔ **走 `是库内容吗` 那把尺子**，所以玄武的流水（`账.jsonl`、`镜/`）
    不算在里头。"这份备份多大"和"这个库变没变"必须是同一个口径：`已备份
    过吗` 拿这个数当**先比字节筛掉**的快捷判（份多了也不慢），它要是比
    `指纹` 多算了流水，筛出来的结果就是"一份都对不上" —— 实测过，原话
    是「备份根里 1 份，没有一份的字节数对得上。」
    """
    根 = os.path.abspath(路)
    总 = 0
    for 基, _, 文件们 in os.walk(根):
        for 名 in 文件们:
            全 = os.path.join(基, 名)
            if not 是库内容吗(os.path.relpath(全, 根).replace(os.sep, '/')):
                continue
            try:
                总 += os.path.getsize(全)
            except OSError:
                pass                 # 统计用的，读不到就当 0，不为它报错
    return 总


# ── 指纹与比对 ──────────────────────────────────────────────────────
#
# **这两条是只读的**，而且很快（catalog 49KB + 每区 8KB），所以关软件那条
# 路可以在界面线程上直接调，不用投活。


def _一条摘要(路, 大小, 名):
    with open(路, 'rb') as fh:
        if 名 in 整份摘的名字 or 大小 <= 2 * 摘要窗口:
            料 = fh.read()            # 小文件整份摘，比拼两段还省事
        else:
            头 = fh.read(摘要窗口)     # 区域头在这儿：data_tail / record_count
            fh.seek(大小 - 摘要窗口)   # 新记录落在这儿：data_tail 是从尾往前让的
            料 = 头 + fh.read(摘要窗口)
    return hashlib.sha256(料).hexdigest()


def 指纹(库根):
    """
    一块永久存储区的指纹：`{相对路径: (字节数, 摘要)}`。

    **相对路径也进来了**（它是字典的键），所以"多了/少了文件"这件事本身
    就是可比的 —— 封区多一个 `.bloom`、压实少两个 `.region`，都抓得到。

    ⛔ **只有"库的内容"进来，`是库内容吗` 说了算。** 玄武的流水（`账.jsonl`、
    `镜/`）不算 —— 它每接一个连接就长一行，算进来的话"备过没有"永远回
    "没备过"，关窗口提醒每次都弹（原委写在 `是库内容吗`）。

    目录读不动、文件读不了（权限、被独占）时回 `None`，**不抛**：上层拿到
    None 就当"比不了"，退化成"弹一次提醒" —— 方向永远是多提醒，不是漏
    提醒。
    """
    出 = {}
    try:
        for 基, _, 文件们 in os.walk(库根):
            for 名 in 文件们:
                路 = os.path.join(基, 名)
                相 = os.path.relpath(路, 库根).replace(os.sep, '/')
                if not 是库内容吗(相):
                    continue
                大小 = os.path.getsize(路)
                出[相] = (大小, _一条摘要(路, 大小, 名))
    except OSError:
        return None
    return 出


def _指纹戳(现):
    """
    把 `指纹()` 那份字典压成**一串**。`现` 是 `None` 就回 `None`。

    ⛔ **压之前先排序。** `os.walk` 给的次序不保证稳定，不排序的话同一个
    库两次算出来的戳可能不一样 —— 那会让"备过没有"随机地判错，而它错
    的那一边是**假"已备份过"**（该提醒的时候不提醒），正是这个功能最不能
    出的错。`separators` 去掉空格同理：它只是让串短一半，不影响判等。
    """
    if 现 is None:
        return None
    return hashlib.sha256(
        json.dumps(sorted(现.items()), ensure_ascii=False,
                   separators=(',', ':')).encode('utf-8')).hexdigest()


def 指纹戳(库根):
    """
    `指纹(库根)` 压成一串 —— **记在钥匙文件里的那一笔**（`标记['库指纹']`）。

    为什么要它：换过钥匙的备份和库**再也不可能逐字节一样**，所以
    "备过没有"没法比字节。这一笔是备份那一刻库的密文摘要，关窗口时
    只比它 —— **不用备份口令、不用读备份**（那两样在那一刻都没有）。
    """
    return _指纹戳(指纹(库根))


def 一模一样吗(库根, 备份路):
    """这两份（库 / 备份）内容一样吗。任一边读不动就判"不一样"。"""
    甲 = 指纹(库根)
    if 甲 is None:
        return False
    乙 = 指纹(备份路)
    return 甲 == 乙


def 已备份过吗(库根, 备份根, 钥匙根=''):
    """
    这份库**现在这个样子**，在备份根里有没有一份一模一样的。

    回 `(有没有, 匹配到的那份名或 None, 凭什么)`。

    两种份两种比法，**看它有没有钥匙**：

        没钥匙（明文备份 / 换钥匙之前备的老份）
            比字节 —— 先比字节总数把绝大多数份筛掉（只 stat 不读内容），
            对得上的才摘摘要。份数多了也不会慢。
        有钥匙（换过的）
            比**钥匙文件里那一笔 `库指纹`**，一个字节的备份都不读

    ⛔ **三种比法的尺子必须是同一把** —— `指纹(库根)` 配 `目录字节`，
    两个都走 `是库内容吗`。要是哪一边把玄武的流水算了进来，两边就永远对
    不上，表现是**每次都提醒**（"先比字节"那道快捷判会先把唯一对得上的
    那份筛掉，连"最像的一份"都走不到）。

    ⛔ **第三格是"这句话凭什么说"**，摆给用户看。关窗口那个提醒原来一律
    说"这个库从上次备份之后又写过东西"，可它其实分不出这三种：

        库里的文件这会儿读不动，摘要根本算不出来（`指纹` 回 `None`）
        比过了，确实不一样 —— 而且能说出**哪几个文件**对不上
        一份的字节数都对不上

    头一种说成"又写过东西"是**冤枉人**，而用户只看得见那一句话，只能猜。
    所以把"凭什么"交上去让界面照实说。判的方向一个字不变：**判不出来
    照样提醒。**
    """
    现 = 指纹(库根)
    if 现 is None:
        return False, None, ('库里的文件这会儿读不动（没权限、被别的程序'
                            '占着、或者盘不在了），摘要压根算不出来。')
    戳 = _指纹戳(现)
    现在总共 = sum(条[0] for 条 in 现.values())
    几份 = 0
    最像的 = None
    for 名, 路, _, 字节 in 列备份(备份根):
        几份 += 1
        标记 = 读备份钥匙(钥匙根, 名) if 钥匙根 else None
        记的 = (标记 or {}).get('库指纹')
        if 记的:
            if 记的 == 戳:
                return True, 名, ''
            continue                 # 换过钥匙的份：字节比不了，只能看这一笔
        if 字节 != 现在总共:
            continue
        乙 = 指纹(路)
        if 乙 == 现:
            return True, 名, ''
        if 最像的 is None and 乙 is not None:
            最像的 = (名, 乙)
    if 最像的 is None:
        return False, None, (
            '' if not 几份 else
            '备份根里 %d 份，没有一份的字节数对得上。' % 几份)
    名, 乙 = 最像的
    差 = sorted(k for k in set(现) | set(乙) if 现.get(k) != 乙.get(k))
    return False, None, (
        '最像的那一份（%s）字节数一样，但有 %d 个文件对不上：%s%s'
        % (名, len(差), '、'.join(差[:5]), '……' if len(差) > 5 else ''))


# ── 做一份备份 ──────────────────────────────────────────────────────


def _确是备份根的孩子(路, 备份根):
    """
    要删的那个目录**必须正好是备份根的直接孩子**。

    这条是拿来保命的：`shutil.rmtree` 打错一个路径就是删一个库。所以只
    认"父亲一模一样、自己在父亲底下有名字"，`备份/` 自己、它的祖先、以及
    任何更深的路径一律拒掉。
    """
    甲 = os.path.abspath(路).rstrip(os.sep)
    乙 = os.path.abspath(备份根).rstrip(os.sep)
    return bool(os.path.basename(甲)) and os.path.dirname(甲) == 乙


def 会换钥匙吗(钥匙根='', 库密文=None):
    """
    这一份备份会不会走"另配一把钥匙"那条路。

    **界面拿它决定问不问那句备份口令** —— 两个条件缺一不可：

        没配第三处      → 没地方放钥匙，走老路（自足）
        库是明文的      → 没有钥匙可换，走老路（**明文备份本来就不用开**）

    写明在这儿而不是让调用方自己 `and` 一下：两个条件分在两个模块里，
    谁漏一个就是"界面问了口令、`做备份` 根本没用它"。
    """
    return bool(钥匙根) and 库密文 is not None


def 做备份(库根, 备份根, 份, 库密文=None, 钥匙根='', 备份口令=None,
          库名=None):
    """
    往 `备份根/份` 复制一份 `库根`，回新那份的完整路径。

    **这是本模块唯一写盘的东西，必须跑在工人线程上**（理由见模块头：一致性
    就来自"复制期间没有第二个写者"）。

    `钥匙根` + `库密文` 两样都给（`会换钥匙吗`）⇒ **走"另配一把钥匙"**：
    逐区按绝对偏移换成那把钥匙的密文，**`<库>/玄武/锁.json` 不拷过去**。
    少给一样就还是 `copytree`，一个字节都不变。

    `备份口令` 只在换钥匙那一路用得上。**它不落盘、不进日志**（口令的
    处置和库口令一样），丢了就是那些备份永久打不开 —— 这一点要跟人说。

    失败时**把拷了一半的那份删掉再抛** —— 一份缺文件的备份比没有备份更坏，
    因为它看起来像是有的。换钥匙那一路**还要顺手把刚落的钥匙收掉**：
    留着一个没有备份的钥匙，下次同一个份名会被 `造在` 挡下来。

    ⚠️ **这里是"先拷，不先删"。** 删旧备份是 `删几份`，而且调用方必须**等
    新的这份验过了再删**。反过来的话，盘满 / 拷贝中途出错时，人已经把旧的
    删了、新的又没成 —— 那一下是**净损失**，而备份这个东西存在的全部意义
    就是不让人净损失。所以本模块把这两步**拆成两个函数**，让调用方没有
    "顺手一起做了"的余地。
    """
    os.makedirs(备份根, exist_ok=True)
    目标 = os.path.join(备份根, 份)
    序 = 2
    while os.path.exists(目标):       # 同一秒备两次，加个尾巴，不覆盖
        目标 = os.path.join(备份根, '%s-%d' % (份, 序))
        序 += 1
    这一份 = os.path.basename(目标)

    换 = 会换钥匙吗(钥匙根, 库密文)
    乙密文 = None
    不要 = ()
    落了钥匙 = False
    if 换:
        # `玄武_钥` 在这儿 import，不放文件顶上：同 `配置`，放上去就等于
        # "谁 import 备份 谁就把城防那一套拖进来"。
        import 玄武_钥 as _钥
        if not 备份口令:
            raise ValueError('这一份备份要另配一把钥匙，得有一句备份口令。')
        # ⛔ **钥匙先落、密文后写**（`玄武_钥` 那条铁律，方向一致）。
        # 反过来的残局更坏：备份目录完整、`列备份` 列得出来，却打不开。
        # **说明书要挡在外面**：拷过去这份备份就又自足了。
        不要 = ('玄武/' + _钥.标记名,)
        # **一次口令只推一次 pbkdf2**（理由在 `造备份钥匙` 的 docstring 里）。
        _, 乙密文 = 造备份钥匙(钥匙根, 这一份, 备份口令,
                              库名 or os.path.basename(os.path.abspath(库根)),
                              指纹戳(库根))
        落了钥匙 = True

    try:
        if 换:
            os.makedirs(目标, exist_ok=True)
            _拷着换钥匙(库根, 目标, 库密文, 乙密文, 不要=不要)
        else:
            shutil.copytree(库根, 目标)
    except BaseException:
        # 拷了一半的那份要清掉（理由见上面那段）。**清不掉就把话说全**：
        # 异常本身照原样抛出去，但先把"还留着一堆残骸"这件事说出来 ——
        # 调用方拿到的是一句 `RuntimeError/copytree 的错`，看不到盘上
        # 还挂着一个名字长得像备份的目录。
        shutil.rmtree(目标, ignore_errors=True)
        没清掉 = os.path.exists(目标)
        if 落了钥匙:
            毁备份钥匙(钥匙根, 这一份)
        if 没清掉:
            raise RuntimeError(
                '拷贝中途失败了，而且**清不干净**：%s 还留在 %s。'
                '手工删掉它，别让它混在备份堆里。'
                % (os.path.basename(目标), 备份根))
        raise
    return 目标


def 删几份(备份根, 要删, 钥匙根=''):
    """
    删掉 `要删` 里那几份。**调用方必须先确认新的那份已经备好、也验过了。**

    每一条都过 `_确是备份根的孩子` 那道闸，一条不合法就**一条都不删**。

    `钥匙根` 给了的话，**顺手把那几份的钥匙也删掉**（配了第三处的库才
    有这一支；没配就一个字节都不多碰）。

    ⛔ **次序是死的：先删备份，再删钥匙。** 反过来的话，删完钥匙、备份
    却删不掉（别的进程占着、只读属性），盘上就留下一份**谁都打不开的
    备份**——那正是"锁死"最坏的样子，而这一趟的本意只是**腾地方**。
    按现在这个次序，最坏的结果是**多一个没人用的钥匙文件**，下次
    `删几份` 或者 `列钥匙` 看得见它，用户自己删掉就行：**不丢数据。**

    ⚠️ **不删钥匙的话第三处会越攒越多。** 一个备份删了、钥匙留着，
    那钥匙对不上任何东西（`列钥匙` 里那条"找不到对应的备份"就是它）。
    攒着看着无害，但它是**新一轮的"看不出来"**：等哪天真要毁一批钥匙，
    得先自己认一遍哪个是哪个——而那正是钥匙文件该替人做完的事。
    """
    for 路 in 要删:
        if not _确是备份根的孩子(路, 备份根):
            raise ValueError('拒删：%s 不是备份根底下的直接一份' % 路)
    for 路 in 要删:
        shutil.rmtree(路)
    if 钥匙根:
        for 路 in 要删:
            # 备份已经删掉了，钥匙删不掉也不再抛 —— 抛出去的话调用方会
            # 以为"备份没删掉"，而盘上的真相正好相反。
            毁备份钥匙(钥匙根, os.path.basename(路))
    return len(要删)


# ── 恢复 ────────────────────────────────────────────────────────────


def 恢复一份(备份路, 目标路, 备份钥=None, 新口令=None):
    """
    把一份备份**拷成一个正经的库**，回 **`(那个库的路径, 开它用的密文)`**。

    **恢复 = 反着拷一遍。** 没有别的花样：备份就是个完整的库目录，拷回去
    就能开。所以这里和 `做备份` 是同一件事换了方向 —— 同样"拷一半就把
    半份清掉"。

    **要不要重新上锁，看的是这一份带不带说明书**（`玄武/锁.json`），不是
    "调用方传没传钥匙"——理由写在下面判 `换` 那一段（那儿有一个真 bug 的
    来龙去脉）。换过钥匙的备份多一步**重新上锁**：

        备份   r/***  备份钥匙的密文，**目录里没有说明书**
        恢复   r/***  **新库自己的锁** —— 边解边重新加密，明文一秒钟不落盘

    ⛔ **新库的口令由人现在定**（`新口令`），不是把备份那把锁搬过来。
    搬过来的话新库的口令就是那句**备份口令** —— 而"改口令结构上做不到"
    （`玄武_钥` 那条：换口令 = 换主密钥 = 换密钥流 = 全库作废），
    那句口令就被钉死成你的库口令了。**恢复出来的该是一个正经的库**，
    不是一份"用别人的口令活着"的副本。

    ⚠️ 新库的锁**和那份备份彻底解绑**（新盐、新随机数、新口令）——
    这是恢复该有的样子：备份留着，新库是个独立的库。

    ⛔ **必须跑在工人线程上。** 理由和 `做备份` 不完全一样：这里不碰那个
    开着的库（源是备份、目标是新目录），一致性不是问题。要上工位是因为
    **这是一整趟几百 MB 的写盘**，摆到界面线程上就是界面卡到拷完为止。
    附带的好处是它和 `做备份` 排在同一条队上，两个大拷贝不会同时开跑。

    **原来那一份备份一个字节都不动。** 恢复是"拷出来"，不是"搬出来"——
    备份留在原地，恢复错了还能再来一次。这条是死的：这个模块里会删备份
    的只有 `删几份`，而它只在"新那份已经备好、也验过了"之后才被叫。

    ⛔ **目标已经在了就拒，绝不覆盖。** 覆盖一个库目录是**当场毁掉一个
    库**，而且 `copytree` 撞上已存在的目录本来就抛 —— 但这儿要在**动手
    之前**把话说清楚，别让人从一句 `FileExistsError` 里去猜。

    ⚠️ **第二格回的是"开这个新库用哪把钥匙"，调用方不能自己猜。**
    换过钥匙那一支回的是**刚造出来的新锁**（调用方手上只有备份钥匙，
    拿它开新库是开不了的——新库的密文是第三把钥匙加的）；没换那一支
    回 `None`，意思是"备份里带着它自己那把锁的说明书，你手上那把
    （或者明文那条路的空手）就是对的"。让调用方自己去推的话，两处
    各推一遍，早晚有一处推错，而症状是"恢复完了切不过去"。
    """
    if not _是库(备份路):
        raise ValueError('这不是一份备份（里面没有 catalog）：%s' % 备份路)
    if os.path.exists(目标路):
        raise ValueError(
            '目标已经在了：%s\n恢复是"拷成一个新库"，不覆盖任何东西'
            '——换个名字，或者先把那个挪开。' % 目标路)
    if os.path.abspath(目标路) == os.path.abspath(备份路):
        raise ValueError('源和目标是同一个目录，那等于自己拷自己。')

    # ⛔ **"这一份要不要重上锁"是盘上说了算，不是"调用方传没传钥匙"。**
    #
    # 判据是**这一份自己带不带说明书**（`玄武/锁.json`）：
    #
    #     带着 ⇒ 它是**自足**的（老路、明文都在这儿），逐字节拷过去就是一个
    #            好库，**不需要重上锁**。调用方手里那把钥匙是"开这一份、
    #            读它表清单用的"，**不是"备份钥匙"** —— 老路那条正是这样。
    #     没带 ⇒ 它是**换过钥匙**的那一种（`做备份` 换钥匙时故意没拷说明书），
    #            只能边解边重新加密，那时候才必须有备份钥匙 + 新口令。
    #
    # ⛔ **老代码把判据写成 `备份钥 is not None`，于是"自足备份 + 会话手里
    # 那把钥匙"被判成"换过钥匙的"** ⇒ 当场抛「这一份是换过钥匙的，恢复要
    # 一句新库口令」，而这一份**根本没换过钥匙**。后果是**界面上恢复一个
    # 加密库的备份每次都失败**（实测复现），而且那句错话把人指去"另配一把
    # 钥匙"这条根本不存在的路上 —— 用户只看得见这一句，只能猜。
    #
    # 两个记号（备份钥 / 新口令）现在只在**真换过钥匙**那一支才要求齐。
    # ⚠️ 剩下的洞写在这儿：一份换过钥匙的备份**没给钥匙**（`备份钥=None`）
    # 时，这一支会走 `copytree`，拷出来是个没有说明书、区文件又是别人那把
    # 钥匙加的密的东西 —— 看着像库，其实开不了。**它和明文备份在盘上分不出**
    # （两者都没有说明书），没有钥匙就判不了，所以只能由调用方认准了传。
    # 界面那条路不会走到：换钥匙那一支**一定**把钥匙传进来。
    换 = False
    if 备份钥 is not None:
        import 玄武_钥 as _钥
        换 = _钥.锁.看标记(备份路) is None
    if 换 and not 新口令:
        raise ValueError('这一份是换过钥匙的，恢复要一句新库口令。')

    os.makedirs(os.path.dirname(os.path.abspath(目标路)), exist_ok=True)
    新密文 = None
    try:
        if 换:
            # `玄武_钥` 在上面判"带不带说明书"那一步已经 import 过了。
            # ⛔ **新库的说明书先落，再写密文**（`锁.造` 那条次序）。
            # 写不下去就抛，目标目录还没建起来，什么也没留下。
            # 迭代 / 盐长 / 块字节照配置（同 `造备份钥匙` 那一段）：
            # 这三个数只在新锁落标记这一刻写进去，之后就跟着标记走。
            import 配置 as _配置
            钥值 = _配置.读()[0]
            锁, 标记 = _钥.锁.造(目标路, 新口令,
                                迭代=钥值.get('玄武钥迭代'),
                                盐字节=钥值.get('玄武钥盐长'),
                                块字节=钥值.get('玄武钥块字节'))
            _钥.锁.写标记(目标路, 标记)
            新密文 = 锁.密文()
            _拷着换钥匙(备份路, 目标路, 备份钥, 新密文,
                        不要=('玄武/' + _钥.标记名,))
        else:
            shutil.copytree(备份路, 目标路)
    except BaseException:
        # 拷了一半的那份要清掉：一个缺文件的半成品库比什么都没有更坏，
        # 因为它看起来像是有的。清不掉的话把话说全（和 `做备份` 同一段）。
        shutil.rmtree(目标路, ignore_errors=True)
        if os.path.exists(目标路):
            raise RuntimeError(
                '拷到一半失败了，而且**清不干净**：%s 还留在盘上。'
                '手工删掉它 —— 它是个开不起来的半成品。' % 目标路)
        raise
    return 目标路, 新密文


