def _开的配置():
    """
    `龙龟之心.开` 要的那份参数 —— **必须和 `霸下之躯` 开库时拿的是同一份**
    （`配置.存储区配置` + `配置.语句上限`，见那个模块第 249 行那段警告）。

    ⛔ **不给的话引擎拿的是自己的默认值**，而库的容量是写在超级块上的 ——
    建库时改过 `区域容量MB` 的库，这儿当场报

        区域容量不一致：库是 4194304，配置是 268435456

    而这个口子的调用方是 `验一遍` / `做完验一遍`，后者的处置是
    **把验不过的备份删掉** ⇒ 症状是"**改过一次区域容量，从此每一份备份
    都被删**"。查起来像备份坏了，其实是开库的参数不对。

    读不动配置就回 `(None, {})`，退回引擎默认 —— 那和改之前一个样。
    """
    try:
        import 配置 as _配置
        值 = _配置.读()[0]
        return _配置.存储区配置(值), _配置.语句上限(值)
    except BaseException:
        return None, {}


def 表清单(库路, 密文=None):
    """
    把一个库（或者一份备份）**当库真开一次**，读它的表清单。

    回 `(表们, None)` 或者 `(None, 说明)`，**不抛**。

    **读表清单不需要登录**：`语法层.tables` 是开库时从 `catalog` 直接装好
    的一个字典，不是一条语句。这条很要紧 —— 界面故意不留口令，要是读它
    需要登录，这条路就走不通了。

    量过：开一次库**不改动盘上任何一个字节**（区域头被重写时内容是一模
    一样的，而 `next_region` 那类修正对已经开过的库是幂等的、当场早返回）。
    所以开过一次的备份仍然和原库逐字节一致，"已备份过吗"不会被自己这一步
    打扰。

    ⚠️ **换过钥匙的那些份不受上面那句影响**：它们和原库**本来就不可能
    逐字节一样**（是拿另一把钥匙重新加的密），"已备份过吗"在那儿比的是
    钥匙文件里记着的**库指纹戳**，压根不看备份自己的字节。所以这个口子
    开它们几次都不会把"备过没有"判错。

    `密文` 是**给加密库用的钥匙**（明文库不传）。它从哪来见 `验一遍`。
    """
    import 龙龟之心
    存储配置, 上限 = _开的配置()
    内核 = None
    try:
        内核 = 龙龟之心.开(库路, config=存储配置, 密文=密文, **上限)
        拿到 = sorted(内核.语法层.tables)
    except BaseException as 错:
        return None, '这一份开不起来：%s' % 错
    finally:
        if 内核 is not None:
            try:
                内核.停()
            except BaseException:
                pass
    return 拿到, None


def 验一遍(备份路, 期望表们, 密文=None):
    """
    把这份备份**当库真开一次**，读它的表清单跟原来对一遍。

    回 `(成不成, 说明)`，**不抛**。

    `密文` 是**给加密库用的钥匙**：备份是原库的逐字节副本，原库是密文，
    备份就是密文，开它当然也要钥匙。**明文库照旧不传**（`None`）。

    钥匙打哪儿来 —— **要么是当前这个会话手里的，要么是从第三处现读的**：

        没换钥匙（老路）    `界面_浏览` 把 `引擎壳.密文` 递进来（`开库`
                            装机时撂在那儿的）。那就是**刚刚做出这份拷贝的
                            那把钥匙**，界面上的人早就为它输过一次口令了，
                            再问一遍是白问；而多留一份口令的拷贝，反而是
                            凭空多出一个要擦的东西（模块头那句"界面故意
                            不留口令"说的是同一件事的另一面：口令不留，
                            **密钥对象**才留）。
        换过钥匙            `界面_浏览._备份的活` 拿 `开备份钥匙` **从第三处
                            现读一把**（多烧约 0.3 秒的 pbkdf2）。那 0.3 秒
                            买的是"**只拿着备份 + 第三处 + 那句口令的人
                            打得开它**"—— 正是将来恢复时的处境。不然
                            "钥匙文件落了、内容却是坏的"要等到真去恢复
                            的那天才会发现，而那时候没有第二份可退。

    ⛔ **钥匙不对 = 备份作废，不是"验不了"。** 这一条不能糊过去：拿错
    钥匙开出来的是 `区域头魔术字不符`，跟"这份备份真的坏了"报的是同一
    句话。区分不了是**引擎的诚实**，不是这里的疏忽 —— 所以两边的处置
    都是同一个：**当作废**。人手上唯一的判据是"我刚才是拿哪个库备的"。

    **读表清单不需要登录**，开库也不改动盘上任何一个字节 —— 两条都在
    `表清单` 的 docstring 里，这里只是拿它跟期望的表对一遍。
    """
    拿到, 说 = 表清单(备份路, 密文=密文)
    if 拿到 is None:
        return False, 说
    应该 = sorted(期望表们)
    if 拿到 != 应该:
        return False, ('表对不上 —— 备份里是 %s，库里是 %s'
                       % ('、'.join(拿到) or '（一张都没有）',
                          '、'.join(应该) or '（一张都没有）'))
    return True, '%d 张表，对得上' % len(拿到)


def 做完验一遍(备份路, 期望表们, 密文=None):
    """
    验收，**不成就把这一份删掉再抛**。

    留着半份坏备份比什么都没有更糟：用户会以为那儿有一份能用的。

    ⛔ **删不干净要说出来。** 这个 `rmtree` 曾经用裸的
    `ignore_errors=True`，然后无条件报"已经删掉了" —— 而实测撞上过一次
    它**没删掉**：`arena.open` 开到一半抛异常时漏了一个 catalog 句柄，
    Windows 上那个文件是独占的，`rmtree` 只删得掉别的、留下 `catalog`
    和整个空目录。用户听到"已经删掉了"，盘上却躺着一个**看着像库的空壳**
    —— 正好是这段话开头要防的那件事。

    （句柄那头已经在 `arena._关掉没开成的` 里堵上了。这里仍然要判一次：
    删不掉的理由不止那一个 —— 杀毒软件、另一个进程开着、只读属性都可能
    让 `rmtree` 半途停下来，而**报一句真话永远比报一句好听的话便宜**。）
    """
    成, 说 = 验一遍(备份路, 期望表们, 密文=密文)
    if not 成:
        shutil.rmtree(备份路, ignore_errors=True)
        if os.path.exists(备份路):
            剩 = []
            for 基, _, 文件们 in os.walk(备份路):
                for 名 in 文件们:
                    剩.append(os.path.relpath(os.path.join(基, 名), 备份路))
            raise RuntimeError(
                '%s\n\n⚠️ **没删干净**：这一份还留在 %s 底下'
                '（剩 %d 个文件%s）。别拿它当备份 —— 它开不起来。'
                '删不掉多半是还有进程占着它，关掉再手工删一次。'
                % (说, 备份路, len(剩),
                   '：' + '、'.join(sorted(剩)[:5]) if 剩 else ''))
        raise RuntimeError('%s\n\n这一份已经删掉了，别拿它当备份。' % 说)
    return 说


def 字节文案(n):
    """按 MB 说，超过 1GB 才换 GB —— 和设置页"字节一律换成 MB 摆"一个口味。"""
    if n >= 1 << 30:
        return '%.2f GB' % (n / float(1 << 30))
    if n >= 1 << 20:
        return '%.0f MB' % (n / float(1 << 20))
    if n >= 1 << 10:
        return '%.1f KB' % (n / float(1 << 10))
    return '%d 字节' % n
