"""
备份 —— 把一块永久存储区整个复制一份，再验一遍它真能用。

**为什么备份是文件层的活，不是引擎的活。**
引擎里没有"复制一个库"这条原语，也不该有：它只认 Bytes，不认"哪个目录
是哪一个库"。装配层早就为同一类问题定过一次调子 —— `霸下之躯.删一个库`
就是自己 `shutil.rmtree` 的（那边注释写着"引擎里没有这条原语……只能在这
一层亲手删目录"）。这里照同一条路走：**备份是本模块亲手拷目录**，引擎
一个字都不动。

**为什么 `做备份` 必须跑在工人线程上。**
不是为了不卡界面 —— 是因为 `界面_接驳.工位` 那条工人线程是**全进程唯一
碰 Storage 的地方**。在它上面跑完整段 `copytree`，期间**不可能有任何写入
发生**，复制出来的一份必然自洽。这就是一致性的全部来源：**不需要锁、不
需要快照、不需要停写**。所以 `做备份` 绝不能拿到界面线程上去调。

**判据为什么用内容摘要，不用 mtime。**
这是踩过的坑，写在这儿免得后人再踩一遍：`arena._rebuild_active_bloom`
末尾有一句**无条件**的 `self._flush_active_meta()`（"无论如何都刷一次元
数据"），而它会把区域头标脏。于是**开一次库**就会让区域头在下次落盘时被
重写 —— 写进去的 64 字节一模一样，**但文件的 mtime 变了**。拿 mtime 当
"这份库变过没有"的判据，结果是：

    备份 → 关（不弹，对）→ 第二天开界面、一条语句都不发、再关 → 还是弹

这个功能就只剩"备份完当场关"那一次有用。所以判据必须是**内容**。

**"内容"里头，玄武的流水不算。** 「这个库变没变」和「这份备份多大」全项目
就 `是库内容吗` 这一把尺子 —— 玄武每接一个连接就往 `玄武/账.jsonl` 追加
一行，把流水算进来的话"备过没有"永远回"没备过"，提醒每次都弹。

**而且不落任何"印章"文件。**
"这份库和某一份备份一模一样吗"直接**当场算、当场比**就行，没有新文件
格式、没有新状态，于是"印章丢了""印章和副本对不上""印章写在复制完成
之前"这一整类 bug 整个不存在。附带三个好处：

  · 判据天然就是"当前库和某一份备份**逐字节一致**"，比 [mtime, size] 严格
  · 用户手工拷进 `备份/` 的一份、别的机器上拷来的一份，**照样算数**
  · 备份就是**原库目录的逐字节副本**（`catalog` + `r/`，加密库还多一个
    `玄武/`），**原样 `--库` 就能打开** —— 恢复这条路不用写任何代码，
    界面自己那条"双击切库"就是（加密库照旧要口令，见下面那段）

**尺寸上的账要说在明处。** 区域文件是预撑到区域容量的（`arena` 的
`fh.truncate`），而且是**实体分配**的，不是稀疏文件。所以一份备份 =
**区数 × 区域容量**，当前这个库一份就是 257 MB。用户拍板过："数据丢了，
你说是硬盘贵还是数据贵" —— 所以这里**不做任何省盘的优化**：不增量、不
压缩、不"只拷用到的部分"。备份唯一的职责是**能恢复**。

**花了盘 ≠ 备成了。** 所以 `做完验一遍` 会把那份备份**当库真开一次**，
读它的表清单跟原来对一遍，对不上就删掉再抛 —— 绝不留一份看着像备份、
其实打不开的东西。

**加密库的备份：拷的是密文，但「谁来开」这一格分两种。**

    没配 `备份钥匙目录`   copytree 一份，**连库那把锁的说明书一起** ⇒ 自足
    配了                  逐区换一遍钥匙，**说明书不进去** ⇒ 靠第三处那把钥匙

第一种是 2026-09-14 之前就有的样子，**它的问题不在加密，在"钥匙跟着一起
走了"**：`玄武/锁.json` 是"怎么把口令变成密钥"的说明书，`copytree` 把它
一起搬过去了，所以**毁掉库里的锁，备份照样打得开**。那不是备份的毛病，
是"备份和库共用一把钥匙"的毛病（开发计划 §八·七 末层）。

第二种就是末层要的：

    库     r/***.region  库钥匙流的密文     +  <库>/玄武/锁.json
    备份   r/***.region  备份钥匙的密文      +  <第三处>/<份名>.钥匙.json

**库、备份、钥匙三样分开**，任丢一样都不足以打开。删掉第三处那一份 ⇒
**那一份备份永远打不开**（"锁死"就是这一下，它砍的是自己的手，所以必须
人确认）。`catalog` 和 `玄武/` 底下别的文件原样拷 —— 引擎压根没锁
`catalog`（`arena._上锁` 那段写着为什么），锁它不在这一层的事里。

**换钥匙是按绝对偏移异或，不是重新加密一遍。** 两块流密码在同一个偏移上
再异或一次，`乙密文 = 甲流 ⊕ 乙流 ⊕ 甲密文` —— 区文件的偏移全部作废不了，
`store_format` 一个字节都不用改。代价是 **一片密文中间断了就半份**（不再是
逐字节副本），所以 `做完验一遍` 那一步在这儿**更**不能省。

⚠️ **`已备份过吗` 是这件事最大的连带坑，说在明处。** 它原来比的是"库和
备份**逐字节**一样吗" —— 换过钥匙之后，这两样**再也不可能逐字节一样**
（两把不同的钥匙），不修的话**一关窗口就弹提醒**。

    走不通的那条  把备份解回明文再摘摘要 —— 摘要要主密钥，主密钥要
                  **备份口令**，而关窗口那一刻手上没有（口令只在备/恢复
                  的时候输过一次，没留住）
    走通的这条    钥匙文件里记一笔「备份那一刻库的密文指纹」
                  （`标记['库指纹']`），关窗口时只比这一笔

**这是故意破一次"不落印章文件"**（模块头上半段那条）。为什么在这儿不成立：
印章落在**第三处**、不在备份里，而且**钥匙文件本身就是那份备份的命** ——
没它那份备份已经死了，"印章丢了 / 对不上"这一整类顾虑跟着一起死。
次序也守住了：**钥匙先落、拷贝后走**（和 `锁` 那条铁律同向），拷贝失败就
把钥匙和半份一起收掉，绝不留一个"看着像备份、其实打不开"的目录。
"""

