#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
玄武_城.py — 城防的骨架

**这一层不判任何事，它只管"按什么次序叫谁"。** 判事的活儿全在六台手上，
城一个字都不替它们拿主意。

    六台之间一次都不互相调用。

它们只认一个对象（`一手`），只改这一个对象，只有城按固定次序叫它们。
一代的病根就是模块互相调用 + 每层兜底 —— 底下断了上面看不见。二代把
这条路堵死：**没有第二台替它兜底，所以坏在哪一台一眼就能看出来。**

次序
====

    画 → 门 → 粘 → 镜 → 饵 → 账

- `画` 先跑：它填 `手法`。
  ⚠ **"后面几台全看这个"是句错话，改掉了。** 今天没有第二台读 `手.手法`
  —— 门/粘/镜/饵 读的分别是 `请求`、`判词`、`请求`、`答案`（见各台自己的
  文件头）。`画` 那一格的去处是**账本**（`一手.账字段`）和界面，不是下游。
  写成"全看这个"的后果很具体：人会以为把 `画` 关掉会影响判词，于是不敢
  关；实际上关掉它只让账上少几个标签。
- `门` 是**唯一的判决点**：它填 `判词`（`真库` / `镜` / `断`）。
- `粘` / `镜` / `饵` 都在判词定了之后才跑 —— 判都没判就往镜里送数据，
  那是把"默认拒"反过来写成"默认镜"。
- `账` 永远跑，**包括判成 `断` 的那些**。拒了不记账，等于白拒。

判词兜底：**默认拒
==================

`门` 一声没吭（没登记、抛了、或者填了个 `None`）—— 城**一律当 `断`**。
这一条是整个骨架里最要紧的一句，所以它写成结构、不写成约定：

    if 一手.判词 is None:
        一手.判词 = 断

`城` 里**没有任何一处**把 `真库` 当默认值。要进真库，必须有一台**明说**
"进真库"。见 `开发日志/开发计划-玄武二代.md` §五那条
「⛔ 明令禁止：把不认识的人静默放进镜」—— 静默错答案是这个项目里最贵的错。

判的台出错 → 拒，记的台出错 → 放过去
=====================================

计划 §三·三：**按「判」和「记」分开。**

    判的台（画 / 门 / 粘 / 镜）出错 → 拒（fail-closed）。判不出来就不放行。
    记的台（账 / 饵）出错         → 请求照走，会话降级成只能碰镜 + 报警。

理由：攻击者能打你的账本模块（把盘写满就行）。**打坏了还能进真库，
那账本就白写了。**

**降级那一半已经落地了。** 「降级成只能碰镜」靠的是 `玄武_镜`，它现在
在岗（`霸下之躯._装玄武` 六台全登记），所以这一条是**真动作**：记的台坏
过的会话，下一手判成 `真库` 就地改判 `镜`（见 `请判` 末尾那一段）。

⚠ 但要说在明处：**镜只是"换个地方答"，不是"挡住他"。** 判到镜的手拿到
的是编出来的数据，人还是进得来。真要挡，靠的是 `门` 那张按来源的黑名单。

城认得几个台，认不出的不管
==========================

六台是**陆续写出来的**（`霸下之躯._装玄武` 按 `次序` 依次登记，哪一台没
造成就不登记）。城对没登记的台就是跳过，一个人也不叫。所以"只有两台"
也是一个能跑的状态，而**城的代码一个字都不用动**。

不 import 谁
============

这个文件**不 import 任何玄武件**，也不 import 霸下任何一层：`台账` 是从
外面递进来的（鸭子类型，只要一个 `记(类, **字段)`）。和 `mysql_门` 对
`工位` 那样，图的是"骨架不该知道插座上插的是什么"。
"""

from __future__ import annotations

import threading

__all__ = ['城', '一手', '真库', '镜', '断',
           '判的台', '记的台', '次序']

# ── 三档判词。**就这三个字符串，别处不许另起别名。** ─────────────────

#: 进真库。**只有一台明说"进真库"才到得了这儿。**
真库 = '真库'
#: 进镜（第二个库，装的全是编的）。`玄武_镜.py` 落地前，判到这一档等于
#: 断——**但两个字符串分开写**，不然镜做好了没人记得回来改。
镜 = '镜'
#: 拒。明说拒绝，不是"装作没看见"。默认就是它。
断 = '断'

#: 固定次序。**这是一份数据，不是一堆 if。** 改次序就改这一行。
次序 = ('画', '门', '粘', '镜', '饵', '账')

#: 判的台。坏一个就拒。
判的台 = frozenset(('画', '门', '粘', '镜'))
#: 记的台。坏一个就降级，请求照走。
记的台 = frozenset(('账', '饵'))

#: 判词定了之后还要跑的台。剩下的（画 / 门）在判词之前跑。
_判决前 = frozenset(('画', '门'))


# ══ 一、一手 ═══════════════════════════════════════════════════════════

class 一手(object):
    """
    六台之间传的**唯一**那个东西。

    字段就是计划 §三·一 那张表，一格不多一格不少：

        会话      这条连接（谁、来自哪、攒了多少前科）
        请求      原样的东西：SQL 文本 / 字节操作 / 登录帧
        ── 下面这几格是六台往里填的 ──
        手法      [画] 这一手暴露了什么
        判词      [门] 真库 / 镜 / 断        ← 唯一的判决点
        延迟秒    [粘] 回话之前等多久
        答案      [镜 · 饵] 给他什么
        账上      [账] 落下去的第几号

    ⚠ **这几格今天全有台在填**（六台都登记上了）。写在这儿的一格如果没人
    来填，症状不是报错，是**那一格连同它的配置旋钮一起变成死开关** ——
    `手法` 就整整漏了一轮，见 `账字段` 那一段。

    ⛔ **`判词` 的初值是 `None`，不是 `真库`。** 这一格初值给 `真库` 的话，
    "门忘了判"和"门判了放行"就长得一模一样 —— 而那正是这个项目最贵的那种
    错（静默错答案）。`None` 在 `城.过` 里一律兜成 `断`。

    这个类**不认识账本、不认识闸口、不认识城**。它就是一叠格子。
    """

    __slots__ = ('类', '会话号', '来源', '请求', '可合并',
                 '手法', '判词', '延迟秒', '答案', '账上', '备注')

    def __init__(self, 类='', 会话号=0, 来源='', 请求=None, 可合并=False):
        self.类 = 类            # 事件类别，也是账本里那个 `类` 字段
        self.会话号 = 会话号
        self.来源 = 来源 or ''  # 对端 IP。拿不到就是空串，**不是 None**
        self.请求 = 请求        # 原样的东西：语句文本 / 账号 / None
        #: 给 `台账.记` 那个开关。**高频低信息量的才开**（一次批量插入
        #: 十万行，逐条记就是账本比数据还大）；判定必须逐条。
        self.可合并 = bool(可合并)

        # ⚠ 这三行底下原来都跟着一句「还没写」——**它们早就写上了**
        # （`玄武_画.py:242` / `玄武_粘滞.py:138` / `玄武_门.py:402`，
        # 饵再把手.答案换掉）。注释比代码旧，下一眼看的就是注释。
        self.手法 = None        # [画] 这一手暴露了什么（见过的标签）
        self.判词 = None        # [门] ← **默认拒就靠这个 None**
        self.延迟秒 = 0.0       # [粘] 回话之前等多久
        self.答案 = None        # [镜 · 饵] 给他什么
        self.账上 = None        # [账] 落下去的第几号
        self.备注 = ''          # 人看的一句话，不参与判决

    def 账字段(self):
        """
        交给 `账台` 的那几个字段。**`类` 不在这里**——它是 `记()` 的
        第一个位置参数，放进 `**字段` 会撞成"给了两个值"。

        `账上` 也不在：那个号是账台**写下去之后**才知道的，它回填到
        `手.账上`，不进账本（一行里写自己的号是废话）。

        ⛔ **`手法` 必须在。** 早先这一份把 `画` 认出来的标签漏在外面，
        于是 `玄武_画.__call__` 里那句 `手.手法 = sorted(标)` 成了
        **全项目唯一一次写它、也是最后一次读它** —— 认出来的东西没进
        账本、也没传给后面任何一台。后果不是报错，是**「城防·画」那六格
        旋钮全是死开关**：`玄武画像` 关掉看不出差别，`玄武拖库翻页` 从 8
        改成 2 也看不出差别，而三处说明（本文件 `:20`、`玄武_画.py:41`、
        `配置.py`「城防·画」那一组）**都在说这一格在账里，只有代码不在**。

        它进账的方式和别的字段一样，走 `台账._收一收` 那条路：列表照收、
        按 `玄武账容器项数` 封顶。**加一个字段不会让老账验不过** —— 链子
        哈希的是每一行自己的内容，老行怎么写的还是怎么验。
        """
        return {'会话号': self.会话号, '来源': self.来源,
                '手法': self.手法, '判词': self.判词,
                '延迟秒': self.延迟秒,
                '请求': self.请求, '备注': self.备注}

    def __repr__(self):
        return '<一手 %s 从 %s 判成 %s>' % (
            self.类 or '?', self.来源 or '?', self.判词 or '（没判）')


# ══ 二、城 ═════════════════════════════════════════════════════════════

class 城(object):
    """
    骨架。**按固定次序叫六台，一个主意都不自己拿。**

    参数：

        `台账`   一个 `玄武_台账.台账`（或者任何有 `记(类, **字段)` 的东西）。
                 **不给就是"不记账"** —— 城照样跑，判照样判，只是不留痕。
                 调用方拿不到账本时（比如库还没开）不该因此起不了城。
        `说`     记一句话的回调，`说(什么)`。不给就不说。

    `记` / `报` 这个分工是照计划 §三·三 来的：**判的台出错是"拒"，
    记的台出错是"放过去但报警"**，两条路都不一样，所以城必须知道
    哪一台是哪一类 —— 那就是 `判的台` / `记的台` 这两个集合。
    """

    def __init__(self, 台账=None, 说=None, 降级上限=4096):
        self._账 = 台账
        self._台 = {}
        self._说 = 说 or (lambda 文: None)
        self._降级 = False      # 记的台坏过。**只升不降**，见下面那个属性
        self._锁 = threading.Lock()
        self._过手数 = 0
        #: 会话号 -> True。**哪些会话要降级成只能碰镜**（计划 §三·三）。
        #: ⛔ 键是攻击者刷出来的，所以有上限（同 `玄武_画` 那条）。
        self._降级会话 = {}
        try:
            self._降级上限 = max(64, int(降级上限 or 4096))
        except (TypeError, ValueError):
            self._降级上限 = 4096

    # ── 登记 ────────────────────────────────────────────────────────

    def 登记(self, 名, 台):
        """
        把一台挂上去。`名` 必须是 `次序` 里那一个。

        `台` 是个可调用，收一个 `一手`，往里填自己那一格。**回什么都可以，
        城不看返回值** —— 六台之间不靠返回值串，靠 `一手` 上那几格。

        ⛔ 名字不在 `次序` 里**当场抛**。悄悄收下一个永远不会被叫的台，
        症状是"明明登记了却不生效"，而那时候两边各自看着都是对的。
        """
        if 名 not in 次序:
            raise ValueError('没这台：%r。认得的是 %s'
                             % (名, '、'.join(次序)))
        if not callable(台):
            raise TypeError('台得是个可调用：%r' % (台,))
        with self._锁:
            self._台[名] = 台
        return self

    def 有(self, 名):
        return 名 in self._台

    # ── 过一手 ──────────────────────────────────────────────────────

    def 请判(self, 手):
        """
        **判一手，但不记账。**回判词（`真库` / `镜` / `断`）。

        ⛔ **为什么判和记要能分开做。** 3306 那条路上，包闸口必须
        **先知道判词**——不然它不知道该不该真去查；而账上要记的是
        **完整**的一手，包括"这一句拉回来多少行"，那个数要等查完才有。

        两条路都堵死的话只剩一个办法：记两条账（"要查什么"一条、
        "拿到多少"一条）。那是把一个事实劈成两半，查账的人得自己去拼。
        所以拆成 `请判` + `记手`，**一条一手只落一条账**。

        叫的是**判的台**：画 → 门 → 粘 → 镜。`记的台`（饵 / 账）一律
        不在这儿叫 —— 它们要看的"这一手做出来是什么样"这时候还不存在
        （见 `记手`）。只做两处改动，都写在这儿：

        1. `门` 判成 `断` 就地收手 —— 后面的台一个都不叫
        2. 判的台坏了就地收手（`_叫` 回的 `False`）
        """
        with self._锁:
            self._过手数 += 1

        for 名 in 次序:
            if 名 in 记的台:
                continue                         # 饵 / 账 —— 归 `记手`

            if 名 in _判决前:                    # 画 / 门
                if not self._叫(名, 手):
                    break                        # 判的台坏了 —— 就地收手
                if 名 == '门' and 手.判词 == 断:
                    break
                continue

            # 粘 / 镜：**判词定了之后才跑**。判成断的没有"给他什么"
            # 这回事，所以一个都不叫。
            if 手.判词 == 断:
                continue
            if not self._叫(名, 手):
                break                            # 粘 / 镜 也是判的台

        # ── 兜底：门一声没吭 ────────────────────────────────────────
        #
        # ⛔ **这一条是"默认拒"落地的地方。** 门没登记 / 抛了 / 填了个
        # `None` —— 全归到这儿。`城` 里没有第二处会把判词写成 `真库`。
        if 手.判词 is None:
            手.判词 = 断
            手.备注 = 手.备注 or '门没判 —— 默认拒'
            self._说('[玄武] %s 没有判词，按默认拒办' % (手,))

        if 手.判词 not in (真库, 镜, 断):        # 门给了个没人认得的词
            手.备注 = '判词认不出（%r），按默认拒办' % (手.判词,)
            手.判词 = 断

        # ── 会话降级 ────────────────────────────────────────────────
        #
        # 计划 §三·三 后半句："记的台出错 → 请求照走，但这个会话**立刻
        # 降级成只能碰镜**"。降级是**会话级**的，所以在这儿按会话号兜：
        # 已经降级的会话，只要判成 `真库` 就改判 `镜`。
        #
        # ⛔ 只动得了 `真库` 那一档。判成 `断` 的不动（那本来就更严），
        # 判成 `镜` 的本来就是镜。**降级只会更严，不会更松。**
        if 手.判词 == 真库 and self._降级会话.get(手.会话号):
            手.判词 = 镜
            手.备注 = (手.备注 or '') and (手.备注 + '；') or ''
            手.备注 += '这个会话记的台坏过，降级成只能碰镜'

        return 手.判词

    def 记手(self, 手):
        """
        收尾：**下饵、记账**。在 `请判` 之后、这一手**真做完了**之后调。

        ⛔ 饵排在这儿，不在 `请判` 里，这是次序那一行
        `画 → 门 → 粘 → 镜 → 饵 → 账` 最容易被写错的一处。饵回答的是
        "**他带走的东西里埋着什么**" —— 而"他带走的那些东西"在
        `请判` 的时候**还没有产生**（那是这一手真查完才有的）。所以饵跟
        账一样是**事后的台**，两个都在这一句里叫，饵在前、账在后。

        饵坏不坏都不挡账：两个都是记的台，出错一律放行 + 降级。
        """
        self._叫('饵', 手)
        return self._叫('账', 手)

    def 过(self, 手):
        """判 + 记，一口气。给"判完就算完事"的调用方（开会话、关会话）。"""
        self.请判(手)
        self.记手(手)
        return 手

    def _叫(self, 名, 手):
        """
        叫一台。**没登记就什么都不做**（六台是陆续写出来的）。

        回 **`True` = 这一台没坏**（没登记也算没坏），`False` = 判的台坏了。
        调用方（`请判`）必须看这个返回值 —— 见下面那条 ⛔。

        出错了怎么走，全看这一台是"判"还是"记"：

            判的台   捕到任何异常 → 判词 = 断，回 `False`。**fail-closed。**
                     捕的是 `BaseException` 不是 `Exception`：一台判的台
                     被 `KeyboardInterrupt` 或者别的 BaseException 打断，
                     放过去就是把"没判成"当"放行"。
            记的台   捕到任何异常 → 报警 + `_降级 = True`，**不拦**，回
                     `True`（这一手照走）。

        ⛔ **只把判词设成 `断` 是不够的，这是个真踩过的坑：**
        `请判` 那个循环原来不看返回值，于是「画」炸了把它钉成 `断` 之后，
        循环**接着去叫「门」**，而门高高兴兴把它改回了 `真库` ——
        **fail-closed 当场变成 fail-open**，而且全程一句错都不报
        （备注还留着"拒"，判词却是"真库"）。所以坏了的判的台必须**叫停
        整条流水线**，由调用方 `break` 出去。
        """
        台 = self._台.get(名)
        if 台 is None:
            return True
        try:
            台(手)
            return True
        except BaseException as 错:
            话 = '%s：%s' % (type(错).__name__, 错)
            if 名 in 判的台:
                手.判词 = 断
                手.备注 = '「%s」这一台坏了，判不出来，拒：%s' % (名, 话)
                self._说('[玄武] %s 出错，判成断 —— %s' % (名, 话))
                return False
            self._降级 = True
            self._降级吧(手)
            self._说('[玄武] %s 出错（这一手照走）—— %s' % (名, 话))
            return True

    def _降级吧(self, 手):
        """
        把一个会话记成"降级"。**键是攻击者刷出来的，所以有上限。**

        满了丢最早进来的那一个。丢掉的代价是"那个会话不再被降级" ——
        而同一个攻击者连开几万个会话，本来就不是靠这一格挡的
        （挡住他的是 `门` 那张按来源的黑名单）。这一格只负责
        "**别让一次记不上账变成一次静默的放行**"。
        """
        号 = getattr(手, '会话号', None)
        if 号 is None:
            return
        with self._锁:
            if 号 not in self._降级会话 and len(self._降级会话) >= self._降级上限:
                self._降级会话.pop(next(iter(self._降级会话)), None)
            self._降级会话[号] = True

    # ── 报 ──────────────────────────────────────────────────────────

    def 记(self, 类, 源='', 可合并=False, **字段):
        """
        往账上写一条。**不抛。**

        记不上账不该让一次判断失败、更不该让一条连接掉线（`玄武_台账.记`
        那段写着同一句话）。所以这儿的异常一律吞掉、转成 `_降级`。

        回写下去的那条（合并项回 `None`，见 `台账.记`）。
        """
        if self._账 is None:
            return None
        try:
            return self._账.记(类, 可合并=可合并, 源=str(源), **字段)
        except BaseException as 错:
            self._降级 = True
            self._说('[玄武] 账写不进去了 —— %s：%s' % (type(错).__name__, 错))
            return None

    # ── 状态 ────────────────────────────────────────────────────────

    @property
    def 账本(self):
        """
        城手上那本账（`台账` 或 `None`）。**给界面那一页读/写同一本用。**

        ⛔ **为什么必须借这本、不能自己再开一本。** `台账` 在内存里攥着
        两样东西：最后一条的号 `_号` 和最后一条的哈希 `_前`（见
        `玄武_台账._落`）。**同一本账文件上开出两个 `台账` 对象，两边
        各攥各的尾，谁先写谁就把对方的尾作废** —— 后写的那一笔"前"
        指向一条已经不相邻的行，哈希链从那儿断开，`验账` 会报
        「第 N 行的"前"接不上上一行 —— 中间少了一行」。

        那不是一次攻击，却长得和"账被抹过"**一模一样** —— 一个安全
        功能报假警，比不报更坏：真出事那次人也不信了。

        借这一本之后的口径是：**这个库开着城，账就归城那一本写**；
        城不在（`玄武记账` 关着），界面才自己开一本 —— 那时候也没有
        第二个写者了。**一个库、一个进程、一个写者**，才是这本账
        从一开始就立着的前提（见 `玄武_台账.py` 头部）。
        """
        return self._账

    @property
    def 降级了(self):
        """
        记的台坏过没有。**只升不降。**

        为什么不为"好了"再降回去：那条路要求城去探一个刚刚证明会坏的东西，
        探成功了才知道能不能降回来 —— 而探的那一下本身就可能再坏一次。
        **一个只会变坏一次的标志，比一个来回跳的标志好判得多。**
        真要看"现在还坏不坏"，看账本最后一条错是什么时候。
        """
        return self._降级

    def 报数(self):
        with self._锁:
            return {'台': [n for n in 次序 if n in self._台],
                    '过手数': self._过手数, '降级': self._降级,
                    '降级的会话数': len(self._降级会话),
                    '有账': self._账 is not None}

    def 收尾(self):
        """
        把账攒着的那几条落下去。**关库、停城之前必须调一次。**

        `玄武_台账.收尾` 那段：合并项攒在内存里，满一秒才落；攻击停了、
        没人再记了，最后不到一秒的那几条要等下一次查询才落地。所以关库
        那条路上**不能靠"它自己会落"**。
        """
        if self._账 is None:
            return None
        try:
            return self._账.收尾()
        except BaseException as 错:
            self._说('[玄武] 收尾没收干净 —— %s：%s' % (type(错).__name__, 错))
            return None

    def __repr__(self):
        有 = '、'.join(n for n in 次序 if n in self._台) or '一台都没有'
        return '<城 %s%s>' % (有, '（降级了）' if self._降级 else '')
