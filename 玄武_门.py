class 包工位(object):
    """
    一个工位外面套的那一层。**鸭子类型**：`mysql_门` 只认
    `干等` / `开会话` / `关会话` 三样，这三个包住就行。

    ⛔ **`包工位` 自己不判任何事。** 三个方法都只是"造一手 → 交给城 →
    照判词办"。判决的字一个都不在这个类里 —— 那是 `门台` 的活儿。
    """

    def __init__(self, 真, 城=None, 说=None, 镜=None, 粘=None, 镜等=2.0,
                 写合并=True):
        self._真 = 真
        self._城 = 城
        self._说 = 说 or (lambda 文: None)
        #: 镜 / 粘 两台。**`包工位` 自己不认识它们**，只负责往每个
        #: `包闸口` 里塞 —— 用不用、怎么用全是 `包闸口` 的事。
        self._镜 = 镜
        self._粘 = 粘
        self._镜等 = 镜等
        self._写合并 = 写合并
        self._锁 = threading.Lock()
        self._地址 = {}          # 连接号 -> 对端 IP

    def _包一手(self, 闸, 连接号, 地址):
        """照这一个连接造一层 `包闸口`。**镜和粘从这儿进去。**"""
        return 包闸口(闸, self._城, 连接号, 地址,
                      镜=self._镜, 粘=self._粘, 镜等=self._镜等,
                      写合并=self._写合并)

    # ── 连接 ────────────────────────────────────────────────────────

    def 开会话(self, 连接号, 登录=None, 超时=30.0, 地址=None):
        """
        ⚠ **`地址` 是这一层唯一一处改霸下的地方**（`mysql_门.py` 那一句
        `开会话(号, 登录=登录, 地址=地址)`）。理由：`一条线.地址` 那段注释
        （`mysql_门.py:153`）自己写着"白名单比的是这个"—— 可它传不到
        工位这一层，`开会话` 原来只有 `(号, 登录, 超时)` 三格。**判来源
        要的东西，得能传进来。**

        没给就是空串（不是 `None`）：`门台` 那边对空串一律"不计数也不
        拉黑"，一条归不到来源的失败不该攒成一张把所有人罩进去的黑名单。
        """
        地址 = str(地址 or '')

        手 = _城.一手(类='连接', 会话号=连接号, 来源=地址)
        if self._城 is not None:
            self._城.过(手)
            if 手.判词 != _城.真库:
                # **当没登进来。** `mysql_门` 那一边收到 `None` 就回 1045
                # —— 和"口令不对"是同一句，从外面反推不回来是被谁拒的。
                return None

        if 登录 is not None:
            真登录 = 登录

            def 包过的登录(闸):
                # 这一层套下去，`闸.登录(账号, 明文口令)` 就现形了。
                return 真登录(self._包一手(闸, 连接号, 地址))

            登录 = 包过的登录

        with self._锁:
            self._地址[连接号] = 地址
        try:
            谁 = self._真.开会话(连接号, 登录=登录, 超时=超时)
        except BaseException:
            with self._锁:
                self._地址.pop(连接号, None)
            raise
        if 谁 is None:
            # ⛔ **握手没过，这张表得自己收干净。** 登录失败 / 口令不对 /
            # 玄武这边已经拒了 —— 三种都是回 `None`，而 `mysql_门` 那一边
            # 收到 `None` 就走 `_服务一条` 的 `finally: if 线 is not None:`，
            # **它压根没给这个连接号登记过连接，`关会话` 一辈子不会来。**
            # 留着就是一条死条目，而"登录失败"恰恰是攻击者最便宜、最能
            # 刷的那条路 —— 攒下去就是把对手送的内存当免费仓库用。
            with self._锁:
                self._地址.pop(连接号, None)
            return None
        return 谁

    def 干等(self, 活, 超时=60.0, 会话号=None):
        """把 `活` 包一层，让它拿到的是 `包闸口` —— 语句和结果在这儿现形。"""
        地址 = self._地址.get(会话号, '')

        def 包过的活(闸):
            return 活(self._包一手(闸, 会话号, 地址))

        return self._真.干等(包过的活, 超时=超时, 会话号=会话号)

    def 关会话(self, 连接号, 超时=30.0):
        """
        收会话。**幂等**：`mysql_门.门.停` 会先让连接线程自己收一遍、
        再扫一遍兜底（`mysql_门.py:351` 那段），所以同一个号到得了两次。
        第二次取不到地址，什么也不记。
        """
        with self._锁:
            地址 = self._地址.pop(连接号, None)
        if 地址 is not None and self._城 is not None:
            self._城.过(_城.一手(类='断开', 会话号=连接号, 来源=地址))
        return self._真.关会话(连接号, 超时=超时)

    # ── 没包到的 ────────────────────────────────────────────────────

    def __getattr__(self, 名):
        if 名.startswith('_'):
            raise AttributeError(名)
        return getattr(self.__dict__['_真'], 名)

    def 报数(self):
        with self._锁:
            在 = len(self._地址)
        报 = {'活着的会话': 在,
              '城': self._城.报数() if self._城 is not None else None}
        if self._粘 is not None:
            报['粘滞'] = self._粘.报数()
        if self._镜 is not None:
            报['镜'] = self._镜.报数()
        return 报


