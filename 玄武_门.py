def 包说(说, 城):
    """
    把 MySQL 口那个 `说` 回调包一层：**每一句原样抄一份进账，再往下传。**

    ⛔ **为什么不让 `说` 就那样过去。** `mysql_门._接受` 拒一个不在
    `MySQL允许来源` 名单里的连接时，只调了 `说`（`mysql_门.py:402`）——
    那条路根本不经过工位，**不包住 `说` 就一点痕迹都不留**。而"有人在
    扫我的口"恰恰是最该留下的一条。

    原文照抄，**一个字都不解析**：把日志当接口用，改一句文案就全塌了。

    量：`可合并=True` ⇒ 一秒最多落一条，带 `次数`。所以一场洪水在账上是
    **"一秒被拒了几千次"**，而不是几千行。看不见"分别是谁"—— 那些 IP
    本来就不在允许来源名单里，要一个个追得在网关上追，不在这一层。
    """
    if 城 is None:
        return 说

    def 说过的(文):
        try:
            城.记('门记', 源='', 可合并=True, 文=str(文))
        except BaseException:
            pass
        if 说 is not None:
            说(文)

    return 说过的
