# ══ 口令指纹 ═══════════════════════════════════════════════════════════

def 口令指纹(口令):
    """
    `(指纹, 长度)`。**原文不出这个函数。**

    指纹 = `sha256(口令)` 前 8 字节的十六进制（16 个字符）。

    ⚠ **这不是慢哈希，别拿它当口令的保管方式。** 它只干一件事：让
    "同一份字典"在账上认得出是同一份。要真保管口令，看 `user.py:50`
    那条 pbkdf2（100 万次）。
    """
    if 口令 is None:
        口令 = ''
    if isinstance(口令, str):
        原 = 口令.encode('utf-8', 'replace')
    elif isinstance(口令, (bytes, bytearray)):
        原 = bytes(口令)
    else:
        原 = repr(口令).encode('utf-8', 'replace')
    return hashlib.sha256(原).hexdigest()[:16], len(原)


# ══ 一张来源黑名单 ═════════════════════════════════════════════════════

class 门台(object):
    """
    判决点。**一个可调用，收 `一手`，往里填 `判词`。**

    参数：

        `值`   `配置.py` 那份值。读的是 `玄武` 打头那四个键。
        `说`   记一句话的回调。

    它认得的事件（`一手.类`）：

        `连接`     来源在不在黑名单里 → `断` / `真库`
        `登录`     `请求['成']` 真 → `真库` 并把失败数清零；
                   假 → 记一次失败，**够阈值就拉黑**，回 `断`
        别的       （查 / 写 / 门记 / 断开）来源在黑名单里就 `断`，否则 `真库`

    ⛔ **`玄武拉黑` 关着的时候它一律回 `真库`。** 那不是"没判"——是
    **明说了放行**，而且原因说得出来（人没开这一条）。`城` 那边只有
    `None` 才算"没判"，这里是 `真库`，两件事分得很开。
    """

    def __init__(self, 值=None, 说=None):
        值 = 值 or {}
        self._开 = bool(值.get('玄武拉黑'))
        try:
            self._阈值 = max(1, int(值.get('玄武失败阈值') or 20))
        except (TypeError, ValueError):
            self._阈值 = 20
        # ⛔ **窗口和时长是两件事，以前共用一个数。** 窗口管"往前看多久算
        # 够了几次"，时长管"拉黑之后关多久"。合在一起的时候，想把关的时间
        # 拉长就得把统计窗口也拉宽 —— 那等于偷偷把"几次算够"改松，
        # 两根轴拧的是同一根杆，谁也调不动。
        try:
            self._窗口 = max(1.0, float(值.get('玄武拉黑秒') or 60.0))
        except (TypeError, ValueError):
            self._窗口 = 60.0
        try:
            self._时长 = max(1.0, float(值.get('玄武拉黑时长') or 60.0))
        except (TypeError, ValueError):
            self._时长 = 60.0
        #: 失败表最多记几个来源。**它原来是没有上限的** —— 而这张表按来源
        #: 拆，来源（IP）是攻击者随手就能换的东西，涨多快他说了算。
        try:
            self._失败上限 = max(64, int(值.get('玄武失败表上限') or 4096))
        except (TypeError, ValueError):
            self._失败上限 = 4096
        self._说 = 说 or (lambda 文: None)

        self._锁 = threading.Lock()
        #: 地址 -> `[失败时刻, …]`（只留窗口里的）和 `拉黑到`（monotonic 秒）
        self._失败 = {}         # 地址 -> [秒, …]
        self._拉黑到 = {}       # 地址 -> 秒

    # ── 那一手 ──────────────────────────────────────────────────────

    def __call__(self, 手):
        地址 = 手.来源 or ''
        if not self._开:
            手.判词 = _城.真库
            return 手.判词

        if 地址 and self.拉了(地址):
            手.判词 = _城.断
            手.备注 = '来源在拉黑名单里'
            return 手.判词

        if 手.类 == '登录':
            成 = bool((手.请求 or {}).get('成'))
            if 成:
                self._清了(地址)
                手.判词 = _城.真库
                return 手.判词
            刚拉 = self._记失败(地址)
            手.判词 = _城.断
            手.备注 = '口令不对' + ('—— 够 %d 次，这个来源拉黑 %g 秒'
                                    % (self._阈值, self._时长) if 刚拉 else '')
            return 手.判词

        手.判词 = _城.真库
        return 手.判词

    # ── 黑名单 ──────────────────────────────────────────────────────

    def 拉了(self, 地址):
        """这个来源现在是不是被拉着。**到点自己就放开了**（不落盘、不清理）。"""
        现在 = time.monotonic()
        with self._锁:
            到 = self._拉黑到.get(地址)
            if 到 is None:
                return False
            if 到 <= 现在:
                self._拉黑到.pop(地址, None)
                self._失败.pop(地址, None)
                return False
            return True

    def _记失败(self, 地址):
        """
        记一次失败。**够阈值就拉黑，回"是不是这一下拉的"。**

        ⚠ 地址是空串（拿不到对端）时**不计数也不拉黑**：一条没法归到任何
        来源的失败，攒起来只会误伤——`''` 会变成一个把所有人都罩进去的
        黑名单项。
        """
        if not 地址:
            return False
        现在 = time.monotonic()
        with self._锁:
            时 = self._失败.setdefault(地址, [])
            时.append(现在)
            # 只留窗口里的那些。**这一步不能省**：不留的话这里变成一个
            # 只涨不落的表，而它涨的速率是攻击者说了算。
            界 = 现在 - self._窗口
            while 时 and 时[0] < 界:
                时.pop(0)
            if len(时) < self._阈值:
                self._淘汰()
                return False
            self._拉黑到[地址] = 现在 + self._时长
            时.clear()
            self._淘汰()
        self._说('[玄武] 来源 %s 在 %g 秒里失败够 %d 次，拉黑 %g 秒'
                 % (地址, self._窗口, self._阈值, self._时长))
        return True

    def _淘汰(self):
        """
        失败表满了就扔最早进来的那个。**先来先扔**，同 `玄武_画._翻账`
        那条（`dict` 记着插入次序，`next(iter(…))` 就是最老的那个）。

        ⛔ **调用方必须已经拿着 `self._锁`。** 这儿要是自己再
        `with self._锁`，那是一把**不可重入**的普通锁，当场死锁 ——
        症状是"界面一点这一格就整个卡住"，没有异常、没有日志。
        （同 `报数` 开头那段注。）
        """
        while len(self._失败) > self._失败上限:
            self._失败.pop(next(iter(self._失败)), None)

    def _清了(self, 地址):
        """登录成功了：把这个来源的失败数清掉。**但不碰拉黑**——被拉黑的
        来源根本走不到这儿（`__call__` 里那一关在前面）。"""
        if not 地址:
            return
        with self._锁:
            self._失败.pop(地址, None)

    def 清单(self):
        """现在被拉着的有谁。给界面和排错看。"""
        现在 = time.monotonic()
        with self._锁:
            return {a: round(到 - 现在, 1)
                    for a, 到 in self._拉黑到.items() if 到 > 现在}

    def 报数(self):
        # ⛔ **不许在这儿调 `清单()`。** `清单()` 自己也要 `self._锁`，
        # 而这是一把**不可重入**的普通锁 —— 拿着它再去拿它，是当场死锁，
        # 症状是"界面一点这一格就整个卡住"，而卡住的地方没有异常、
        # 没有日志，看不出是谁。所以在这儿把条件重写一遍，不嵌套。
        现在 = time.monotonic()
        with self._锁:
            return {'开着': self._开, '阈值': self._阈值, '窗口秒': self._窗口,
                    '拉黑时长秒': self._时长, '失败表上限': self._失败上限,
                    '记着失败的来源数': len(self._失败),
                    '正在拉黑': sum(1 for 到 in self._拉黑到.values()
                                    if 到 > 现在)}


# ══ 包一层闸口 ═════════════════════════════════════════════════════════

class 包闸口(object):
    """
    一个闸口外面套的那一层。**鸭子类型**：没包到的方法原样透过去。

    包这几个（`io_layer.Gate` 上那几个出入口）：

        读：`fetch` `fetch_many` `page` `count`      ← 逐条记
        写：`send` `send_many` `fill`                ← 按秒并成带次数的一条
        身份：`登录`                                  ← 只记指纹，不记原文

    ⛔ **`page` / `count` 必须单独包，不能指望 `fetch` 那一层兜住。**
    `io_layer.Gate.page` 里那句 `return self.fetch(...)` 调的是**真闸口
    自己**，不是外面这一层——包了 `fetch` 也拦不到 `page`。

    `__getattr__` 那一手是**故意的**：闸口上有十几个方法（`as_dicts`、
    `stats`、`leg`……），玄武一个都不关心，一一转发就成了"闸口每加一个
    方法，玄武就得跟一次"。**没包到的原样透过去，包到的才过手。**
    """

    #: 逐条记的（读）。**读才是偷数据**，而且读的频率比写低得多。
    _读的 = {'fetch': '查', 'fetch_many': '查', 'page': '翻页', 'count': '计数'}
    #: 并着记的（写）。一次批量插入十万行逐条记 = 账本比数据还大。
    _写的 = {'send': '写', 'send_many': '批写', 'fill': '灌'}

    def __init__(self, 真, 城=None, 会话号=0, 地址='', 镜=None, 粘=None,
                 镜等=2.0, 写合并=True):
        self.__dict__['_真'] = 真
        self.__dict__['_城'] = 城
        self.__dict__['_号'] = 会话号
        self.__dict__['_地址'] = 地址 or ''
        #: 镜那一台（`玄武_镜.镜`）。**没给就是"这库没有镜"**：判到镜
        #: 的手一律拒，绝不偷偷改成真库。
        self.__dict__['_镜'] = 镜
        #: 粘那一台（`玄武_粘滞.粘滞`）。真去睡的是这一层，不是粘自己。
        self.__dict__['_粘'] = 粘
        try:
            self.__dict__['_镜等'] = max(0.0, float(镜等))
        except (TypeError, ValueError):
            self.__dict__['_镜等'] = 2.0
        #: 写的那几种（写 / 批写 / 灌）要不要在账上**按秒并成一条**。
        #: ⛔ 关掉它，账上看得见"每一次写分别写了什么"，但一场批量插入
        #: 十万行会让账本比数据本身还大。**这是拿账的体量换账的细。**
        self.__dict__['_写合并'] = bool(写合并)

    def __getattr__(self, 名):
        if 名.startswith('_'):
            # ⛔ 不能让 `_真` 掉进这里 —— 那是一次无限递归。
            raise AttributeError(名)
        return getattr(self.__dict__['_真'], 名)

    # ── 那一手 ──────────────────────────────────────────────────────

    def _先过一手(self, 类, 请求, 可合并=False):
        """
        **判在前，做在后。**回判词连同那一手：`真库` / `镜` / `断`。

        ⛔ **这里一律不抛、不记、不等。**判完怎么处置是 `_包着做` 的事，
        而处置的头一步是 **[粘] 吊他一下** —— 三档都得吊。要是这里把
        `断` 直接抛出去，粘就只吊得到"办得成"的那两手，**判成断的反而
        一毫秒都不用等**，正好吊反了。

        账也**还没记**（这一步只 `请判`）：账上要写的是**完整**的一手，
        包括"这一句拉回来多少行"，那个数要等真查完才有。所以调用方拿到
        这一手、做完事、把结果填进 `手.请求`，再调 `_记上`。
        """
        手 = _城.一手(类=类, 会话号=self._号, 来源=self._地址,
                      请求=请求, 可合并=可合并)
        if self._城 is None:
            手.判词 = _城.真库
            return 手, _城.真库
        return 手, self._城.请判(手)

    def _记上(self, 手):
        if self._城 is not None:
            self._城.记手(手)

    def _收尾(self, 手, 回, 数行, 下饵):
        """
        数行 → 记账（镜那一趟还夹着**下饵**）→ 把饵改过的行放回结果里。

        `下饵` 只有镜那一路是 `True`，**这一条是硬要求不是优化**：
        `玄武_饵` 自己第一句就查判词，这里是第二道闸。真库那一路连
        `手.答案` 都不设 —— 没那个字段，饵就无从下手。
        """
        if 数行:
            try:
                手.请求['行数'] = len(回) if 回 is not None else 0
                if 回 is not None and getattr(回, 'error', None):
                    手.请求['错'] = 回.error
            except TypeError:
                pass
        if not 下饵:
            self._记上(手)
            return 回
        行们 = getattr(回, 'rows', None) if 回 is not None else None
        if 行们 is None:
            # 写/灌/计数这些没有行可下饵。**照记不误**，饵自己会收手。
            self._记上(手)
            return 回
        # 饵认列靠这个：`回.columns` 是 `[(列名, 类型号)]`。
        try:
            手.请求['列名'] = [列[0] for 列 in 回.columns]
        except (TypeError, IndexError, KeyError):
            pass
        手.答案 = 行们
        self._记上(手)              # ← 饵在这里跑，把 `手.答案` 换掉
        回.rows = 手.答案 if 手.答案 is not None else 行们
        return 回

    def _包着做(self, 类, 请求, 做, 可合并=False, 数行=True):
        """
        `_先过一手` → 做 → 填结果 → 记账。**所有出入口都走这一个。**

        `做` 收**一个闸口**、回结果：判成 `真库` 给真闸口，判成 `镜` 给
        镜那一台的闸口。同一句 `lambda 闸: 闸.fetch(...)` 两条路都走得通
        —— 镜是照真库结构编的，接口本来就一样。

        `做` 抛的时候**也要记一笔**——"他试了这个、没成"是要看的。

        ⛔ **判成 `镜` 而镜不在（或借不到）时，一律拒，绝不偷偷改走真库。**
        "镜坏了就回真库"是最省事、也是最要命的一条捷径：他会看见真数据，
        而且账上写着判的是镜 —— 真库被看了，痕迹反而更干净。
        """
        手, 判 = self._先过一手(类, 请求, 可合并=可合并)
        self._等(手)                       # [粘] 判完了、办事之前，三档都吊
        if 判 == _城.断:
            # 拒的这一手**没有"做完"这回事**，账在这儿就记掉 —— 不记的话
            # 它一点痕迹都不留，而"他求了什么被拒了"正是要看的那一条。
            self._记上(手)
            raise 玄武断('玄武判了「断」：%s（来源 %s）'
                         % (手.备注 or '这一手不给办', self._地址 or '?'))
        if 判 == _城.镜:
            return self._夹着镜(手, 做, 数行)
        return self._夹着真(手, 做, 数行)

    def _夹着真(self, 手, 做, 数行):
        try:
            回 = 做(self._真)
        except BaseException as 错:
            手.请求['错'] = '%s：%s' % (type(错).__name__, 错)
            self._记上(手)
            raise
        return self._收尾(手, 回, 数行, 下饵=False)

    def _夹着镜(self, 手, 做, 数行):
        """
        镜那一趟。**整趟都在 `占住()` 里** —— 镜是第二个真霸下库，
        而 `Syntax._身份` 是单槽游标（"成立的前提只有一条：一次只有
        一个调用者"），两个会话同时进去就串身份了。
        """
        镜机 = self._镜
        if 镜机 is None:
            self._记上(手)
            raise 玄武断('玄武判了「镜」，但这个库没有镜 —— 这一手不给办')
        with 镜机.占住(self._镜等) as 闸:
            if 闸 is None:
                # ⛔ 借不到就拒。**等下去是拿他的矛攻我们的盾**：他多开
                # 几个连接就能把我们的线程全钉在锁上。
                self._记上(手)
                raise 玄武断('镜正被别的会话占着 —— 这一手不给办')
            try:
                回 = 做(闸)
            except BaseException as 错:
                手.请求['错'] = '%s：%s' % (type(错).__name__, 错)
                self._记上(手)
                raise
            return self._收尾(手, 回, 数行, 下饵=True)

    def _等(self, 手):
        """
        [粘] **判完了才等**，而且真睡的是这一层、不是粘自己：粘只算
        "该吊多久"，一声不响，免得在我们自己的调用栈里睡着、把线程占死。

        ⛔ 睡之前先过 `进去()`：同时吊住的人数到顶就不睡，直接放走。
        不设这道闸，他开 500 个连接就能把我们的线程全睡光 —— 粘滞自己
        反倒成了最好用的那个攻击面。
        """
        等 = float(getattr(手, '延迟秒', 0.0) or 0.0)
        if 等 <= 0:
            return
        粘机 = self._粘
        if 粘机 is None:
            # 算得出延迟秒就说明粘在跑；粘不在 -> 延迟秒必是 0。
            return
        if not 粘机.进去():
            return
        try:
            time.sleep(等)
        finally:
            粘机.出来()

    # ── 读 ──────────────────────────────────────────────────────────

    def fetch(self, 语句, 参数=()):
        return self._包着做('查', {'语句': 语句, '参数': 参数},
                            lambda 闸: 闸.fetch(语句, 参数))

    def fetch_many(self, 语句们):
        # 回的是一个**结果列表**，`len()` 数出来的是几句、不是几行 ——
        # 所以这一句不数行，别让账上那个"行数"骗人。
        return self._包着做('查', {'语句们': 语句们},
                            lambda 闸: 闸.fetch_many(语句们),
                            数行=False)

    def page(self, 表, 列='*', 其中=None, 参数=(), 排序=None,
             每页=256, 偏移=0):
        # 每页和偏移也记上：**一页一页拉空一张表**就是拖库的样子，
        # 而"他翻到第几页了"只有这两个数说得清。
        return self._包着做(
            '翻页',
            {'表': 表, '列': 列, '其中': 其中, '每页': 每页, '偏移': 偏移},
            lambda 闸: 闸.page(表, 列, 其中, 参数, 排序, 每页, 偏移))

    def count(self, 表, 其中=None, 参数=()):
        return self._包着做('计数', {'表': 表, '其中': 其中},
                            lambda 闸: 闸.count(表, 其中, 参数))

    # ── 写 ──────────────────────────────────────────────────────────

    def send(self, 语句, 参数=()):
        return self._包着做('写', {'语句': 语句, '参数': 参数},
                            lambda 闸: 闸.send(语句, 参数),
                            可合并=self._写合并, 数行=False)

    def send_many(self, 语句们):
        回 = self._包着做('批写', {'条数': len(语句们) if 语句们 else 0},
                          lambda 闸: 闸.send_many(语句们),
                          可合并=self._写合并, 数行=False)
        return 回

    def fill(self, 表, 行们, 列=None, 批=0, 维度=None, 出错就停='stop'):
        # ⛔ **行数在这一句里数，但 `行们` 本身一个字都不进账**：
        # 一页网页正文几百 KB，十页就把 `_字段上限` 顶穿了。
        try:
            多少 = len(行们)
        except TypeError:
            多少 = -1
        return self._包着做(
            '灌', {'表': 表, '行数': 多少, '列': 列},
            lambda 闸: 闸.fill(表, 行们, 列, 批, 维度, 出错就停),
            可合并=self._写合并, 数行=False)

    # ── 身份 ────────────────────────────────────────────────────────

    def 登录(self, 用户, 口令):
        """
        ⛔ **口令原文不进 `一手`。** 见文件头「口令：原文一个字都不落盘」。

        `成` 是"这一手试中了没有"，和账号、指纹一起放在 `请求` 里 ——
        **不是**把结果放在判词里：判词是 `门台` 的活儿，这一层只报事实。
        """
        印, 长 = 口令指纹(口令)
        手 = _城.一手(类='登录', 会话号=self._号, 来源=self._地址,
                      请求={'账号': 用户, '口令指纹': 印, '口令长度': 长})
        if self._城 is None:
            return self._真.登录(用户, 口令)
        try:
            谁 = self._真.登录(用户, 口令)
        except BaseException as 错:
            手.请求['成'] = False
            手.请求['错'] = '%s：%s' % (type(错).__name__, 错)
            self._城.过(手)
            raise
        手.请求['成'] = 谁 is not None
        self._城.过(手)
        return 谁


