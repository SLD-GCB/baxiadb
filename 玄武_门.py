def 是环回(地址):
    """
    `conn.addr[0]` 那个字符串是不是环回。**认不出来就当不是。**

    `::ffff:127.0.0.1` 这种**四六混写的要拆出来看**：Windows 上双栈
    监听回给你的一律是这个形状，直接把字符串去掉那截比是认不出来的
    —— 认不出来就当成"外面的"，于是一台正常的界面会被判进镜里。
    """
    try:
        ip = ipaddress.ip_address(str(地址 or '').strip())
    except (ValueError, TypeError):
        return False
    映 = getattr(ip, 'ipv4_mapped', None)
    if 映 is not None:
        ip = 映
    return bool(ip.is_loopback)


def _是盒子(件):
    """
    这一样递过来的是**盒子**（无参可调用，用到的时候取），还是**东西本身**？

    ⛔ **判据是"无参也调得动"，不是"能调用"。** 光看 `callable()` 会把
    六台里的 `镜` 和 `粘` 判成盒子 —— 它们自己就有 `__call__(self, 手)`，
    于是 `_解` 会拿零个参数去调它，参数不够就抛，被兜底接住回 `None`，
    症状是**每一帧都变成"这个库没有镜"**，而且一声不响（fail-closed，
    不泄数据，但 9099 那条口等于全废）。

    拿不到位签名的（C 写的内建、某些 `functools.partial`）**当盒子试一次**
    —— 那种情况下"试一次"就是唯一能问出答案的办法，而试错有兜底。
    """
    if not callable(件):
        return False
    try:
        参们 = inspect.signature(件).parameters.values()
    except (TypeError, ValueError):
        return True
    for 参 in 参们:
        if 参.kind is 参.VAR_POSITIONAL:
            return True                       # `*args` —— 无参也调得动
        if 参.kind in (参.POSITIONAL_ONLY, 参.POSITIONAL_OR_KEYWORD) \
                and 参.default is 参.empty:
            return False                      # 有一个必填的位子 ⇒ 不是盒子
    return True


class 皮9099(object):
    """
    9099 那三扇门外面包的一层皮。**给 `io_layer.serve_storage(…, 门皮=…)`。**

    3306 那边的包法（`包工位` + `包闸口`）在这儿用不上：9099 的帧门是
    `(frame, conn)` → 帧，没有一个"闸口"物件。所以这一层是**另一条接缝**，
    自己判、自己挑门，城和账跟 3306 共用同一座、同一本。

    判决规则（开发计划 §四·三、§五）：

        环回          → 交给城判（画 / 门 / 粘 该看的都看得到）
        非环回        → **镜**（9099 上接进来的本来就不该有别人，
                        来源本身就是判据 —— §四·三）
        城判成 `断`   → **断**（非环回也救不回来）

    ⛔ **"城判了断，非环回改成镜"是绝不会有的**：非环回只把 `真库`
    **收紧**成 `镜`，不会把 `断` 放松。反过来的话，一个正在撞库的会话
    只要从非环回连过来就换来一面镜 —— 那是拿一条判据去顶掉另一条。

    ⛔ **镜不在、镜借不到、镜起不来 —— 一律拒，绝不偷偷走真库。**
    和 `包闸口` 那条一模一样，理由也一样。

    ⚠ **这一层不做 3306 那种"下饵"。** 饵要认的是"他带走的那几行"，
    而 9099 这边出去的是**编好的帧**（还没解），这一层不去解它 ——
    解帧是 `io_layer` 的活儿，在这儿再解一遍就是把线上那条规矩抄第二份，
    抄出来的那一份迟早和原版对不上。`手.答案` 一个字都不填，饵自己会
    收手（它第一句就查判词和答案）。
    """

    def __init__(self, 城=None, 镜=None, 粘=None, 说=None, 镜等=2.0):
        #: ⚠ **三样都可以给"一个无参可调用"而不是东西本身。**
        #: 理由在装配层：9099 那个口是**在城装好之前**就起来的
        #: （`霸下之躯` 里"起服务"排在"装城防"前面），所以这一层拿到手
        #: 的时候城还不存在。给个盒子，用到的时候再取。
        #:
        #: 取不到的时候分两半，**别把这两半说成一样**：
        #:
        #:   **环回** → 照原样放行。城防没装不该让本机也连不上
        #:            （`_装玄武` 那段写着"玄武起不来不该让库也起不来"）。
        #:   **非环回** → **仍然按"9099 上来的本来就不该有别人"处理**
        #:            （§四·三），也就是进镜；镜也取不到就**拒**。
        #:
        #: ⛔ **后一半不挂在城在不在上**：那条判据说的是**这个口**露给谁，
        #: 跟城有没有装完是两件事。要是城取不到就整个放行，那么**城防装配
        #: 一失败，空盒期就永久把远端帧原样递进真库** —— 那是拿一次装配
        #: 错误换一个不设防的 9099。
        self._城 = 城
        self._镜 = 镜
        self._粘 = 粘
        self._说 = 说 or (lambda 文: None)
        try:
            self._镜等 = max(0.0, float(镜等))
        except (TypeError, ValueError):
            self._镜等 = 2.0
        self._锁 = threading.Lock()
        self._镜门 = None
        self._镜门轮次 = None
        self._报 = {'过的帧': 0, '进镜的帧': 0, '拒的帧': 0, '非环回': 0}
        #: 三样各自"这是盒子还是东西本身"。**在装配时判一次**，别放到
        #: 每一帧上（判据要 `inspect` 签名，热路上做是白扔钱）。
        self._盒 = {'城': _是盒子(城), '镜': _是盒子(镜), '粘': _是盒子(粘)}

    # ── 那三样（值或者盒子）─────────────────────────────────────────

    def _解(self, 名, 件):
        """
        值就是值；**盒子就取一次**。

        取不到回 `None` —— **不抛**。这一层是挂在连接线程上的，盒子那头
        多半在装配线程上填；填之前来的帧一律走"城防不在"那条路。
        """
        if not self._盒[名]:
            return 件
        try:
            return 件()
        except BaseException:
            return None

    def _取城(self):
        return self._解('城', self._城)

    # ── 接线：收三扇门，回三扇门 ────────────────────────────────────

    def __call__(self, 门):
        """
        收 `io_layer` 组好的三扇门，回包过的三扇。

        ⛔ **原字典不动**（回的是新的一本）。`门皮` 那个位置上是别人组好
        的东西，改它等于隔着接口改别人的变量。
        """
        return {名: self._包一门(名, 门[名]) for 名 in 门}

    def _包一门(self, 名, 真门):
        def 皮(frame, conn=None):
            return self._过(名, 真门, frame, conn)
        # 排错时要认得出这是谁 —— 不加这一行，`repr` 出来是一片
        # `<function 皮9099.<locals>.皮 at 0x…>`，一屋子同名函数。
        皮.__name__ = '皮9099_%s' % 名
        return 皮

    def _过(self, 名, 真门, frame, conn):
        地址 = ''
        try:
            地址 = str(conn.addr[0])
        except (AttributeError, IndexError, TypeError):
            pass
        try:
            号 = id(conn) if conn is not None else 0
        except BaseException:
            号 = 0
        环回 = 是环回(地址)

        手 = _城.一手(类='9099%s' % 名, 会话号=号, 来源=地址,
                      请求=self._请求(名, frame))
        城 = self._取城()
        判 = _城.真库
        if 城 is not None:
            判 = 城.请判(手)
        if not 环回:
            self._报['非环回'] += 1
            if 判 != _城.断:
                判 = _城.镜
                手.备注 = ((手.备注 + '；') if 手.备注 else '') \
                    + '9099 上来的不是环回（%s）' % (地址 or '看不出来')
        # 判词落在那一手上，**包括城取不到的时候** —— 那时 `请判` 没跑过，
        # 不补这一行它就停在 `一手` 的默认值上，账上会出现一笔"没判过"。
        # （现在城不在就不记账，可这一条不该靠"正好没记账"才成立。）
        手.判词 = 判
        self._等(手)

        if 判 == _城.断:
            self._报['拒的帧'] += 1
            self._记上(手)
            return self._拒(frame, '玄武判了「断」：%s'
                            % (手.备注 or '这一帧不给办'))
        if 判 == _城.镜:
            self._报['进镜的帧'] += 1
            return self._在镜里(名, frame, conn, 手)
        self._报['过的帧'] += 1
        try:
            回 = 真门(frame, conn)
        except BaseException as 错:
            手.请求['错'] = '%s：%s' % (type(错).__name__, 错)
            self._记上(手)
            raise
        self._记上(手)
        return 回

    @staticmethod
    def _请求(名, frame):
        """
        账上写什么。**帧的负载一个字都不抄** —— 那是他自己带来的字节，
        长度就够了（和 `包闸口.fill` 不抄 `行们` 是同一条理由），
        而且它是**没解开的**，抄进账本就等于在账里存了一份看不懂的原文。
        """
        载 = b''
        try:
            载 = frame.payload or b''
        except AttributeError:
            pass
        return {'门': 名, '负载长': len(载) if isinstance(载, bytes) else 0}

    def _在镜里(self, 名, frame, conn, 手):
        """
        把这一帧交给**镜那个库的三扇门**。

        ⛔ **整帧都在 `占住()` 里**：镜是第二个真霸下库，`Syntax` 是单槽
        游标；3306 那条路的镜会话和这一条会撞上同一份语法层。

        ⚠ **他多半登不进镜**（镜的管理员口令是随机的、只写在
        `玄武/镜.json` 里），于是登录门那一帧回 `BAD_LOGIN`，后面的帧
        因为没有身份一律被拒。**这不是 bug，是当前的样子**：这一条只做到
        "把明确敌意的帧路由到镜"，没有替他在镜里造一个身份 ——
        "把不认识的人静默放进镜"是明令禁止的，给他造身份比那还远一步。
        """
        镜机 = self._解('镜', self._镜)
        if 镜机 is None:
            self._记上(手)
            return self._拒(frame, '玄武判了「镜」，但这个库没有镜')
        with 镜机.占住(self._镜等) as 闸:
            if 闸 is None:
                self._记上(手)
                return self._拒(frame, '镜正被别的会话占着')
            门 = self._拿镜门(名, 镜机)
            if 门 is None:
                self._记上(手)
                return self._拒(frame, '镜这一台起不来')
            try:
                回 = 门(frame, conn)
            except BaseException as 错:
                手.请求['错'] = '%s：%s' % (type(错).__name__, 错)
                self._记上(手)
                raise
            self._记上(手)
            return 回

    def _拿镜门(self, 名, 镜机):
        """
        镜那个库的某一扇门。**按轮次缓存** —— `复位` 是整面镜丢掉重造，
        旧的那份语法层指着已经关掉的库，缓存跟着轮次一起换就是安全的。
        调用方**必须正拿着 `占住()`**。
        """
        try:
            轮 = 镜机.轮次
            with self._锁:
                if self._镜门 is not None and self._镜门轮次 == 轮:
                    return self._镜门.get(名)
            # ⛔ **`io_layer` 在这儿 import，不放文件顶上。** 这一层
            # 只在"真有一个非环回的帧要进镜"时才需要它；放顶上就变成
            # 一开玄武就得把整个引擎（`io_layer` → `storage_layer` →
            # `arena`）拖进来，`玄武_镜` 那边也是同一条理由。
            import io_layer
            语法 = 镜机.语法
            新 = {'语句层': io_layer.sql_handler(语法),
                  '字节层': io_layer.byte_handler(语法),
                  '登录层': io_layer.login_handler(语法)}
        except BaseException as 错:
            self._说('[玄武] 镜的三扇门接不上 —— %s：%s' % (type(错).__name__, 错))
            return None
        with self._锁:
            self._镜门 = 新
            self._镜门轮次 = 轮
        return 新.get(名)

    def _拒(self, frame, 话):
        """
        回一帧错的。**用 `transport.err_frame`，不自己拼帧** —— 帧的规矩
        在那一层，这一层拼一份就有了第二份实现，迟早对不上。

        码用 `Code.PERMISSION`（`kernel.py`，这一期为它加的）：让收帧的
        人一眼分得清**"我不让你办"和"你这个操作码我不认"**。回 `None`
        是最后一手 —— 连错误帧都编不出来的时候，宁可让连接那边超时，
        也不能假装这一帧办成了。
        """
        try:
            import transport
            import kernel as _核
            return transport.err_frame(frame, 话, _核.Code.PERMISSION)
        except BaseException as 错:
            self._说('[玄武] 9099 连拒绝帧都没编出来 —— %s：%s'
                     % (type(错).__name__, 错))
            return None

    def _等(self, 手):
        """[粘] 和 `包闸口._等` 同一条：判完了才吊，到顶就不吊。"""
        等 = float(getattr(手, '延迟秒', 0.0) or 0.0)
        粘机 = self._解('粘', self._粘)
        if 等 <= 0 or 粘机 is None:
            return
        if not 粘机.进去():
            return
        try:
            time.sleep(等)
        finally:
            粘机.出来()

    def _记上(self, 手):
        城 = self._取城()
        if 城 is not None:
            城.记手(手)

    def 报数(self):
        报 = dict(self._报)
        报['镜门接上了'] = self._镜门 is not None
        return 报


