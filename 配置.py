def _深拷(v):
    """
    表、字典各拷一层新的。

    ⛔ **不能 `dict(缓存)` 了事。** 这一版起 `默认值()` 里有了 `{}` 和
    `[]`（MySQL 那份），浅拷之后**每一处拿到的都是同一个表对象**：界面
    上往账号表里加一行，加的是盘上那份默认值，下次谁调 `默认值()` 都多
    这一行。而且这种串号在单次操作里看不出来——它是**全局**状态，出问题
    的那次和改它的那次隔着半天。
    """
    if isinstance(v, list):
        return [_深拷(x) for x in v]
    if isinstance(v, dict):
        return {k: _深拷(x) for k, x in v.items()}
    return v


