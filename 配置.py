def 读(路径=None):
    """
    读配置。返回 `(值, 问题)`。

    **文件不在、读不动、里面是垃圾——一律不报错**，回全套默认值，把
    哪里不对记在 `问题` 里（一串 `(键, 说明)`）。这条是"删掉它就是
    全套默认"那条性质的实现：文件是**可选**的。

    **不合法的那一项回落到默认值，但绝不闷着**——参照项目的
    `manager.py:80-88` 是校验不过就悄悄用默认，用户改错一个字，界面上
    什么都看不出来。这里把每一处都记进 `问题`，界面照单全念。
    """
    路径 = 路径 or 配置文件
    值 = 默认值()
    问题 = []

    if not os.path.exists(路径):
        return 值, 问题

    try:
        with open(路径, 'r', encoding='utf-8') as f:
            原始 = json.load(f)
    except Exception as exc:
        问题.append((None, '配置文件读不动（%s），按全套默认值来' % exc))
        return 值, 问题

    if not isinstance(原始, dict):
        问题.append((None, '配置文件里不是一份键值表，按全套默认值来'))
        return 值, 问题

    认得的 = set(默认值())
    for 键, 原值 in 原始.items():
        if 键 == '版本':
            continue
        if 键 not in 认得的:
            # **认不出的键报出来，不静默扔。** 它多半是打错了一个字，
            # 或者是从更新的版本带过来的——两种情况都该让人看见。
            问题.append((键, '不认得这个键，已经跳过'))
            continue
        值[键] = 原值

    # 逐条校一遍：不合法就回落默认值，并记下来。
    for 键 in list(值):
        错 = 校验(键, 值[键])
        if 错:
            问题.append((键, '%s，按默认值 %r 来' % (错, 默认值()[键])))
            值[键] = 默认值()[键]

    return 值, 问题


