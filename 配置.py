# ══ 三、校验：一处权威 ═════════════════════════════════════════════════

def 校验(键, 值):
    """
    这一项合法吗。合法回 `None`，不合法回一句人话。

    **界面和读文件都走这一个函数**——校验只有一处，就不会出现"界面上
    拦住了、文件里手改一个照样进得去"。
    """
    行 = None
    for 条0 in _表:
        if 条0[0] == 键:
            行 = 条0
            break
    if 行 is None:
        return '不认得这个键'

    _, 名, 类型, 低, 高, 组, 生效, _ = 行

    if 类型 == '开关':
        return None if isinstance(值, bool) else '要 true 或 false'

    if 类型 == '文本':
        if not isinstance(值, str) or not 值.strip():
            return '不能是空的'
        return None

    if 类型 == '可空文本':
        # `MySQL默认库` 用这个：**空着是正当的设置**（必须报库名），
        # 不像 `库路径` 那样空着就没法开库。
        if not isinstance(值, str):
            return '要一段文字'
        if 值 != 值.strip():
            return '两头不要留空格'
        return None

    if 类型 == '文本表':
        if not isinstance(值, list):
            return '要一串字符串'
        for i, x in enumerate(值):
            if not isinstance(x, str) or not x.strip():
                return '第 %d 项不是一段非空文字' % (i + 1)
            if x != x.strip():
                return '第 %d 项两头留了空格' % (i + 1)
            if not _是IPv4(x):
                # **白名单里有一条永远匹配不上的，症状是"爬虫连不上"而
                # 配置看上去是对的。** 这里先拦下来，别留到那时候。
                return ('第 %d 项不是 IPv4 字面量（%s）——白名单按地址'
                        '原样比，写主机名或网段都匹配不上' % (i + 1, x))
        return None

    if 类型 == '账号表':
        return _校验账号表(值)

    if 类型 in ('整数', '小数'):
        if isinstance(值, bool) or not isinstance(值, (int, float)):
            return '要一个数'
        if 类型 == '整数' and int(值) != 值:
            return '要一个整数'
        数 = float(值)
        if 数 < 低 or 数 > 高:
            return '要在 %s 和 %s 之间' % (低, 高)
        return None

    return None


def _是IPv4(文):
    """
    是不是一个 IPv4 字面量。

    ⛔ **只收 IPv4。** 这不是偷懒，是为了**只支持一条路**：监听口开在
    IPv4 上，`getpeername()` 回的就是四元组里的一个点分地址；支持 IPv6
    要多一套双栈监听 + 另一种地址形状的白名单比对，而那两样现在一个都
    没有。所以"半支持"是不行的——写个 IPv6 地址进去，症状是**白名单
    永远匹配不上**，看着像"爬虫的 IP 变了"。
    """
    段 = 文.split('.')
    if len(段) != 4:
        return False
    for x in 段:
        if not x.isdigit() or (len(x) > 1 and x[0] == '0'):
            return False
        if not 0 <= int(x) <= 255:
            return False
    return True


def _校验账号表(值):
    """
    账号映射表。形状：

        {"spider": {"霸下账号": "爬虫"}, ...}

    **只认 `霸下账号` 这一个键，别的一律报错。**
    """
    if not isinstance(值, dict):
        return '要一张表：{"MySQL 用户名": {"霸下账号": "霸下里的名字"}}'
    for 名, 项 in 值.items():
        if not isinstance(名, str) or not 名.strip():
            return '有一个 MySQL 用户名是空的'
        if len(名.encode('utf-8')) > 32:
            # MySQL 自己的用户名上限就是 32 字符
            return 'MySQL 用户名 %r 太长（MySQL 上限 32 字节）' % 名[:20]
        if not isinstance(项, dict):
            return '%s 那一项要是一张表：{"霸下账号": "..."}' % 名

        # ⛔ **写到这儿的"口令"必须当众拒掉，不许当没看见。**
        #
        # 这不是洁癖：**这一层的口令一个都不存**——客户端把明文交上来，
        # 我们转手交给霸下自己的 pbkdf2 去判。所以这个位置上的
        # `口令` / `密码` / `password` 是**一个不会生效的字段**，
        # 而写它的人一定以为它生效。
        #
        # 那次登录会是"口令不对"，而配置里明明写着口令。找这个要很久。
        for 忌 in ('口令', '密码', 'password', 'passwd', 'pwd'):
            if 忌 in 项:
                return ('%s 那一项里有 `%s`——<b>本层一个口令都不存</b>，'
                        '这一格不会生效。口令由客户端连的时候填，'
                        '服务端拿明文交给霸下自己判。请把这一格删掉'
                        % (名, 忌))

        if '霸下账号' not in 项:
            return '%s 那一项里没有 `霸下账号`' % 名
        账 = 项['霸下账号']
        if not isinstance(账, str) or not 账.strip():
            return '%s 的 `霸下账号` 不能是空' % 名
        if 账 != 账.strip():
            return '%s 的 `霸下账号` 两头留了空格' % 名

        多 = [k for k in 项 if k != '霸下账号']
        if 多:
            return '%s 那一项里有认不出的键：%s' % (名, '、'.join(map(str, 多)))
    return None


