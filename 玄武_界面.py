    def _备份根(self):
        """
        备份放在哪儿：`<库目录>/备份`，或者配置里「备份放在哪儿」指着的
        那个目录。**远程腿回 `None`。**

        ⛔ **和备份那个按钮走同一条**（`备份.备份根按配置`）。这一页要是
        自己算老位置，配置一挪，症状就是"按钮说备好了、这一页说没有备份"。
        """
        路 = self._库根()
        if not 路:
            return None
        try:
            return _备份.备份根按配置(路)
        except ValueError:
            return None

    def _刷恢复(self) -> None:
        """摆一句"这儿存着几份、最近的是哪一份"。**只读目录，不碰内容。**"""
        根 = self._备份根()
        if 根 is None:
            self._恢复话.setText('库在对面那台机器上，这一台碰不到它的盘。')
            self._恢复果.setText('')
            return
        # 「备份和库同不同盘」那一句。**算一次，两种情形都用得上**，
        # 而且**只在算得出来的时候算**（`_库根()` 是 `None` 时上面早就
        # 返回了）。
        同盘, 同盘话 = _备份.同盘吗(self._库根(), 根)
        # ⛔ **只是报一声，不挡着任何操作。** 见 `备份.同盘吗` 的
        # docstring：默认配置下本来就是同盘，真要拦，开箱第一次备份
        # 就被拦下了 —— 而拦下来最可能的后果是他干脆不备了。
        尾巴 = ('\n\n⚠ %s' % 同盘话) if 同盘 else ''
        份们 = _备份.列备份(根)
        if not 份们:
            self._恢复话.setText(
                '这个库<b>还没有任何备份</b>（<code>%s</code> 是空的）。\n'
                '先去「数据库管理」页按「🗄 备份当前库」备一份。%s'
                % (根, 尾巴))
        else:
            名, _, 时刻, 字节 = 份们[0]
            什么时候 = (time.strftime('%Y-%m-%d %H:%M:%S',
                                     time.localtime(时刻))
                        if 时刻 is not None else '时间认不出')
            self._恢复话.setText(
                '这个库的备份都放在 <code>%s</code> 里，<b>%d 份</b>。'
                '最近的一份：<b>%s</b>（%s，%s）。%s'
                % (根, len(份们), 名, 什么时候, _备份.字节文案(字节), 尾巴))
        self._恢复话.setText(self._恢复话.text() + self._锁死话())
        self._恢复果.setText('')

    def _锁死话(self) -> str:
        """
        「哪几份被锁死了」那一段。**没配第三处就一个字都不说。**

        ⛔ 这一页非说不可的一句是：**配了备份钥匙目录之后，备份不再自足。**
        那一份的钥匙不在第三处了，它就**永远是乱码**，谁也开不了 ——
        而这件事从界面上看是看不出来的：备份目录里那些份**一个字节都不少**，
        `列备份` 照旧把它们列出来，大小也对。藏着不说的话，唯一的发现时机
        是真要恢复的那一天，而那时候没有第二份可退。

        判据只有一条：**第三处里有没有这份的钥匙**（`备份.列钥匙`）。
        它和"这份开不开得起来"不等价（钥匙在、口令忘了，一样开不了），
        但那是另一个框里的事（`问备份口令`），这儿只管钥匙在不在。
        """
        钥匙根 = self._钥匙根()
        if not 钥匙根:
            return ''
        份们 = _备份.列备份(self._备份根() or '')
        if not 份们:
            return ''
        有 = _备份.列钥匙(钥匙根)
        没钥匙 = [名 for 名, _, _, _ in 份们 if 名 not in 有]
        没备份 = sorted(名 for 名 in 有 if 名 not in set(
            名 for 名, _, _, _ in 份们))
        if not 没钥匙 and not 没备份:
            return ('\n\n🔑 这 %d 份都<b>另配了钥匙</b>（放在 '
                    '<code>%s</code>），恢复要拿那句备份口令。'
                    % (len(份们), 钥匙根))
        出 = ('\n\n🔑 备份钥匙放在 <code>%s</code>。' % 钥匙根)
        if 没钥匙:
            # ⛔ **这几个字里没有"可能"**：钥匙不在了 = 那一份就是乱码，
            # 没有别的解释，也没有别的出路。
            出 += ('\n⛔ <b>%d 份被锁死了</b>（钥匙不在了，永远是乱码）：'
                   '%s。备份那些字节还在，但<b>再也开不起来了</b>。'
                   % (len(没钥匙), '、'.join(没钥匙)))
        if 没备份:
            # 钥匙在、备份没了：多半是手工删了某个备份目录，或者份名被改过。
            # 这一句是给"我自己删过东西吗"一个交代，不改任何行为。
            出 += ('\n⚠ 有 %d 把钥匙找不到对应的备份了：%s。'
                   % (len(没备份), '、'.join(没备份)))
        return 出

    def _钥匙根(self):
        """第三处（备份钥匙目录）。**没配回 `None`，读不动也回 `None`。**"""
        路 = self._库根()
        if not 路:
            return None
        try:
            return _备份.钥匙根按配置(路) or None
        except Exception:
            return None

    def _on_restore(self) -> None:
        """
        从备份恢复一份出来，然后切过去。

        次序是死的，五步：

          1. **挑一份**（主线程，会弹框）
          2. **定新库叫什么**（主线程，会弹框）——目标已经在了就拒，
             `copytree` 撞上已有目录本来就抛，但不能让人从一句
             `FileExistsError` 里去猜
          3. **弄清楚这份备份要不要口令**（主线程）——见下面那段
          4. **投活**（工人线程）：读源表清单 → 拷 → 开副本核对
          5. **回话**（主线程）：切过去

        ⛔ **为什么要先在主线程把口令弄清楚，而不是到工人线程上再问。**
        工人线程上**开不了 Qt 对话框**（`界面_浏览.挑旧份框` 那段写着同一个
        道理）。所以界面线程要把"钥匙"先弄到手，再把它当参数投进活里。

        **要不要问口令，判据是"这两把锁是不是同一把"，不是"当前库加没加密"**
        （`_同一把锁`）：备份是原库的逐字节副本，所以从**这个库**备出去的
        那一份，带着的是**同一把锁**——会话手里那把 `引擎壳.密文` 就是对的
        钥匙，用户刚为这个库输过一遍口令，不该再问第二遍（他当场拍板的就是
        这一条）。

        锁对不上的**一律当场问口令**：别人机器上拷来的、别的库的备份、
        以及**这个库毁过密钥之后**那一支——标记文件已经删了，`看标记` 回
        `None`，跟谁都比不成"同一把"。**这一支是故意的**：刚把钥匙毁掉，
        就不能再拿会话内存里那份旧密钥悄悄把库开回来，那等于毁了个寂寞。
        问到的口令也由 `锁.开` 当场验一遍：口令不对当场挡下，不会拷一份
        开不了的东西出来。

        ⛔ **三条路最后都汇成"手里一把验得过的钥匙"**（`钥匙`），明文备份
        那一支是 `None`。**没有一个"口令"变量在这一路上传递**——理由写在
        下面那一段。
        """
        if self._恢复中:
            self._报('上一份还在拷，等它拷完。')
            return

        路 = self._库根()
        目录 = getattr(self.engine, '库目录', None)
        if 路 is None or not 目录:
            self._报('库在对面那台机器上，这一台碰不到它的盘，恢复不了。')
            return

        根 = self._备份根()
        份们 = _备份.列备份(根) if 根 else []
        if not 份们:
            self._报('这个库还没有任何备份。先去「数据库管理」页按'
                     '「🗄 备份当前库」备一份。')
            return

        # ① 挑一份
        框 = 挑份框(份们, self)
        if 框.exec_() != QDialog.Accepted:
            return
        备份路 = 框.挑中的()
        if not 备份路:
            return

        # ② 新库叫什么
        旧名 = _备份带的库名(os.path.basename(备份路))
        新名, 好 = QInputDialog.getText(
            self, '恢复 —— 新的那个库叫什么',
            '从这一份恢复：\n%s\n\n'
            '恢复出来的是**一个新库**，放在这个库目录底下：\n%s\n\n'
            '（默认给它加了「-恢复」，免得跟原来那个库撞名。'
            '改成一个你自己认得出的名字。）' % (备份路, 目录),
            QLineEdit.Normal, 旧名 + '-恢复')
        新名 = (新名 or '').strip()
        if not 好:
            return
        if not 新名:
            self._报('库名不能是空的。')
            return
        if os.sep in 新名 or (os.altsep and os.altsep in 新名) \
                or 新名 in ('.', '..'):
            self._报('库名里不能有路径分隔符。只写名字，库放在这个库目录'
                     '底下。')
            return
        目标路 = os.path.join(目录, 新名 + '.db')
        if os.path.exists(目标路) or _钥.锁.在不在(目标路):
            self._报('「%s」已经在了（%s）。换个名字——恢复是拷成一个'
                     '**新**库，不覆盖任何东西。' % (新名, 目标路))
            return

        # ③ 这份备份的钥匙从哪儿来。**先看第三处，再走老路。**
        #
        # ⛔ **次序不能反。** 配了第三处之后，这一份里**根本没有
        # `玄武/锁.json`**（`做备份` 故意没拷过去），所以 `看标记` 一定回
        # `None` —— 先走老路的话，它会被当成**明文备份**，一路走到
        # `表清单(密文=None)` 才炸成"这一份备份自己就开不起来"，
        # 而那句错话指的方向全错（看着像备份坏了，其实是钥匙没问）。
        #
        # ⛔ **从头到尾只有"钥匙"这一样东西在手，没有一个"口令"变量。**
        # 几条路都是当场把钥匙弄到手的（要么是会话手里现成的，要么是
        # `锁.开` / `开备份钥匙` 推出来的），而 `请求切库` 的后两格**只来
        # 一样就够**——递钥匙那条路 `开库` 会拿标记验一遍（`_上锁的门槛`），
        # 验得过就不弹框，也就不需要口令。
        #
        # 曾经在这儿多留了一个 `口令` 变量，准备"锁对不上时把口令也递过去"。
        # 它是**死的**：口令从来只是 `锁.开` 的输入，出来的是钥匙，而这一路
        # 到切库都不需要再推一遍 pbkdf2（那是 100 万次迭代，白等零点几秒）。
        # 多留一个"看着有用、其实永远是空串"的变量，比不留更容易让人读错。
        份名 = os.path.basename(备份路)
        钥匙根 = self._钥匙根() or ''
        钥匙 = None          # 开**那一份备份**用的
        新口令 = None        # 换过钥匙的那一支才用得上：给**新库**定一句

        if 钥匙根 and _备份.读备份钥匙(钥匙根, 份名) is not None:
            # —— 换过钥匙的那一支 ——
            #
            # 备份里没有说明书，所以**先问备份口令**（`开备份钥匙` 当场把
            # 它推成主密钥、比一遍校验值，口令不对当场挡下）。
            钥匙 = self._问备份钥匙(钥匙根, 份名)
            if 钥匙 is None:
                return
            # **再问新库的口令。** 恢复出来的是一个新库，它有自己的锁；
            # 不拿备份那把锁搬过来（搬过来的话新库的口令就变成那句备份
            # 口令，而"改口令结构上做不到"，那句就被钉死了）。
            新口令 = 界面零件.问新库口令(self, 备份路)
            if 新口令 is None:
                return
        elif 钥匙根:
            # 配了第三处，**这一份的钥匙却不在**：多半是被「锁死」过
            # （`毁备份钥匙`），也可能份名被手工改过。
            # ⛔ **当场说清楚，不往下走。** 往下走只会在工人线程上白拷
            # 几百 MB，最后报一句"区域头魔术字不符"——那句话听着像盘坏了。
            self._报('「%s」这一份的**钥匙不在** %s 里，它已经打不开了'
                     '（钥匙删掉就再没有第二把，这是设计本身）。\n'
                     '换一份恢复：这一页上面列着哪几份还有钥匙。'
                     % (份名, 钥匙根))
            return
        else:
            # —— 老路：备份自足，钥匙在备份自己身上 ——
            try:
                份标记 = _钥.锁.看标记(备份路)
                本标记 = _钥.锁.看标记(路)
            except _钥.锁错 as 错:
                self._报('锁文件读不出来：%s' % 错)
                return

            if 份标记 is None:
                # 明文备份 → 明文库。**不在这儿拦人**，但下面确认框里
                # 要说清楚。
                pass
            elif _同一把锁(份标记, 本标记):
                钥匙 = getattr(self.engine, '密文', None)
                if 钥匙 is None:
                    # 锁是同一把，会话手里却没钥匙——不该发生（加密库开出来
                    # 的壳上一定撂着一把），但真发生了就**退回去问口令**，
                    # 不能矇着往下走。
                    钥匙 = self._问备份口令(备份路)
                    if 钥匙 is None:
                        return
            else:
                钥匙 = self._问备份口令(备份路)
                if 钥匙 is None:
                    return

        # ④ 投活
        self._恢复中 = True
        self._恢复起钟 = time.time()
        self._摆恢复钮()
        self.engine.投(
            lambda 闸: self._恢复的活(闸, 备份路, 目标路, 钥匙, 新口令),
            lambda 值, 错: self._恢复回话(值, 错, 目标路, 钥匙))

    def _问备份钥匙(self, 钥匙根, 份名):
        """
        问一句**备份口令**，当场拿它把第三处那个钥匙文件开一遍。回 `密文`
        或 `None`（人点了取消 / 口令不对）。

        **为什么现在就要开一遍**（`开备份钥匙` 是真跑 pbkdf2 的）：口令
        打错的话，要等工人线程把几百 MB 拷完、开到副本那一步才报
        "区域头魔术字不符" —— 那时候人已经等了半分钟，而那句话分不清
        "口令错了"和"盘坏了"。而且这一趟还会白拷一份出来，恢复的收尾
        再把它删掉。

        `None` 这一支**不一定是取消**：口令不对也是 `None`（错话已经由
        `_报` 说出去了）。这个框里问到的字**只进 `开备份钥匙`**。
        """
        次, 好 = QInputDialog.getText(
            self, '这一份的备份口令',
            '「%s」是**另配了钥匙**的一份 —— 它的钥匙在：\n%s\n\n'
            '要用当初给这一份定的那句**备份口令**（不是库口令）。'
            % (份名, 钥匙根), QLineEdit.Password, '')
        if not 好:
            return None
        try:
            return _备份.开备份钥匙(钥匙根, 份名, 次)
        except _钥.锁错 as 错:
            self._报('这句口令开不了那一份的钥匙：%s' % 错)
            return None

    def _问备份口令(self, 备份路):
        """
        问一次这一份备份的口令，**当场用它开一遍**，回钥匙或 `None`。

        ⛔ **"开一遍"不是多此一举。** `锁.开` 会把口令推成主密钥再比标记里
        的校验值，所以这一步同时干了两件事：验明口令对不对，和**把钥匙
        拿到手**。不验的话，口令打错要等拷完几百 MB、开到副本那一步才报
        "区域头魔术字不符"——那时候人已经等了半分钟，而且那句话分不清
        "口令错了"和"盘坏了"。

        口令**不进返回值**：切库那一步要的是钥匙（`密文`），而口令本身
        只在下面这一个框里活几秒。
        """
        次, 好 = QInputDialog.getText(
            self, '这一份备份要口令',
            '这一份备份和当前开着的库**不是同一把锁**，'
            '所以得单独给一次口令：\n%s\n\n'
            '（多半是别的机器上拷来的，或者是另一个库的备份。）' % 备份路,
            QLineEdit.Password, '')
        if not 好:
            return None
        try:
            锁 = _钥.锁.开(备份路, 次)
        except _钥.锁错 as 错:
            self._报('这一份开不了：%s' % 错)
            return None
        return 锁.密文()

    @staticmethod
    def _恢复的活(闸, 备份路, 目标路, 钥匙, 新口令=None):
        """
        **跑在工人线程上**：读源 → 拷 → 开副本核对。返回值交回 `_恢复回话`。

        ⛔ **先读源的表清单，再拷。** 顺序反过来的话，一份**本身就坏了**
        的备份要先白拷几百 MB 才被发现；而这个顺序还能白捡一件事：
        `表清单` 是解开密的、真走一遍 `龙龟之心.开`，所以"钥匙不对"也在
        写盘之前就报出来了。

        拷完再核对一次（`做完验一遍`），对不上就把半成品删掉抛出来 ——
        **一个缺文件的半成品库比什么都没有更坏，因为它看起来就像个库。**

        ⛔ **核对那一步的钥匙是"开新库"那把，不是"开备份"那把。**
        换过钥匙的一支里这是**两把不同的钥匙**：`恢复一份` 拿 `钥匙`（备份
        钥匙）解、拿**新造的锁**重新加密写到 `目标路`，所以开出来那个新库
        要用它回上来的第二格。拿备份钥匙去核对只会回"开不起来"，
        而新库其实好端端的 —— 症状是"恢复完了它说我拷坏了，还删了"。

        `闸` 这一格**一个字都没用上**，但得留着：`引擎壳.投` 的活收的就是
        `(闸)` 一个参数（见 `界面_浏览._备份的活`，那边是用它发语句落盘）。
        这一趟一个引擎语句都不发 —— 恢复是文件层的活，不经过引擎。
        """
        表们, 说 = _备份.表清单(备份路, 密文=钥匙)
        if 表们 is None:
            raise RuntimeError('这一份备份自己就开不起来，没敢往盘上拷。\n\n%s'
                               % 说)
        新路, 新密文 = _备份.恢复一份(备份路, 目标路, 备份钥=钥匙,
                                     新口令=新口令)
        说 = _备份.做完验一遍(新路, 表们, 密文=新密文 if 新密文 else 钥匙)
        return {'路': 新路, '字节': _备份.目录字节(新路),
                '说': 说, '表数': len(表们), '新密文': 新密文}

    def _恢复回话(self, 值, 错, 目标路, 钥匙) -> None:
        """**在主线程里被叫。** 报一句，然后切过去。"""
        self._恢复中 = False
        self._摆恢复钮()
        用了 = time.time() - getattr(self, '_恢复起钟', time.time())

        if 错 is not None:
            QMessageBox.critical(self, '没恢复成', '恢复没成：%s' % 错)
            return

        窗 = self.window()
        if 窗 is None or not hasattr(窗, '请求切库'):
            QMessageBox.information(
                self, '拷好了，但切不过去',
                '新库已经拷好、也核对过了：\n%s\n\n'
                '可这个面板没装在主窗上，切不了库。下次开界面的时候'
                '从树里双击它就能进去。' % 值['路'])
            return

        # **切过去用的是"开新库"那把钥匙。** 换过钥匙的一支里它和
        # `钥匙`（开备份那把）**不是同一把** —— `恢复一份` 回上来的第二格
        # 才是新库的锁。这一格为空 = 这一份没换过钥匙，那 `钥匙` 就是对的
        # （明文那一支两格都是 `None`）。
        切库钥匙 = 值.get('新密文') or 钥匙
        换过 = 值.get('新密文') is not None

        QMessageBox.information(
            self, '恢复好了',
            '已经从备份拷出一个新库，也开起来核对过了。\n\n'
            '新库：\n%s\n\n'
            '大小 %s（%d 张表）。%s\n'
            '拷贝用了 %.1f 秒。\n\n'
            '**原来那个库和原来那份备份，一个字节都没动。**%s\n'
            '现在切过去——'
            % (值['路'], _备份.字节文案(值['字节']), 值['表数'], 值['说'],
               用了,
               # 换过钥匙那一支要当面说清"新库是哪句话开着的" —— 不说的话，
                # 人下次开这个库会拿**备份口令**去试（那正是他刚敲过的那句），
                # 而两句话是故意解绑的，试不开。
               ('\n\n🔑 新库用的是**你刚给它定的那句口令**。备份那句口令'
                '（以及原来那个库的口令）**都开不了它** —— 恢复出来的'
                '是一个独立的库，不是原来那个的影子。') if 换过 else ''))

        # 切过去。**钥匙走 `请求切库` 的第三格，口令那一格留空**——含义写在
        # `霸下之躯.主窗.请求切库` 那段。这一路四种情形（同一把锁 / 别的锁 /
        # 明文备份 / 换过钥匙的那一份）下**手里都有一把验得过的钥匙**，
        # 所以 `开库` 一律不会再弹那个输口令的框；明文备份那把钥匙就是
        # `None`，走的是明文那条路。
        窗.请求切库.emit(目标路, '', 切库钥匙)

    def _摆恢复钮(self) -> None:
        """按钮跟着 `_恢复中` 走。**拷着的时候灰掉**，不让人再点一下。"""
        钮 = getattr(self, '_恢复钮', None)
        if 钮 is None:
            return
        if self._恢复中:
            钮.setText('⏳ 正在恢复…')
        else:
            钮.setText('📥 从备份恢复…')
        钮.setEnabled((not self._恢复中) and self._恢复可用())

    def _恢复可用(self) -> bool:
        """
        这一页现在能不能恢复。

        **看的是"这一台碰不碰得到盘"，不是"库锁没锁"。** 明文库当然能恢复
        （恢复出来还是明文）；**毁过密钥的库也能恢复**——那是这条路上最值钱
        的一幕：盘上那个库打不开了，而备份里那一份自己有钥匙，拿口令照样
        打得开。恢复正是"毁错了"和"盘坏了"唯一的退路。

        ⚠️ **配了第三处之后，上面那句要打个折**：那一份的钥匙在**第三处**，
        不在它自己身上。所以「库毁了 + 第三处也毁了」这一支**真的救不回来**
        —— 那是"锁死备份"买来的东西，用户配那一格的时候就是拿这个换的。
        页面上那条「哪几份被锁死了」管的就是把这件事说在明处
        （`_锁死话`），而不是到恢复的那天再让人发现。

        灰着的时候要说清为什么（`_刷按钮` 里那个 tooltip 管这件事）。
        """
        return bool(self._库根()) and bool(getattr(self.engine, '库目录', None))

    @property
    def 正在恢复(self) -> bool:
        """
        拷着没有。**主窗关软件那一路拿它拦人**
        （和 `界面_浏览.正在备份` 一个用处，见 `霸下之躯.主窗._拦一下关窗口`）。
        """
        return self._恢复中

    # ── 四、毁密钥 ──────────────────────────────────────────────────

