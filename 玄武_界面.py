    def _on_new(self) -> None:
        """
        建一个上了锁的新库。

        **这一页自己不建库。** 它只把名字和口令交给主窗，由 `_要切库` →
        关窗口 → `main` 那个循环 → `开库` 去建。理由和切库那条一样：
        建库要开一个 Arena，而界面里**只许有一个**（`baxia-multi-library-
        unbind`）。在这儿顺手开一个"临时库"建完就关，就是同一时刻两个
        Arena——那正是这套装配一直在躲的东西。

        所以口令跟着切库请求走（`霸下之躯.请求切库` 的第二个参数），
        `开库` 拿到它就是"给这个新库上锁"，没拿到就是"打开一个已经上锁的
        库，口令得现问"。**一句话管两条路，口令要输几遍由调用方决定。**

        ⛔ **第三格（现成的钥匙）必须是 `None`，而且必须是显式的三个参数。**
        这一页手上**只可能有一句口令、不可能有钥匙**——钥匙是"已经开过的
        那个库"手里的东西，而这里是个**还没建出来**的库。少写这一格不是
        "留空"（Qt 会当场抛 `TypeError: needs 3 argument(s), 2 given!`），
        也给不出别的值。口径见 `霸下之躯.请求切库`。
        """
        名 = self._新名.text().strip()
        if not 名:
            self._报('库名不能是空的。')
            return
        if os.sep in 名 or (os.altsep and os.altsep in 名) or 名 in ('.', '..'):
            # 名字里带分隔符就是路径——那等于允许在库目录外面建东西。
            self._报('库名里不能有路径分隔符。只写名字，库放在这个库目录'
                     '底下。')
            return
        口 = self._新口.text()
        if not 口:
            self._报('口令不能是空的。空口令等于没上锁。')
            return
        if 口 != self._新确.text():
            self._报('两遍口令不一样。')
            return

        目录 = getattr(self.engine, '库目录', None)
        if not 目录:
            self._报('这一条腿问不出库目录（远程腿不数本机的库），'
                     '建不了新库。')
            return
        路 = os.path.join(目录, 名 + '.db')
        if os.path.exists(路) or _钥.锁.在不在(路):
            self._报('「%s」已经在了（%s）。换个名字，或者先去「数据库'
                     '管理」页切过去。' % (名, 路))
            return

        窗 = self.window()
        if 窗 is None or not hasattr(窗, '请求切库'):
            self._报('这个面板没装在主窗上，建不了库。')
            return

        # 口令交出去之前先把框擦干净：窗口马上就关了，但擦掉的是"这个
        # 控件里不再攥着它"这件事，跟窗口关不关没关系。
        口要交 = 口
        self._新名.clear()
        self._新口.clear()
        self._新确.clear()
        窗.请求切库.emit(路, 口要交, None)

