    def _刷锁(self) -> None:
        """
        盘上那一行"锁没锁"的真相，**只读标记，不碰口令**。

        `看标记` 就是为这一页这种用处写的：它必须**不需要口令**——不
        这样的话，界面在库还没打开的时候根本没资格知道这个库要不要口令，
        那个输口令的框也就弹不出来。

        ⛔ **不摆空白行**。摆不下的时候填 `—` 而不是把控件藏起来：
        `QFormLayout` 藏了控件还留着标签，"迭代次数："后面空着一条，看着
        像读失败，而不像"这个库没有这一项"。
        """
        路 = self._库根()
        if 路 is None:
            self._锁话.setText(
                '<b>库在对面那台机器上。</b>这一页管的是盘上的密文和'
                '钥匙，而这一台一个字节的盘都碰不到——建不了、毁不了、'
                '也看不了。')
            for 件 in self._锁件.values():
                件.setText('—')
            self._刷按钮()
            return

        if self._已毁:
            # 毁完再刷，标记文件已经没了，`看标记` 会回 None——照那个回
            # "这是个明文库"，就和上面红横幅当面打架了。**这两个状态差得
            # 远：**明文库是"从来没锁过"，毁掉的库是"锁过、钥匙扔了"。
            self._锁话.setText(
                '⛔ <b>这个库的钥匙已经毁了</b>（就在刚才，这个界面里做的）。\n'
                '盘上那些字节还在，还是密文，可<b>再也没有一把钥匙能打开'
                '它们</b>——标记文件已经删了，主密钥也换成随机字节了。')
            for 件 in self._锁件.values():
                件.setText('—')
            self._刷按钮()
            return

        try:
            标记 = _钥.锁.看标记(路)
        except _钥.锁错 as 错:
            # 标记在、但读不出来（文件坏了、算法不认）。**这是要报的**：
            # 库开得开是因为钥匙在手上，可标记一坏，下次开界面就没人
            # 知道该弹不弹口令框了。
            标记 = None
            self._锁话.setText(
                '⚠ <b>锁文件在，但读不出来</b>：%s\n'
                '这个库现在开得开（口令是现推的，不靠这个文件），可'
                '<b>下次开界面就没人知道该不该问口令了</b>。趁现在还能开，'
                '把它记下来。' % 错)
            for 件 in self._锁件.values():
                件.setText('—')
            self._刷按钮()
            return

        if 标记 is None:
            self._锁话.setText(
                '<b>这是个明文库。</b>区文件、布隆、账本，在盘上都是'
                '明文的——搬走硬盘的人直接就读到了。\n'
                '下面「新建一个上了锁的库」能建一个；<b>这个库翻不成'
                '密文</b>，要加密只能导出重建。')
            for 件 in self._锁件.values():
                件.setText('—')
        else:
            self._锁话.setText(
                '<b>这个库上了锁。</b>盘上的区文件和布隆都是密文，'
                '没有口令就是一堆解不开的字节。')
            self._锁件['标记文件'].setText(_钥.锁.标记路径(路))
            self._锁件['算法'].setText(str(标记.get('算法')))
            self._锁件['迭代次数'].setText(
                '%s 次 pbkdf2（挡离线穷举的唯一屏障）' % 标记.get('迭代'))
            self._锁件['盐'].setText(str(标记.get('盐')))
            self._锁件['随机数'].setText(str(标记.get('随机数')))
        self._刷按钮()

