"""
玄武_界面.py — 加密与密钥面板（第 6 页）

**这一页管的是盘上那堆密文，不是库里那张表。**

    盘上的区文件和布隆  一直是密文        ← 这一页让它成为常态
    他搬走硬盘          拿到的是乱码
    他连 3306 查        拿到的是明文       ← 那不是这一页管的事（外围 · 镜）

所以这一页上的按钮**没有一个会碰表里的数据**，碰的全是
`<库>/玄武/` 和区文件的**钥匙那一头**。和设置页一样：它是一张会动盘上
文件、但**不往引擎里投活**的表单（界面只有一条工人线程独占闸口，见
`界面_接驳` 文件头那条铁律）。

三件这一页**做不到**的，摆在这儿一次说清
==========================================

**一、已经存在的明文库，翻不成密文。**

`锁.造` 的次序是死的：**标记先落、密文后写**（见 `玄武_钥.py`）。给一个
已经写满明文的库上锁，得把每个区文件和布隆**重新读明文、写密文**——
那是几百 MB 到几 GB 的一整趟写，中途断电就留下一个半明半密的库。
所以这一页只给**新库**上锁；老库要加密，只有导出重建一条路。
（要支持就地翻，得单独做一条能中断能续的写路径，见开发计划 §十一。）

**二、改口令做不到。**

口令不是存在哪儿的字符串，它是**主密钥的来路**：

    口令 --pbkdf2--> 主密钥 --shake256--> 每一块盘上数据的密钥流

换口令 = 换主密钥 = 换密钥流 = **全库每一个字节都要重写**。它和上面那条
是同一件事，不是"改一个字段"。真要能改，得把标记格式改成"随机主密钥 +
用口令派生的 KEK 包起来"（LUKS 那种做法）——那要动 `玄武_钥.py` 的标记
格式，是单独一件事，**没做，也不该由这一页偷偷替人做主**。

**三、毁密钥之后，正在开着的这个界面还能读到关掉为止。**

毁的是**盘上那个标记文件**和**这把锁手里的主密钥**（`锁.毁`）。而正在
跑的那个 Arena 手里**另有一份**密钥流（`开库` 那一刻给它的）。所以准确
说法是：

    盘上的库  从这一下起**永远打不开**
    内存里    还有一份，直到这个窗口关掉

要"立刻全没"得连引擎那份一起擦，而擦内存这件事在纯 Python 里本来就只是
尽力而为（`玄武_钥.锁.毁` 那段写着）。这一页不假装它做到了。

这一页**做得到**的一件大事：从备份恢复
======================================

上面三条说的都是"做不到"的。**"从备份恢复"是这一页唯一一条"拿回来"的路**，
而且它正好补上第三条那个洞：

    毁密钥  毁掉的是**这一个库目录里**那份标记文件
    备份    里带着**它自己那份**标记文件（备份是逐字节副本，`玄武/` 跟着走）

所以**毁错了、盘坏了、把库目录删了**——只要还有一份备份，数据就还在。
这一页的「📥 从备份恢复…」就是把那份备份拷回成一个正经的库。

三条它**不是**什么的，摆在这儿：

  · **不是"把备份盖回原库"。** 它拷成库目录下的一个**新**库，原库和
    原来那份备份**一个字节都不动**。要就地覆盖得先整个退出这个库
    （单写者 + Windows 独占），那是另一件事，没做。
  · **不是"口令丢了也能救"。** 恢复要开那份备份，还得有口令。它救的是
    "库没了/毁了/坏了"，不是"口令忘了"——**口令忘了，备份也开不了。**
  · **不是"恢复完自动就没事了"。** 恢复出来的是一份**旧的**数据，
    从备份那一刻往后写的东西不在里面。这是备份本身的性质，不是这条路
    的毛病。

谁在写这本书
============

六台**已经全部在岗**（`霸下之躯._装玄武`），所以这本账是**真的流水**：
每一手、每一条判词、每一次拉黑都往里走。这一页往下**自己只写一笔**：
毁密钥。别的地方一个字都不写——翻一眼这一页就在盘上留个文件，那是骚扰
不是功能。

（**「从备份恢复」刻意不记账**：这一页写的账是**当前这个库**的
`<库>/玄武/账.jsonl`，而恢复这个动作说的是**另一个**库的事。往这本书里
写别人的事，比不写更糟。）
"""

