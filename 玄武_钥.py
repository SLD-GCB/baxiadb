#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
玄武_钥.py — 城防的锁

**把盘上的区文件变成乱码，并且能在一瞬间让它永远是乱码。**

这个模块不知道霸下、不知道 Arena、不知道区文件长什么样。它只提供
两样东西：

    密文   一个**长度不变、可随机寻址**的流密码        —— 给 arena 用
    锁     密钥从哪来、怎么派生、怎么毁              —— 给人用

为什么是流密码，不是分组密码
============================

**因为长度不能变。**

霸下的区文件是**直存直取**的：块的偏移是 `块号 × 块字节数`，记录的
偏移槽里直接存着，超级块和根数组钉在文件头上。**只要密文比明文长
一个字节，这些偏移全部作废** —— 那不是"加一层"，那是重写盘上格式。

流密码**逐字节异或，一进一出等长**，所以：

    块 0 还是从偏移 0 开始，块 7 还是从偏移 7×块字节数 开始
    `store_format.py` 一个字节都不用改
    超级块、根数组、描述符表，全都当没这回事

**而且它天然可随机寻址。** 密钥流只由 `(密钥, 随机数, 偏移)` 决定 ——
想解第 300 万字节就解第 300 万字节，不用从头解过来。数据库要的正是
这个（先读块头、再读记录，跳着读）。

零第三方依赖怎么做到
====================

`hashlib.shake_256` 是**标准库里的 C 实现**，而且它是**可扩展输出**
（XOF）—— 一次调用能吐任意多字节：

    密钥流(偏移) = shake_256(密钥 ‖ 随机数 ‖ 块号).digest(块长)

一次调用拿 4096 字节，不是 32 字节。**快的是 C，不是 Python 循环**，
所以这条路才走得通。旁边带一个"上一块"的缓存 —— 数据库的顺序小读
（先读块头 16 字节、再读块体）全部命中缓存，不会重复算。

派生密钥用 `hashlib.pbkdf2_hmac`，也是 C 的。

它丢得掉吗
==========

**锁丢得掉，区文件丢不掉。**

删掉 `<库>/玄武/锁.json`，库**打不开** —— 但那不是"丢了一个衍生
结构"，那是**钥匙本身丢了**（见 `baxia-derived-state-must-be-droppable`
那条的反面）。所以这个文件**必须进备份、必须单独留一份**。
`玄武_台账.py` 那种"随便删"的性质，这里一个都没有。

诚实标出来的两处弱点
====================

**一、同一段明文在同一个偏移上会编出同一段密文。** 这是所有
"固定密钥 + 固定计数器"的全盘加密都有的性质（LUKS、BitLocker 一样）。
它泄露的是"两块内容相等"，不泄露内容本身。要消掉它得给每个块加
随机数 —— 那就加长了，前面那条立命的东西就没了。**这是刻意的取舍。**

**二、口令弱就是弱。** pbkdf2 迭代次数是**挡暴力破解的唯一屏障**，
而它挡不住字典。口令的选择权在用户手上，这个模块只能把迭代拉高。

**三、没有完整性校验。** 这一版只管**保密**（他搬走的是乱码），
不管**防篡改**（他有盘、他改你的库）。两件事，分开做。
"""

import hashlib
import json
import os
import threading

__all__ = ['锁', '密文', '锁错', '标记名']

# 锁文件的名字，放在 `<库目录>/玄武/` 底下。
标记名 = '锁.json'

_编码 = 'utf-8'
_算法 = 'shake256-ctr'
_版本 = 1

# 密钥流一次算多大。4096 是折中：太小了 Python 调用次数多，太大了
# 解 16 个字节的块头要白算 4K。**它不是盘上格式的一部分**，改它不影响
# 已经写下的数据 —— 偏移寻址只认 `密钥 ‖ 随机数 ‖ 块号`，认块号。
_块字节 = 4096

# pbkdf2 迭代次数。**这是挡暴力破解的唯一屏障**，别往下调：
# 调低一次，攻击者离线跑字典的成本就低一档。100 万次在现在的机器上
# 大约是零点几秒 —— 开库的人等一下，解密的成本是每次开库一次。
_迭代 = 1_000_000
_盐字节 = 16
_随机数字节 = 16


class 锁错(Exception):
    """锁的事出了岔子（口令不对、锁文件坏了、库已经上锁了）。"""


def _指纹(主密钥):
    """
    一段只有拿着主密钥才算得出来的字节。**它不是密钥的派生** ——
    是"密钥的指纹"，所以它泄露的信息只有"这个密钥对不对"。

    截 16 位（8 字节）：够用来判对错，不够用来当攻击的起点。

    ⛔ **摆成模块级的函数，不是 `锁` 的方法。** 两边要用同一段字节：
    `锁` 把它写进标记当「校验」，`密文` 拿它当"这把钥匙配不配这把锁"
    的判据（见 `密文.校验`）。写在 `锁` 里面的话，`密文` 要调它就得回头
    引用一个**在它后面才定义**的类 —— 能跑，但读起来是绕的。算法只有
    一处，改这里就是改两边。
    """
    return hashlib.blake2b(主密钥, digest_size=16,
                           person=b'baxia-suoding').hexdigest()


# ══ 密文：长度不变、可随机寻址的流密码 ═════════════════════════════


class 密文(object):
    """
    一条密钥流。**加密就是异或，解密也是异或** —— 同一个方法。

    `解` 和 `加` 的实现是同一个（异或自反），分开只是让调用的地方
    读起来知道在干什么。

    用法（`arena` 那边就是这么用的）：

        密.加(偏移, 明文)  ->  写下去的密文
        密.解(偏移, 密文)  ->  读上来的明文

    **偏移是文件里的绝对偏移**，不是"相对于上一次读"。寻址的钥匙是
    `(密钥, 随机数, 偏移 // 块字节)`，跟读过什么、读过多少无关 ——
    所以同一个偏移永远算出同一段密钥流，读几次都一样。

    线程安全：`_上一块` 是缓存，加了锁。**但真正的并发正确性来自
    "同一个偏移算出同一段密钥流"** —— 缓存就算被抢了，也只是重算一次，
    结果一样。
    """

    __slots__ = ('_键', '_随机数', '_锁', '_上一块号', '_上一块', '_块字节')

    def __init__(self, 键, 随机数, 块字节=_块字节):
        self._键 = bytes(键)
        self._随机数 = bytes(随机数)
        #: 一次算多大一段密钥流。配置键 `玄武钥块字节`，由 `锁` 递进来。
        #: **它不是盘上格式的一部分** —— 下面 `_取块` / `_密钥流` 认的
        #: 是**块号**，块长换了只影响"算多少次"，不影响"查到哪一段"。
        try:
            self._块字节 = max(256, int(块字节 if 块字节 else _块字节))
        except (TypeError, ValueError):
            self._块字节 = _块字节
        self._锁 = threading.Lock()
        self._上一块号 = -1
        self._上一块 = None

    @property
    def 块字节(self):
        """一次算多大一段密钥流。`毁()` 重建这个对象时要照着来。"""
        return self._块字节

    def _取块(self, 块号):
        """这一块 4096 字节的密钥流。**带一块缓存。**"""
        with self._锁:
            if 块号 == self._上一块号:
                return self._上一块
        种 = (self._键 + self._随机数
              + 块号.to_bytes(8, 'big'))
        块 = hashlib.shake_256(种).digest(self._块字节)
        with self._锁:
            self._上一块号, self._上一块 = 块号, 块
        return 块

    def _密钥流(self, 偏移, 长):
        """
        `[偏移, 偏移+长)` 这一段密钥流。

        **跨块是常态**：块字节是 4096，而数据库读一个记录可能只有 100
        字节，也可能跨过块边界。所以这里按块拼，不是"块号 × 块长"一把
        切 —— 那样偏移不在块头上就算错。
        """
        if 长 <= 0:
            return b''
        出 = []
        剩 = 长
        位 = 偏移
        while 剩 > 0:
            块号, 块内 = divmod(位, self._块字节)
            块 = self._取块(块号)
            拿 = min(剩, self._块字节 - 块内)
            出.append(块[块内:块内 + 拿])
            位 += 拿
            剩 -= 拿
        return 出[0] if len(出) == 1 else b''.join(出)

    def _弄(self, 偏移, 数据):
        数据 = bytes(数据)
        if not 数据:
            return b''
        流 = self._密钥流(偏移, len(数据))
        # 异或。`int.from_bytes` 比逐字节循环快得多 —— 逐字节在
        # Python 里是每次一个对象，一个 4K 的块就是四千次。
        return (int.from_bytes(数据, 'big')
                ^ int.from_bytes(流, 'big')).to_bytes(len(数据), 'big')

    def 加(self, 偏移, 数据):
        """明文 -> 密文。**和 `解` 是同一个运算**（异或自反）。"""
        return self._弄(偏移, 数据)

    def 解(self, 偏移, 数据):
        """密文 -> 明文。**和 `加` 是同一个运算。**"""
        return self._弄(偏移, 数据)

    def 校验(self):
        """
        主密钥的指纹。**和标记里那个「校验」字段是同一段字节**（`_指纹`）。

        用处只有一个：**在把钥匙交出去之前，先认一下它配不配那把锁。**

            对得上  → 用它开，一个字都不问
            对不上  → 当场说"钥匙跟这把锁对不上"，
                      而不是等 `arena` 读到第一个区域头再报
                      "区域头魔术字不符" —— 那句话分不清
                      "钥匙拿错了"和"盘坏了"，而这两件事该做的处理相反

        **不含密钥本身**，就是个指纹：拿到它的人推不回主密钥。
        """
        return _指纹(self._键)

    def __repr__(self):
        return '<密文 %s>' % _算法


# ══ 锁：一个库一把 ═════════════════════════════════════════════════


class 锁(object):
    """
    一把锁 = 一个主密钥 + 一份标记。标记**默认**放在
    `<库目录>/玄武/锁.json`，但**"放哪儿"是个参数，不是这句代码的
    一部分** —— 备份钥匙（`备份.py`）就是同一把锁，只是标记落在第三处
    （库、备份、钥匙三样分开）。

    **锁文件里没有密钥。** 它只存"怎么把口令变成密钥"（盐、迭代、
    算法）和一个**校验值**（用来当场认出"口令不对"，而不是等你读到
    一堆乱码才发现）。

        口令 --pbkdf2(盐, 迭代)--> 主密钥
        主密钥 --shake256--> 密钥流

    所以：**拿到库文件的人，除非同时有口令，否则什么都没有。**
    盐不是秘密，迭代次数也不是 —— 它们只是让暴力破解变贵。

    一把锁管一个库。**要毁密钥就是毁主密钥** —— 锁文件留着也没用，
    因为口令推不出已经不在的那个主密钥了。

    ⛔ **路径那一格收的是"标记文件本身的路"，不是"库目录"。** 老签名
    （`造` / `开` / `看标记` / `写标记`）仍然收库目录，它们只是薄壳，
    里面把路径算出来再转给带 `在` 的那一组。**库那头的调用点一个字都
    不用改** —— 这一层是做加法，不是做替换。
    """

    __slots__ = ('_标记路', '_标记', '_主密钥', '_密文', '_已毁')

    def __init__(self, 标记路, 标记, 主密钥, 块字节=_块字节):
        self._标记路 = str(标记路)
        self._标记 = 标记
        self._主密钥 = bytes(主密钥)
        self._已毁 = False
        # ⛔ **块字节以标记里那一格为准，不看调用方传了什么。**
        #
        # 它和迭代、盐**是同一类东西**：`_取块` 算的是
        # `shake256(键 + 随机数 + 块号)` 取 `块字节` 长，而块号又是
        # `偏移 // 块字节` —— 改一个数，**同一把钥匙算出来的密钥流整个
        # 不一样**。放在配置里当个全局旋钮的后果是：改一下设置，
        # 已有的加密库当场全变成"区域头魔术字不符"，而且是永久的、
        # 没有任何提示指向那一次改动。**所以它必须跟着库走。**
        #
        # 标记里没有这一格 = 那是加这一格之前造的老锁，那时候 `块字节`
        # 这个参数还不存在，一律是 `_块字节`。**这时候回落到 `块字节`
        # 形参（也就是配置值）没问题**：老锁在盘上就是 4096，而今天之前
        # 没有任何一条路能把它造成别的数。
        记块 = 标记.get('块字节')
        self._密文 = 密文(self._主密钥, bytes.fromhex(标记['随机数']),
                          块字节 if 记块 is None else 记块)

    # ── 看看在不在 ──────────────────────────────────────────────────

    @staticmethod
    def 标记路径(库目录):
        return os.path.join(str(库目录), '玄武', 标记名)

    @staticmethod
    def 在不在(库目录):
        """这个库上没上锁。**没锁 = 明文库 = 今天的样子。**"""
        return os.path.exists(锁.标记路径(库目录))

    @staticmethod
    def 看标记(库目录):
        """（老签名）库那一个的标记。路径 = `标记路径(库目录)`。"""
        return 锁.读标记(锁.标记路径(库目录))

    @staticmethod
    def 读标记(标记路):
        """
        只读标记，**不碰口令、不解密**。**标记不在那儿就回 `None`** ——
        "没有"是一个正常答案（明文库、还没备过钥匙的份），不是错。

        给"开库之前先知道这个库要不要口令"用 —— 界面要靠它决定
        弹不弹输口令那个框。所以它**绝不能需要口令**。
        """
        路径 = str(标记路)
        if not os.path.exists(路径):
            return None
        try:
            with open(路径, 'r', encoding=_编码) as f:
                标记 = json.load(f)
        except (OSError, ValueError) as exc:
            raise 锁错('锁文件读不出来（%s）：%s' % (路径, exc))
        if 标记.get('算法') != _算法:
            raise 锁错('这个库用的算法是 %r，这一版不认'
                       % 标记.get('算法'))
        return 标记

    # ── 造一把 ──────────────────────────────────────────────────────

    @classmethod
    def 造(klass, 库目录, 口令, 迭代=None, 盐字节=None, 块字节=None):
        """（老签名）给一个库上锁。路径 = `标记路径(库目录)`。"""
        return klass.造在(klass.标记路径(库目录), 口令,
                         os.path.basename(os.path.abspath(str(库目录))),
                         迭代=迭代, 盐字节=盐字节, 块字节=块字节)

    @classmethod
    def 造在(klass, 标记路, 口令, 库名='', 迭代=None, 盐字节=None,
            块字节=None):
        """
        **在这儿**造一把新锁，`标记路` 是标记文件本身的路。库目录那条路
        由 `造` 转进来；备份钥匙由 `备份.py` 转进来（落在第三处）。

        **这儿必须还没有锁**，不然抛 —— 重新上锁等于换钥匙，已经写下去
        的密文就永远解不开了。

        返回 `(锁, 标记)`。**标记要不要落盘由调用方决定** —— 因为
        "先落标记、后写密文"和"先写密文、后落标记"是两个不同的次序，
        出事时留下的是两种不同的残局，这个模块不替调用方选。

        ⛔ 但有一件事是死的：**标记落盘之前，一个密文字节都不许写。**
        反过来的残局（一堆密文 + 没有标记）是**数据永久丢失**；
        而"有标记、没密文"只是开出来一个空库。两种残局差得很远。

        ⚠️ `造` 和 `造在` **每一把都新抽盐、新抽随机数**，所以就算两次
        用的是同一句口令，**两把锁的钥匙流也不一样**。备份那边靠的正是
        这一条：同一句备份口令，一份备份一把钥匙。
        """
        if not 口令:
            raise 锁错('口令不能是空的')
        路径 = str(标记路)
        if os.path.exists(路径):
            raise 锁错('这儿已经有一把锁了（%s）。重新上锁会换掉钥匙，'
                       '已经写下去的密文就永远解不开了。' % 路径)
        # ⛔ **这三条只在"上锁这一刻"用得上，所以改它们不影响已有的库。**
        # 盐、迭代次数、块字节**三样全写进标记**（下面那三格），开一个
        # 已有的库认的是标记里那一份（`开在` → `锁.__init__`），不是模块
        # 常量、也不是调用方手里那个配置值。**新库照新参数、老库照老参数**
        # —— 这一条是"改了配置老库还能开"的全部来源。
        try:
            用迭代 = max(1, int(迭代 if 迭代 else _迭代))
        except (TypeError, ValueError):
            用迭代 = _迭代
        try:
            用盐长 = max(8, int(盐字节 if 盐字节 else _盐字节))
        except (TypeError, ValueError):
            用盐长 = _盐字节
        try:
            用块长 = max(256, int(块字节 if 块字节 else _块字节))
        except (TypeError, ValueError):
            用块长 = _块字节
        盐 = os.urandom(用盐长)
        随机数 = os.urandom(_随机数字节)
        主密钥 = klass._派生(口令, 盐, 用迭代)
        标记 = {
            '版本': _版本,
            '算法': _算法,
            '盐': 盐.hex(),
            '迭代': 用迭代,
            '随机数': 随机数.hex(),
            '校验': klass._校验(主密钥),
            '库': 库名 or os.path.basename(os.path.dirname(路径)),
            '块字节': 用块长,
        }
        os.makedirs(os.path.dirname(os.path.abspath(路径)), exist_ok=True)
        return klass(路径, 标记, 主密钥, 用块长), 标记

    @staticmethod
    def 写标记(库目录, 标记):
        """（老签名）把标记落到库那个位置。"""
        return 锁.写标记在(锁.标记路径(库目录), 标记)

    @staticmethod
    def 写标记在(标记路, 标记):
        """把标记落到 `标记路`。**必须在写任何密文之前。** 原子写。"""
        路径 = str(标记路)
        os.makedirs(os.path.dirname(os.path.abspath(路径)), exist_ok=True)
        临时 = 路径 + '.新'
        with open(临时, 'w', encoding=_编码) as f:
            json.dump(标记, f, ensure_ascii=False, indent=2, sort_keys=True)
            f.flush()
            os.fsync(f.fileno())
        os.replace(临时, 路径)
        return 路径

    # ── 开一把 ──────────────────────────────────────────────────────

    @classmethod
    def 开(klass, 库目录, 口令, 块字节=None):
        """（老签名）用口令开一个库的锁。"""
        return klass.开在(klass.标记路径(库目录), 口令, 块字节=块字节)

    @classmethod
    def 开在(klass, 标记路, 口令, 块字节=None):
        """
        用口令开**落在 `标记路` 的那把锁**。**口令不对当场抛 `锁错`**，
        不是等读到乱码才发现。

        这就是那个"校验"值的用处：`blake2b(主密钥)` 的前 16 位。它确实
        给了攻击者一个"试对没试对"的判据 —— 但那正是 pbkdf2 迭代
        次数在挡的事，跟 LUKS 一个套路。**没有它的话，口令打错会表现成
        "这个库坏了"**，而这两件事该做的处理完全相反。
        """
        标记 = klass.读标记(标记路)
        if 标记 is None:
            raise 锁错('这儿没上锁（没有 %s）' % 标记路)
        主密钥 = klass._派生(口令, bytes.fromhex(标记['盐']),
                            int(标记['迭代']))
        if klass._校验(主密钥) != 标记.get('校验'):
            raise 锁错('口令不对')
        return klass(标记路, 标记, 主密钥, 块字节)

    # ── 派生 / 校验 ─────────────────────────────────────────────────

    @staticmethod
    def _派生(口令, 盐, 迭代):
        """
        口令 -> 主密钥。

        **空口令在这里就已经被 `造` 拦掉了**，但 `开` 这条路也要防 ——
        用户在框里直接回车就是空串，而"空口令能开"是一个不该有的口子。
        """
        if not 口令:
            raise 锁错('口令不能是空的')
        return hashlib.pbkdf2_hmac('sha256', 口令.encode(_编码), 盐,
                                   迭代, dklen=32)

    @staticmethod
    def _校验(主密钥):
        """
        标记里那个「校验」字段。**算法在模块级的 `_指纹` 里**（挪出去是因为
        `密文.校验` 也要用同一段字节，见那个函数的注释）。这儿留一层薄壳：
        类里面几处写的都是 `klass._校验(...)`，读起来比 `_指纹(...)` 更像
        "锁自己的事"。
        """
        return _指纹(主密钥)

    # ── 用 ──────────────────────────────────────────────────────────

    def 密文(self):
        """
        给 `arena` 用的那一条密钥流。

        ⛔ **已经毁掉的锁不许再发密文。** 毁密钥的意思就是"从现在起，
        盘上那些字节永远解不开了" —— 这时候要是还能拿到密文对象，
        那就是"毁"这个动作根本没生效。
        """
        if self._已毁:
            raise 锁错('这把锁已经毁了，密钥没有了')
        return self._密文

    def 已毁(self):
        return self._已毁

    # ── 毁 ──────────────────────────────────────────────────────────

    def 毁(self, 擦几遍=1):
        """
        **末层那一下：让盘上的密文永远是乱码。**

        做三件事，一件都不能省：

        1. **标记文件删掉** —— 留着它就等于留着"怎么算密钥"的说明书，
           虽然没密钥它推不出来，但没理由留。
        2. **主密钥在内存里擦掉** —— 见下面那段。
        3. **钥匙流对象丢掉** —— 它里面攥着同一份密钥。

        擦内存这件事在 Python 里是**尽力而为**，我不会假装它是彻底的：
        不可变 `bytes` 没法原地改，只能换成一份等长的随机字节再把引用
        指过去 —— 而**旧的那份什么时候被 GC 收走、有没有被 swap 到盘上，
        这个模块管不了**。真要守得住得锁内存页（`mlock`），那是平台相关的
        事，纯 Python 这一层做不到。

        **所以准确的说法是：这一下让"正常路径"上再也拿不到密钥，
        而不是"密钥从物理内存里彻底消失"。** 差的那一截，
        靠的是"密钥默认不在这台机器上"（见模块头：不给，而不是毁）。

        返回擦了几遍。**不可逆，没有撤销。**
        """
        路径 = self._标记路
        for _ in range(max(1, int(擦几遍))):
            try:
                if os.path.exists(路径):
                    os.remove(路径)
            except OSError as exc:
                raise 锁错('标记删不掉（%s）：%s' % (路径, exc))
            # 换成一份等长的随机 —— 让"原来的那个 bytes 对象"
            # 尽早没有引用者。
            self._主密钥 = os.urandom(len(self._主密钥))
            self._密文 = 密文(os.urandom(32), os.urandom(_随机数字节),
                              self._密文.块字节)
        self._已毁 = True
        return max(1, int(擦几遍))

    # ── 报 ──────────────────────────────────────────────────────────

    def 报(self):
        """给界面那一页用。**不含密钥，一个字节都不含。**"""
        return {
            '库目录': os.path.dirname(os.path.dirname(self._标记路)),
            '算法': self._标记.get('算法'),
            '迭代': self._标记.get('迭代'),
            '已毁': self._已毁,
            '标记': self._标记路,
        }

    def 标记文件(self):
        """这一把锁的标记落在哪儿。**备份钥匙靠它报给界面。**"""
        return self._标记路

    def __repr__(self):
        return '<锁 %s %s>' % (self._标记路,
                              '已毁' if self._已毁 else '活着')
