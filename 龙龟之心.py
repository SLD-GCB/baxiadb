#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
龙龟之心.py — 数据库内核

**整个后端就是这一个东西，前端只认它。**

    前端（PySide6，以后）/ 采集端 / 脚本
              ↓ 只认这一个
    ┌───────────────────────────────────────────┐
    │ 龙龟之心     —— 整个后端                  │
    │                                           │
    │   语法层（领导）   调度数据的增删改查       │
    │     ├── 存储层        管理永久存储区        │
    │     └── 输入输出层    控制数据的流入流出     │
    │                                           │
    │   存储引擎（store_format / arena）          │
    │   缓冲层（mortise）   ← 由 arena 装配       │
    └───────────────────────────────────────────┘

它只干两件事：**组装**和**生命周期**。不新加语义——上面每一条路都是别处
写好的，这里只把它们接起来、按次序起停。

口子就这一组，没有别的
----------------------

    龙龟之心.建(root)        建一个库，把内核装起来
    龙龟之心.开(root)        打开已有的库，把内核装起来
    龙龟之心.连(host, port)  连一个已经开着的服务端（**库在对面**）
    内核.进出                前端的**唯一数据口**（输入输出层那一组：
                             send / fetch / fill / page / count）
    内核.起服务(host, port)  让前端能在另一个进程连进来
    内核.停()                关掉整个内核
    内核.语法层 / 内核.存储层  给排错看，前端不该直接往里伸手
                             （连进来的内核没有这两个）

    # 同进程
    import 龙龟之心
    with 龙龟之心.建('网页.db') as k:
        k.进出.send('建表 网页 (网址 文本 主键, 域名 文本)')
        k.进出.fill('网页', [('a.com', 'a')], columns=['网址', '域名'])
        print(k.进出.fetch('查询 * 从 网页'))

    # 跨进程：这个进程起服务，前端连上来
    k = 龙龟之心.开('网页.db')
    svc = k.起服务('127.0.0.1', 9000)
    print(svc.port)          # port 给 0 就让系统挑
    k.停()

    # 另一个进程（前端）连上去
    with 龙龟之心.连('127.0.0.1', 9000) as k:
        print(k.进出.fetch('查询 * 从 网页'))

**前端只有一种形状：内核对象**
------------------------------

`建` / `开` / `连` 都返回同一个 `内核`，`.进出` 也永远同形同义——**在哪条腿上
（本地 / 远程）由开法决定，前端不用知道**。这就是输入输出层那条铁律
（"两条腿必须表现一致"）升到门面层的样子：前端从头到尾只写一套代码。

差别全封在 `内核` 里面，而且是**用形状挡的，不是用约定**：

| | `建` / `开`（本地腿） | `连`（远程腿） |
|---|---|---|
| 手上有 `Storage` | 有 | **没有**（库在对面那个进程里） |
| `.语法层` / `.存储层` | 给 | **当场报错**——这层壳在对面 |
| `.起服务` | 给 | **当场报错**——对面已经是一个服务了 |
| `.停()` | 关服务、关库 | **只关这条 socket**，一个字节的盘都不碰 |

**启动次序实际上是反的，这一点必须说清楚**
----------------------------------------

图上是"语法层持有存储层"，代码里是 `Storage` 先被造出来（`Syntax` 在
`Storage.__init__` 里被构造，Arena 也是在 `Syntax` 里开的），造完之后真正
管事的是**语法层**——`存储层` 上每一个动作都原样转给它（见 `storage.py`
「增删改查：走语法层」那一段）。

不是两套编排，是同一件事的两种说法：**存储层是壳，语法层是里子。** 留这个
壳是因为"管永久存储区"是存储层的职分，前端的图上也该有这一格。要是哪天
觉得这层壳白占地方，删掉它的影响面就是 `storage.py` 一个文件，`Syntax`
自己站着——但那是另一个决定，得先说。

单写者
------

**一个永久存储区同一时刻只能有一个 Arena**，而 Arena 只有 `Syntax` 开得
出来。所以这里做了一件别处做不了的事：**`进出` 那条闸口是"接管"来的，
不是"另开一个库"**（`Gate.attach`）。要是这里图省事写 `Gate.open(root)`，
这个进程里就有两个 Arena、两个写者，各自的数据尾指针互相踩——踩出来的
坏数据要到很久以后才有人发现。

**服务一起，本地腿就作废。** 库归服务端的线程独占，这个进程再从本地腿
进出就是两个线程同踩一个 Arena。这一条直接用形状挡掉：`起服务` 之后再
碰 `进出` 当场报错，报的错里带着端口——要读写就 loopback 连回来，走的是
和前端完全一样的那条远程腿。

    k = 龙龟之心.开('网页.db')
    svc = k.起服务('127.0.0.1', 0)
    with 输入输出层.Gate.connect('127.0.0.1', svc.port) as g:
        print(g.fetch('查询 * 从 网页'))
    k.停()
"""

import io_layer as io_mod
import storage as storage_mod

__all__ = ['内核', '开', '建', '连']


class 内核(object):
    """
    一个开着的库，加上它的服务状态。**前端只跟这个对象打交道。**

    它自己不做任何数据库动作：语句怎么解、数据怎么摆、盘怎么写，全在下
    面几层。这里只有三件事——手上有哪一份 `Storage`、闸口在哪条腿上、
    服务起没起。**这三件事各只有一个来源**，所以不可能出现"两个库"或
    "两个写者"。
    """

    def __init__(self, storage, gate=None):
        self._storage = storage  # 连进来的内核没有这一份，是 None
        self._gate = gate        # 本地腿：第一次问 `进出` 时才接；远程腿：连上就有
        self._svc = None         # 起了服务才有
        self._closed = False

    # ── 组装：建 / 开 ───────────────────────────────────────────────
    # **这里是全项目唯一一处把五层接起来的地方。** 存储层的构造带出语法层
    # 和 Arena（见模块头「启动次序实际上是反的」），之后所有动作都从语法层
    # 走。别在别处再写一遍这套装配——两份装配就是两个 Arena。

    @classmethod
    def 建(cls, root, config=None, 密文=None, **limits):
        """
        建一个库，把内核装起来。库已存在时由引擎决定报错还是接着用。

        ⛔ **上锁的库，次序不能反：先造锁落标记，再建库。**

            from 玄武_钥 import 锁
            锁, 标记 = 锁.造(库目录, 口令)     # 库还不能有锁
            锁.写标记(库目录, 标记)            # ⛔ 先落标记
            内 = 内核.建(库目录, config, 密文=锁.密文())   # 后写密文

        反过来（先 `建` 再上锁）会留下**一个明文头 + 一堆密文**，
        那个库这辈子打不开，而且报的错是"区域头魔术字不符"——
        看着像盘坏了，其实是次序反了。`密文=None` 就是明文库。
        """
        return cls(storage_mod.Storage(root, config, 密文=密文,
                                       **limits).create())

    @classmethod
    def 开(cls, root, config=None, 密文=None, **limits):
        """
        打开已有的库，把内核装起来。

        `密文` 从哪来：`玄武_钥.锁.开(库目录, 口令).密文()`。
        **不给（`None`）而库又上了锁，会在读到第一个区域头的时候大声
        报错**（"区域头魔术字不符"），不是悄悄读出乱码——这一点是
        `arena` 里那句魔术字校验管着的，它同时兜住了"没给钥匙"和
        "给了错钥匙"两种。
        """
        return cls(storage_mod.Storage(root, config, 密文=密文,
                                       **limits).open())

    @classmethod
    def 连(cls, host, port, timeout=5.0):
        """
        连一个已经开着的服务端，把内核装起来——**库在对面**。

        拿到的内核只有 `.进出`（远程腿那一份）。别的口子一个都不开，
        而且是当场报错、不是"最好别用"：`.语法层` / `.存储层` 那层壳在
        对面那个进程里，这边根本没有；`.起服务` 更没意义——对面已经是
        一个服务了。**这三条挡在这里，前端的代码就不用分叉了。**
        """
        return cls(None, io_mod.Gate.connect(host, port, timeout))

    # ── 两层：给排错看 ──────────────────────────────────────────────

    @property
    def 语法层(self):
        """领导那一层。**前端不该直接往这里伸手**——要读写走 `进出`。"""
        if self._storage is None:
            raise RuntimeError('这是连进来的内核，库在对面——语法层不在这边')
        return self._storage.syntax

    @property
    def 存储层(self):
        """管永久存储区那一层（也是 `进出` 借的那一份，不是另开的）。"""
        if self._storage is None:
            raise RuntimeError('这是连进来的内核，库在对面——存储层不在这边')
        return self._storage

    # ── 用户 ────────────────────────────────────────────────────────
    #
    # 这两条**故意不是语句**：它们要回答的是"这个库初始化过没有"和"把
    # 第一个管理员设上"，而这两件事都发生在**还没有人能登录**的时候。
    # 开成语句就等于在库刚建好、还没设管理员的那一小段时间里，让任何
    # 能连上端口的人给自己发一个管理员（见 `Syntax.设初始管理员`）。

    def 有用户(self):
        """
        库里有没有用户。**起服务前必查**（见 `起服务`）：没有就是谁都能
        当管理员。

        **连进来的内核问不了这一条**，和 `语法层` 那些一样当场报错——
        对面是不是一个没初始化的库，这边没有地方可以知道（协议里也刻意
        没开这个口子：一个"这个用户名在不在"的接口就是给试探的人预备的）。
        """
        if self._storage is None:
            raise RuntimeError(
                '这是连进来的内核，问不了"库里有没有用户"——库在对面，'
                '而且对面开成服务就说明它已经有用户了（没用户的库不许起'
                '服务）。要建第一个管理员，得在本机把库打开')
        return self._storage.有用户()

    def 设初始管理员(self, 名字, 口令):
        """
        建库后设第一个管理员。**库里已经有用户就报错**，不覆盖。

        只在**本机、还没人被登录**的时候用得着：界面开库时如果发现库里
        没用户，弹的就是这一句。之后的加人一律走 `建用户` 语句（要
        `管用户` 权限）。
        """
        if self._storage is None:
            raise RuntimeError(
                '这是连进来的内核，设不了初始管理员——库在对面，而且对面'
                '开成服务就说明它已经有用户了')
        return self._storage.设初始管理员(名字, 口令)

    # ── 进出的那个口 ────────────────────────────────────────────────

    @property
    def 进出(self):
        """
        前端的唯一数据口：输入输出层的闸口（`send` / `fetch` / `fill` /
        `page` / `count`）。

        **它是接管来的**——`Gate.attach` 把手上这一份 `Storage` 接上闸口，
        不碰盘、不开库（见模块头「单写者」）。

        **服务起了之后这里会报错**，这是故意挡的：那时候库归服务端的线程
        独占，本地腿再用就是两个写者同踩一个 Arena。报的错里带着端口，
        照着 loopback 连回来即可。

        **别对这个闸口调 `close()`。** 它一路走到 `Storage.close()`，
        会把库关掉——关库是内核的事（`停()`）。
        """
        if self._closed:
            raise RuntimeError('内核已经停了，进出不了')
        if self._svc is not None:
            raise RuntimeError(
                '库已经交给服务端的线程独占（引擎是单写者），这个进程不能'
                '再从本地腿进出。要读写就 loopback 连回来：'
                "Gate.connect('127.0.0.1', %d)" % self._svc.port)
        if self._gate is None:
            self._gate = io_mod.Gate.attach(self._storage)
        return self._gate

    # ── 起服务 / 停 ─────────────────────────────────────────────────

    def 起服务(self, host='127.0.0.1', port=0, 门皮=None):
        """
        把手上的库开成一个服务，返回 `Service`（拿 `svc.port` 连它）。

        `port=0` 让系统挑一个空闲的，挑到的在 `svc.port` 上。

        `门皮` 原样递给 `io_layer.serve_storage`（那一格是给玄武留的，
        详见那边的 docstring）：收三扇门、回三扇门。**不给就是原来的
        行为，一个字节都不差。**

        **三扇门都在这一句里接上**（`io_layer.serve_storage` 里那三句）：

            语句门（`0x2x`）  `statements=sql_handler(语法层)`
            字节门（`0x1x`）  `bytes_handler=byte_handler(语法层)`
            登录门（`0x05`）  `login=login_handler(语法层)`

        **三扇门拿的是同一份语法层**，也就是同一个库。这里不用再插一手。

        以前字节门不在这条线上：套接层自己向语法层借一个 `Kernel`，那个
        物件持着 Arena、直接打存储引擎——是唯一一条绕过语法层的路。现在
        它也在这一层（输入输出层的字节门），走 `Syntax.put/get/scan`。

        **库里一个用户都没有就拒服务。** 没有用户 = 没人能登录 = 谁先连上
        谁就是管理员。宁可它不开端口，也不要它开着端口等人来抢第一个
        账号。真漏了这一步的部署，提示摆在这儿：先在本机用界面开一次库、
        把管理员设好，再来起服务。

        **不在命令行传口令**给一个"没有用户就现建一个"的开关：那种口令
        会落在 shell 历史里，而且等于把抢管理员的窗口从"库刚建好那一下"
        拉长成"每次起服务的那一刻"。
        """
        if self._closed:
            raise RuntimeError('内核已经停了，起不了服务')
        if self._storage is None:
            raise RuntimeError(
                '这是连进来的内核，库在对面——那边已经是一个服务了，'
                '这边起不了第二个')
        if self._svc is not None:
            raise RuntimeError('服务已经起了，端口 %d' % self._svc.port)
        if not self._storage.有用户():
            raise RuntimeError(
                '这个库里一个用户都没有，不能起服务——**没有用户就是谁都'
                '能当管理员**，端口一开，第一个连上来的就给自己发一个。'
                '先在本机把库打开、设好初始管理员（界面上会要求设），'
                '再来起服务')
        # 先起来，再扔掉手上那个闸口——**扔，不是关**：`Gate.close()` 一路
        # 走到 `Storage.close()`，那会把库关掉，而这里正要把同一个库交给
        # 服务端。起不来的话（端口被占之类）闸口还在原处，接着用没事。
        svc = io_mod.serve_storage(self._storage, host, port, 门皮=门皮)
        self._gate = None
        self._svc = svc
        return svc

    def 停(self):
        """
        关掉整个内核：**服务先停、库后关**。可以重复调，第二次什么都不做。

        反过来的次序（先关库）会让正连着的客户端往一个已经关掉的库发请求，
        那些请求会以各种看不懂的样子失败——这个次序在 `Service.close` 里，
        这里只是照它走。
        """
        if self._closed:
            return
        self._closed = True
        svc, self._svc = self._svc, None
        gate, self._gate = self._gate, None
        if svc is not None:
            svc.close()          # 服务先停、库后关，都在这一句里
        elif self._storage is not None:
            self._storage.close()
        elif gate is not None:
            # 远程腿：**只关这一条 socket**。盘在对面那个进程手里，这边
            # 一个字节都碰不到，也就没有"把别人的库关了"这回事。
            gate.close()

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self.停()


# 模块这一层的口子：`龙龟之心.开('x.db')`。**不是转发壳子**——同一对函数
# 对象，不在两个地方各写一遍，改不动第二处。
开 = 内核.开
建 = 内核.建
连 = 内核.连
