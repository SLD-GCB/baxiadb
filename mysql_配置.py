# -*- coding: utf-8 -*-
"""
mysql_配置.py — MySQL 兼容口**从配置里怎么读**。

这个文件以前是 `霸下-mysql.conf` 的读写。**那个文件已经并进 `配置.py`
了**（设置页第 5 页那一节 MySQL），现在这儿一点文件 IO 都没有——只剩下
一组函数，把 `配置.py` 那份值翻成 `mysql_门` 要的形状。

为什么不并进 `配置.py`
======================

`配置.py` 管的是**这份值长什么样、合不合法、怎么存**。这里管的是
**服务层怎么读它**——两件事的变化理由完全不同：

    `配置.py`    加一个键、改一次校验、换一种存法
    这里         服务层要多看哪一个数、某个数缺省时当成什么

而且这一层的缺省值**必须在这儿给**：`配置.py` 的 `默认值()` 是"用户
什么都没配"的意思，但服务层要的是"这一格空着的时候我按什么跑"。两件事
平时给出同一个答案，**改配置的时候才不是**。

⛔ 一处说一件事：键名只认 `配置.py` 的
========================================

这一版起键名**就是 `MySQL` 打头的那十个**（`MySQL监听地址`、`MySQL账号`
……），和 `配置.py` 的 `_表` 一个字都不差。**这儿不许再起一套短名字。**

上一版踩过这个：`配置.py` 那边叫 `开机听MySQL`，另一个文件里叫 `监听地址`
——同一件事两个名字、又没定谁压谁，迟早在"改了这个没生效、因为那个不一样"
上花掉一个下午，而那时候两边各自看着都是对的。

⚠️ 账号映射那张表里**一个口令都不存**
======================================

映射只有一列：MySQL 用户名 → 霸下账号。口令由客户端（爬虫）连的时候填，
明文经 `mysql_clear_password` 交上来，**转手交给霸下自己的 pbkdf2 去判**
（`mysql_门.py` 握手那段有完整流程）。所以：

  * 这一层没有任何地方需要口令，也就没有任何地方会存它；
  * 在这一格里写 `口令` / `密码` 是**一个不会生效的字段**，而写它的人
    一定以为它生效——`配置._校验账号表` 会当众把它拒掉，那不是洁癖。
"""

from __future__ import annotations

__all__ = ['监听地址', '默认库', '耗时日志秒',
           '账号映射', '允许来源', '允许连', '攒批参数']


# ══ 单个标量：缺省值在这儿给 ═══════════════════════════════════════════

def 监听地址(值):
    """
    MySQL 口绑哪张网卡。

    **缺省 127.0.0.1，不是 0.0.0.0。** 这条不是随手填的：登录走的是
    `mysql_clear_password`，**口令在网线上是明文**。绑到 0.0.0.0 就等于
    把一个能拿到明文口令的口敞到网上。
    """
    return (值.get('MySQL监听地址') or '127.0.0.1').strip()


def 端口(值):
    """MySQL 口听哪个端口。缺省 3306——爬虫把它写死了（`config_gui.py:201`）。"""
    try:
        return int(值.get('MySQL端口') or 3306)
    except (TypeError, ValueError):
        return 3306


def 默认库(值):
    """客户端没报库名时用哪个库。空串 = 必须报。"""
    return (值.get('MySQL默认库') or '').strip()


def 耗时日志秒(值):
    """超过这个秒数的语句记一条。**0 = 每条都记。**"""
    try:
        return float(值.get('MySQL耗时日志秒') or 0)
    except (TypeError, ValueError):
        return 0.0


# ══ 账号映射 ═══════════════════════════════════════════════════════════

def 账号映射(值):
    """
    `{MySQL 用户名: 霸下账号}`——摊平之后的形状。

    服务层每次建连都要查一次"这个用户名对应哪个霸下账号"，不该每次去拆
    一层 dict，所以在这一处摊平。

    **键原样，不做大小写折叠。** MySQL 的用户名是区分大小写的，而"顺手
    lower 一下"会让 `Spider` 和 `spider` 两条规则悄悄打起来——谁赢取决于
    dict 的插入次序，而那个次序在 JSON 里不保证。

    ⛔ **表是空的时候回空表 = 谁也不许连。** 不是"谁都放进来"——那两件事
    差着一整个安全边界，而看起来只差一个 `if`。
    """
    出 = {}
    for 名, 项 in (值.get('MySQL账号') or {}).items():
        if isinstance(项, dict) and isinstance(项.get('霸下账号'), str):
            出[名] = 项['霸下账号']
    return 出


# ══ 来源白名单 ═════════════════════════════════════════════════════════

def 允许来源(值):
    """白名单，一串 IP 字面量。空名单 = 谁也不许连。"""
    return [x for x in (值.get('MySQL允许来源') or [])
            if isinstance(x, str) and x]


def 允许连(值, 地址):
    """
    这个来源地址许不许连。

    ⛔ **空名单是"谁也不许"，不是"谁都可以"。** 反过来（空=全放行）的
    写法看起来更"方便"，但它的失败方式是把一个监听口无条件敞到网上，
    而配的人以为自己什么都没配、是安全的。**默认必须是关的。**

    ⚠️ 比的是**地址原样**，所以写主机名、写 `192.168.1.0/24` 都匹配不上。
    这件事在 `配置.校验` 那边就拦住了（那一项必须是 IPv4 字面量），不留
    到这儿变成"爬虫就是从 127.0.0.1 来的，怎么连不上"。
    """
    return 地址 in 允许来源(值)


# ══ 攒批 ═══════════════════════════════════════════════════════════════

def 攒批参数(值):
    """
    `(条数, 字节, 秒)`——攒批的三个阈值。

    **字节在这儿换成数**：配置那一页摆的是 MB（`配置.py` 第三条规矩：
    字节一律换成 MB 摆），服务层要的是字节。
    """
    try:
        条数 = int(值.get('MySQL批条数') or 512)
    except (TypeError, ValueError):
        条数 = 512
    try:
        字节 = int(float(值.get('MySQL批字节MB') or 8.0) * 1024 * 1024)
    except (TypeError, ValueError):
        字节 = 8 << 20
    try:
        秒 = float(值.get('MySQL批等待秒') or 0.5)
    except (TypeError, ValueError):
        秒 = 0.5
    return (条数, 字节, 秒)
