#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
玄武_画.py — 画：认手法，不认 IP

**六台里最不危险的一台，也是最先该做的一台。** 它不看来源、不碰真库、
不拦任何人，只回答一个问题：

    这一手**长得像什么**？

答案是 `一手.手法` —— 一列短标签（`['元数据探测', '联合注入', '像 sqlmap']`），
空的就表示"看不出什么"。

判词不是它的事
==============

`手法` 和 `判词` 是**两格**，别搅在一起。画**从不写判词**，它没有那个权力
—— 唯一的判决点是 `门`。画认出"这是 sqlmap"也不代表要拒：**认出来是为了
记住他**（计划 §三·二 那张表：画的"说不"的后果是"记进画像，下次直接认
出来"），不是当场翻脸。

⚠ 但 `城` 把画归在 `判的台` 里（`玄武_城.判的台`）—— 那是**按计划 §三·三
分的类**，不是按"它判不判事"分的。后果要认在明处：**画自己抛异常 = 整条
流水线判成断**（fail-closed）。所以这个文件里**一次 I/O 都没有、一次锁
都没有、一次回调都没有** —— 它就是一堆编译好的正则加几次字典查找，
唯一能抛的东西是"正则写错了"，而那是启动时就该炸的。

不认 IP
=======

画只看**请求长什么样**。同一个 IP 换工具就换手法，换个 IP 使同一把工具
还是同一个手法 —— 这正是 IP 挡不住的地方（肉鸡是别人的、会换）。

为什么要攒状态
==============

单看一句 SQL，"他是不是在拖库"看不出来 —— `翻页 偏移=256` 这一句本身
干干净净。是**同一个会话一直翻**才成了拖库。所以画手里有一张按会话号
记的小表（翻页数 / 见过几种手法）。

**那张表丢得掉**：它完全能从账本推出来（账上每一手都带着会话号和手法），
所以它不落盘、重启就重数 —— 见 `baxia-derived-state-must-be-droppable`。
而且它**必须有上限**：那是攻击者能刷的东西。
"""

from __future__ import annotations

import re

__all__ = ['画', '画台', '认得的手法']

# ══ 一、认什么 ═════════════════════════════════════════════════════════
#
# 每条都是 `(标签, 正则)`。**正则一律编在模块级** —— 画是每一手都要跑的
# 那一台，在热路上 `re.compile` 是白扔钱。
#
# 全部只在**小写化之后的文本**上匹配，所以正则里不写大写。

#: 一句 SQL 里出现的特征。顺序无关紧要（结果是排序去重的标签）。
#: 这一份是**原文**，底下 `_特征` 才是编好的 —— 拆成两截是为了让下面这些
#: 多行拼接的写法读得出来，而不是每一行外面套一层 `re.compile(`。
_特征原 = (
    # ── 看家底 ──────────────────────────────────────────────────
    ('元数据探测', r'information_schema|pg_catalog|sqlite_master'
                   r'|sys\.(?:tables|columns|objects)'),
    ('列表名', r'\bshow\s+(?:tables|databases|columns|full\s+tables)\b'
               r'|\bdescribe\b|\bdesc\s+[`"]?\w'),
    ('探版本', r'@@version|@@datadir|@@basedir|version\s*\(|database\s*\('
               r'|current_user|system_user|user\s*\(\s*\)'),
    # ── 注入的几条路 ────────────────────────────────────────────
    ('联合注入', r'\bunion\s+(?:all\s+)?select\b'),
    ('布尔盲注', r'\b(?:and|or)\s+(?:not\s+)?[\w\'"(@]+ *[=<>!]'
                 r'|\b(?:ord|ascii|mid|substr|substring|left|right|char)\s*\('),
    ('时间盲注', r'\bsleep\s*\(|\bbenchmark\s*\(|\bwaitfor\s+delay\b'
                 r'|\bpg_sleep\s*\(|\bdbms_lock\.sleep\b'),
    ('报错注入', r'\bextractvalue\s*\(|\bupdatexml\s*\(|\bexp\s*\(\s*~'
                 r'|\bfloor\s*\(\s*rand\s*\(|\bgeometrycollection\s*\('),
    ('排序探测', r'\border\s+by\s+\d+|\bgroup\s+by\s+\d+'),
    # ── 越界的手 ────────────────────────────────────────────────
    ('读文件', r'\bload_file\s*\(|\binto\s+(?:out|dump)file\b'
               r'|\bload\s+data\s+(?:local\s+)?infile\b'),
    ('命令执行', r'\bxp_cmdshell\b|\bsp_executesql\b|\bsys_eval\b'
                 r'|\bsp_oacreate\b|\blo_import\b'),
    ('改盘', r'\binto\s+outfile\b|\bdrop\s+(?:table|database)\b'
             r'|\btruncate\s+table\b|\balter\s+table\b'),
    # ── 混淆 ────────────────────────────────────────────────────
    ('注释障眼', r'/\*!|/\*.*?\*/|--[ \t]|#[ \t]*$'),
    ('十六进制', r'0x[0-9a-f]{6,}'),
    ('字符编码', r'\bchar\s*\(\s*\d+\s*(?:,\s*\d+\s*)+\)'
                 r'|\bconcat\s*\(\s*0x'),
    ('空白异常', r'[ \t]{8,}|\n\s*select'),
)

#: **编好的那一份。** 上面那两条注释说的"编在模块级"落在这儿 ——
#: `_特征` / `_工具` 后面每一个使用者拿到的都是 `re.Pattern`，
#: 谁也别再拿原文去 `.search()`。
#: ⛔ **编在模块级 = 正则写错了在 `import` 的时候就炸**，这正是要的：
#: 画是判的台，它要是启动之后才发现自己认不出东西，那一手已经被判成
#: `断` 发下去了。
_特征 = tuple((标, re.compile(正)) for 标, 正 in _特征原)

#: 一串特征凑够几条，才敢说"这是一把自动化工具"。
#: **单条不算**：`--` 是注释也是正常 SQL；`@@version` 可能是运维在排查。
_工具线 = 3

#: 自动化工具的招牌。命中就单独加一个标签，**和上面那些手法并列**。
_工具原 = (
    ('像 sqlmap', r'/\*!\d{5}.*?\*/'),
    ('像 sqlmap', r'\band\s+ord\s*\(\s*mid\s*\('),
    ('像 sqlmap', r'\bunion\s+select\s+1\s*,\s*2\s*,\s*3'),
    ('像 nmap', r'\bmysql\s+--|\bshow\s+variables\b'),
)

#: 编好的那一份，同 `_特征`。
_工具 = tuple((标, re.compile(正)) for 标, 正 in _工具原)

# ⛔ **这儿原来有一个 `_字典特征 = '字典爆破'`，2026-09-14 删掉了。**
#
# 它原来的用法是 `__call__` 里那句 `if 类 == '登录': 标.add(_字典特征)`
# —— **成败都打**。于是每一次正经登录（包括每一次成功的）都顶着
# "字典爆破"这四个字进账，满屏都是它。而这一格上面原写着「同一份字典
# 打过来，长度会撞在一起」—— 那件事代码里**一行的实现都没有**：
# 画从来没数过口令长度、也没比过长度。**说明在说一件没发生的事。**
#
# 也想过改成"同一会话里失败的登录攒够几次再打"，**数不成**：画的会话号
# 是**连接号**（`玄武_门` 那边一个连接一个号），而爆破多半是开一堆连接、
# 一户试一下，一个会话里根本攒不够。真数得出来的是 `门` —— 它按
# **来源**（IP）记失败次数，够 `玄武失败阈值` 就拉黑 `玄武拉黑秒`，
# 而"换连接、不换 IP"正是爆破本来的样子。
#
# 所以这一格**不是"还没做"，是"不该由画做"**：画的活儿是认**手法**
# （这一句长得像什么），爆破是**次数**的事。两样都在账上，各有各的台，
# 判词仍然只有 `门` 一个出口。


def _正(值, 默认):
    """
    取一个"至少是 1 的正整数"。**没配过（`None`）就用默认**，
    其余一律夹到 1 以上。

    ⛔ **判据是 `is not None`，不是 `or`。** 四把尺子的配置下限都是 1，
    所以今天 `0` 走不到这儿；但 `0 or 默认` 这个写法埋着一句话：
    "0 和没配过是一回事"。哪天下限松到 0，人要的就是 `1`（夹到下限），
    而不是**悄悄换成默认值** —— 那正是"改了配置不生效"的形状。

    **四把尺子共用这一个** —— 抄四遍就是四处会分岔，而分岔的样子是
    "改了一格、另一格没跟上"。这个文件里每条配置都是这个形状。
    """
    try:
        return max(1, int(默认 if 值 is None else 值))
    except (TypeError, ValueError):
        return 默认


def _文本(手):
    """
    把 `一手.请求` 里能看的东西拼成一段小写文本。**只读，不改，不记。**

    `请求` 的形状随事件类变：查/写是 `{'语句': …}`，翻页是
    `{'表': …, '列': …}`，登录是 `{'账号': …}`，也可能是 `None`。所以
    这儿一律 `str()` 之后拼 —— **宁可少认，不能抛**。
    """
    请 = getattr(手, '请求', None)
    if 请 is None:
        return ''
    if isinstance(请, str):
        return 请.lower()
    if isinstance(请, dict):
        块 = []
        for k in ('语句', '表', '列', '其中', '账号', '参数', '语句们'):
            v = 请.get(k)
            if v is None:
                continue
            块.append(v if isinstance(v, str) else repr(v))
        return ' '.join(块).lower()
    return str(请).lower()


# ══ 二、画 ═════════════════════════════════════════════════════════════

class 画(object):
    """
    认手法的台。**一个可调用，收 `一手`，填 `一手.手法`。**

    参数：

        `开`   关掉就什么都不做（`手法` 留空）。**默认开** —— 它不改一个
               请求的去向，关掉它省下的只有"看不见"。
        `说`   记一句话的回调。
        `上限` 按会话号攒的那张小表最多记几笔。**必须有**，见 `_会话`。
        `工具线` / `拖库翻页` / `批量灌手数` / `多手法数`
               四把尺子，全部来自 `配置.py`「城防·画」那一组。它们**只决定
               打哪个标签**（标签进了账，人看着办），**不决定任何一个请求
               的去向** —— 所以改宽改窄都伤不到正经用户。

    填的 `手法` 是一个**排过序、去过重**的列表：同一次判断同样输入必然
    同样输出（账本要比对，不能这一遍一个样）。看不出什么就是 `[]` ——
    **空列表不是 `None`**：`None` 是"没判"，空列表是"看了，没看出来"。
    """

    def __init__(self, 开=True, 说=None, 上限=4096, 工具线=_工具线,
                 拖库翻页=8, 批量灌手数=4, 多手法数=4):
        self._开 = bool(开)
        self._说 = 说 or (lambda 文: None)
        try:
            self._上限 = max(64, int(上限 or 4096))
        except (TypeError, ValueError):
            self._上限 = 4096
        # 四把尺子。**默认值照抄模块常量**：不传就还是"以前那个数"，
        # `造画台` 传了才跟着配置走。
        #
        # ⛔ **属性名不带下划线，是故意的。** 模块顶上那几个常量叫
        # `_工具线`，而方法体里写 `_工具线` 指的是**模块那个**、不是实例
        # 这个。属性名要是也起成 `_工具线`，`__call__` 里漏改一句
        # **不会报错，会静默地用回模块常量** —— 界面上改了、账上没变。
        # 名字分得开，漏改就是 `AttributeError`，当场响。
        self.工具线 = _正(工具线, _工具线)
        self.拖库页 = _正(拖库翻页, 8)
        self.灌手数 = _正(批量灌手数, 4)
        self.多手法 = _正(多手法数, 4)
        #: 会话号 -> `{'翻页': n, '手数': n, '手法': set()}`
        #: ⛔ **只涨不落的东西必须封顶** —— 见 `_翻账`。
        self._账 = {}

    # ── 那一手 ──────────────────────────────────────────────────────

    def __call__(self, 手):
        if not self._开:
            # ⛔ **关掉就得真的关掉。** 早先这一句只在 `_翻账` 里回了个
            # 假账本（`{'翻页': 0, '手数': 0, '手法': set()}`），而上面
            # 那几圈正则**照跑**、底下 `手.手法 = sorted(标)` **照填** ——
            # 于是 `玄武画像` 这一格关掉之后，账上照样满是指纹标签，只是
            # 拖库 / 批量灌数据 / 多手法试探那三条按会话算的标签不再出现。
            # 人看着"关了"，账上看不出关过。
            #
            # 这一格的 docstring 写的正是「关掉就什么都不做（`手法` 留空）」，
            # 所以判据不用另立：**这一格就是那句 docstring**。
            # 留 `None` 不填空列表 —— `None` 是"没判"，`[]` 是"看了，没看
            # 出来"，这两件事在这一层分得开（类 docstring 最后一段）。
            return getattr(手, '手法', None)

        文 = _文本(手)
        类 = getattr(手, '类', '') or ''
        标 = set()

        for 标签, 正 in _特征:
            if 正.search(文):
                标.add(标签)

        # 特征凑够几条 —— 才敢说这是一把工具在跑，不是人在敲。
        if len(标) >= self.工具线:
            标.add('像工具')
        for 标签, 正 in _工具:
            if 正.search(文):
                标.add(标签)

        # 「登录类事件无条件打『字典爆破』」那一句在这儿，2026-09-14 删了。
        # 理由写在文件顶上 `_字典特征` 原来那一格的位置 —— 一句话：
        # **成败都打，是个假标签；而真的爆破计数归 `门` 管。**

        记 = self._翻账(getattr(手, '会话号', 0), 类)
        # 拖库：**同一会话翻够多次**才叫拖库。单看一页干干净净。
        if 记['翻页'] >= self.拖库页:
            标.add('拖库')
        if 类 in ('灌', '批写') and 记['手数'] >= self.灌手数:
            标.add('批量灌数据')
        记['手法'] |= 标
        # 一会儿换一个手法 = 在试，不是在用。
        if len(记['手法']) >= self.多手法:
            标.add('多手法试探')

        手.手法 = sorted(标)
        return 手.手法

    # ── 按会话攒的那张小表 ──────────────────────────────────────────

    def _翻账(self, 号, 类):
        """
        取（没有就建）这个会话那一笔，顺手把"手数 / 翻页数"加上。

        ⛔ **封顶这一条不能省。** 这张表的键是**会话号**，而会话号是
        **攻击者刷出来的**：他开十万条连接，这儿就长十万笔，而它一笔都
        不会自己消失（`关会话` 那条路**不经过画** —— 画只在有请求的手上
        被叫，一条连进来什么都不干的连接根本叫不到它）。那就是一份由对手
        决定大小的内存。

        满了就丢**最早进来的那一个**（dict 记着插入次序，弹第一个）。
        丢掉的代价只是"那个会话的翻页数重新数"—— 这张表本来就是**能把
        从账本重推出来的派生状态**，丢得掉是它的设计前提，不是妥协。

        ⚠ 这里**不再自己判 `_开`**：关掉的那条路在 `__call__` 头一句就
        返回了（连这一句都不该走到），两个地方各判一次就是两处会分岔 ——
        而分岔的样子正是"关掉之后还在悄悄数"。
        """
        记 = self._账.get(号)
        if 记 is None:
            if len(self._账) >= self._上限:
                self._账.pop(next(iter(self._账)), None)
            记 = self._账[号] = {'翻页': 0, '手数': 0, '手法': set()}
        记['手数'] += 1
        if 类 == '翻页':
            记['翻页'] += 1
        return 记

    def 报数(self):
        return {'开着': self._开,
                '记着的会话数': len(self._账),
                '上限': self._上限,
                '工具线': self.工具线,
                '拖库翻页': self.拖库页,
                '批量灌手数': self.灌手数,
                '多手法数': self.多手法,
                '特征条数': len(_特征)}


# ══ 三、造型 ═══════════════════════════════════════════════════════════

def 认得的手法():
    """
    认得出的手法标签有哪些。**给界面和排错看，也是这个文件的自述。**

    ⚠ **这张表里没有"字典爆破"，是有意的**（2026-09-14 删的，理由见
    文件顶上那一段）。这一份是"画能说出什么"的清单，不是"玄武能发现
    什么"——爆破、拉黑那些在 `门` 那边，别把它塞回这张表里，
    否则这张表就从"自述"变成了"许愿"。
    """
    标 = set(标签 for 标签, _ in _特征)
    标 |= set(标签 for 标签, _ in _工具)
    标 |= {'像工具', '拖库', '批量灌数据', '多手法试探'}
    return sorted(标)


def 造画台(值=None, 说=None):
    """
    造一台画，给 `城.登记('画', …)` 用。

    读的配置键全在 `配置.py`「城防·画」那一组：**`玄武画像`**、
    `玄武画像上限`、`玄武工具线`、`玄武拖库翻页`、`玄武批量灌手数`、
    `玄武多手法数`。**一个数都不在这儿另抄** —— 抄一份就是两处会分岔，
    而这一处分岔的样子是"界面上写着 5 页算拖库、账上还是按 8 页算"。
    """
    值 = 值 or {}
    return 画(开=bool(值.get('玄武画像', True)), 说=说,
              上限=值.get('玄武画像上限'),
              工具线=值.get('玄武工具线'),
              拖库翻页=值.get('玄武拖库翻页'),
              批量灌手数=值.get('玄武批量灌手数'),
              多手法数=值.get('玄武多手法数'))


#: 兼容 `玄武_门.造门台` 那个叫法。
画台 = 造画台
